/*
 * 01_认识函数.c —— 阶段2 / 第 01 课 / 第 01 个文件：认识函数
 *
 * 编译：gcc -std=c99 -Wall -Wextra 01_认识函数.c -o bin/01_认识函数
 * 运行：./bin/01_认识函数
 *
 * 本篇只回答一个问题：**函数到底是什么，一次调用发生了什么。**
 * 具体的定义语法、参数规则、原型与多文件、递归、作用域，分别放在 02–06 篇。
 *
 * 阶段1 里其实已经在用函数了（main、printf、还有那些 static 小函数），
 * 只是当时把它们当成"现成的工具"。从这一课开始，把函数本身当成研究对象。
 *
 * ====================== 一、为什么需要函数 ======================
 * 假设要算三组数据的和，每组逻辑一模一样：
 *
 *      int s1 = 0;
 *      for (int i = 0; i < n1; i++) s1 += a1[i];
 *      int s2 = 0;
 *      for (int i = 0; i < n2; i++) s2 += a2[i];
 *      int s3 = 0;
 *      for (int i = 0; i < n3; i++) s3 += a3[i];
 *
 * 问题不在"能写"，而在：
 *
 *  1) 重复 —— 逻辑改了要改三处，漏一处就是 bug
 *  2) 没有名字 —— 读代码的人得先看懂循环，才知道这是"求和"
 *  3) 无法单独测试 —— 想验证求和逻辑，只能整段跑
 *
 * 函数就是解决这三件事的最小工具：**给一段逻辑起个名字，固定它的输入输出。**
 *
 *      int sum(const int *a, int n) { ... }        定义一次
 *      sum(a1, n1);  sum(a2, n2);  sum(a3, n3);    到处调用
 *
 * 一句话：**函数 = 可复用的、有名字的一段代码，带明确的输入和输出。**
 *
 * ====================== 二、函数的四个组成部分 ======================
 *
 *      int  sum (const int *a, int n)
 *      ─┬─  ─┬─  ────────┬────────
 *       │    │           └─ 形参列表：输入是什么（可以没有）
 *       │    └─ 函数名：以后靠这个名字调用
 *       └─ 返回类型：输出是什么（不需要输出就写 void）
 *
 *      {                       ← 函数体：真正干活的地方
 *          int s = 0;
 *          ...
 *          return s;           ← 把结果交回调用点
 *      }
 *
 * 四件事想清楚，函数就写对了：
 *
 *      它叫什么名字？      → 见名知意，动词开头：sum、print_line、is_even
 *      它要什么输入？      → 参数列表，没有就写 (void)
 *      它给什么输出？      → 返回类型，没有就写 void
 *      它内部怎么算？      → 函数体，外部不需要知道
 *
 * 最后一条尤其重要：**调用者只关心"输入什么、得到什么"，不关心内部实现。**
 * 这就是"抽象"—— 和 printf 一样，你不用知道它怎么格式化，只知道它能打印。
 *
 * ====================== 三、main 也是一个函数 ======================
 *      int main(void) { ... return 0; }
 *
 * 它和普通函数没有本质区别，只是**由运行时启动代码调用**，而不是你调用：
 *
 *      操作系统 → 启动代码（crt0）→ main → return → 退出码传回操作系统
 *
 * 所以：
 *
 *  - `return 0;` 的 0 是**退出码**，不是"给谁看的数据"。
 *    约定 0 表示成功，非 0 表示失败（`echo $?` 能看到）。
 *  - 一个程序**有且只有一个** main，它是入口，不能被别的函数调用（标准不允许）。
 *  - main 也可以带参数：`int main(int argc, char **argv)`，
 *    用来接收命令行参数（阶段1 第 06 课第 05 篇讲过 argv 的类型）。
 *
 * ====================== 四、一次调用发生了什么 ======================
 * 这是本篇最重要的一段。调用 `sum(data, 5)` 时，机器实际做了四步：
 *
 *      1) 把实参的值复制到"形参"的位置（值传递，见 03 篇）
 *      2) 记下"回来的时候接着执行哪一行"（返回地址）
 *      3) 在栈上开一块空间给这次调用（叫**栈帧**），放形参和局部变量
 *      4) 跳到函数入口开始执行
 *
 * 函数执行到 return 时，反向再做一遍：
 *
 *      5) 把返回值放到约定的位置
 *      6) 销毁这次调用的栈帧（局部变量随之消失）
 *      7) 按返回地址跳回调用点，继续往下走
 *
 * 画成图（栈从高地址向低地址增长，这里只示意"一层层叠上去"）：
 *
 *      ┌──────────────┐
 *      │  main 的栈帧  │   data、n、s 等局部变量
 *      ├──────────────┤
 *      │  sum 的栈帧   │   形参 a、n，局部 s、i
 *      └──────────────┘   ← 栈顶，sum 返回后这块立即作废
 *
 * 三句话记住：
 *
 *  - **函数调用是有成本的**：压栈、跳转、返回，都是指令。
 *  - **局部变量是"这一层"的**：函数返回后它就没了（所以不能返回局部变量地址）。
 *  - **递归为什么能工作**：每次调用都有自己的栈帧，互不干扰（05 篇细讲）。
 *
 * ====================== 五、三类函数 ======================
 *  (1) 库函数：别人写好、你 #include 就能用
 *          printf / scanf / strlen / malloc ...
 *      它们不是"语言的一部分"，而是标准库提供的；用之前要包含对应的头文件，
 *      头文件里放的就是**函数原型**（04 篇详讲）。
 *
 *  (2) 自定义函数：你自己写的
 *          本例里的 add、print_line、sum
 *
 *  (3) main：程序入口，特例（第三节）
 *
 * ====================== 六、函数的好处与代价 ======================
 *  好处：
 *      - 复用：写一次，到处调用
 *      - 可读：sum(a, n) 比一段循环更能表达意图
 *      - 可测试：单独喂输入、单独验输出
 *      - 可分工：多人各写各的函数，靠接口对接
 *      - 便于优化：小函数可能被内联，消除调用开销
 *
 *  代价：
 *      - 调用有开销（压栈、跳转），极热点的微函数可能不如直接写
 *      - 拆得太碎反而难读：**函数应该按"一件事"划分，不是按行数划分**
 *
 * ====================== 七、C 的函数和其他语言不一样的地方 ======================
 *  - 没有**重载**（同名不同参数不行），要用不同名字：sum_int / sum_double
 *  - 没有**默认参数**，参数个数固定
 *  - 没有**嵌套定义**（函数里不能再定义函数），但可以调用
 *  - 没有闭包、没有 lambda；想让"函数当参数传"，只能用**函数指针**
 *    （阶段1 第 06 课第 04 篇）
 *  - 参数**永远是值传递**，想让函数改外部变量必须传地址（03 篇）
 *
 * ====================== 八、常见误区 ======================
 *  1. 以为 main 很特殊、不能返回       main 就是函数，return 0 是退出码
 *  2. 以为函数能改实参                C 是值传递，改的是副本
 *  3. 在函数里再定义函数              C 不允许嵌套定义
 *  4. 忘了 return                    非 void 函数走到末尾是未定义行为
 *  5. 把"函数应该很长"当中级水平       好函数通常短、只做一件事
 *  6. 名字用拼音或 a1/a2              见名知意比省字符更重要
 *  7. 以为调用没有成本                递归太深就是栈溢出（05 篇）
 *
 * ====================== 九、实践建议 ======================
 *  - 一个函数只做一件事，能用一句话说清它的职责
 *  - 名字用动词开头：sum / print / is_even / find_max
 *  - 输入输出写进签名，别用全局变量偷偷传数据
 *  - 不修改的参数加 const（阶段1 第 06 课第 01 篇讲过）
 *  - 函数超过一屏就该想想能不能拆
 *  - 先写调用（想清楚怎么用），再写实现，接口往往更合理
 */

#include <stdio.h>
#include <string.h>

/* ---- 一个最小的函数：两个 int 进，一个 int 出 ---- */
static int add(int a, int b)
{
    return a + b;
}

/* ---- void 函数：只干活，不返回结果 ---- */
static void print_line(void)
{
    printf("   ------------------------------\n");
}

/* ---- 有输入、无输出：打印但不给结果 ---- */
static void print_sum(int a, int b)
{
    printf("   %d + %d = %d\n", a, b, a + b);
}

/* ---- 阶段1 反复出现的形状：数组 + 长度 ----
 * 传数组其实就是传首地址，所以长度必须另外给（阶段1 第 06 课第 01/02 篇讲过）
 */
static int sum(const int *a, int n)
{
    int s = 0;
    for (int i = 0; i < n; i++)
        s += a[i];
    return s;
}

/* ---- 用打印观察"调用顺序"：先进后出 ---- */
static void inner(void)
{
    printf("   [inner] 进入\n");
    printf("   [inner] 退出\n");
}

static void outer(void)
{
    printf("   [outer] 进入\n");
    inner();                        /* 在函数里调用另一个函数 */
    printf("   [outer] 退出\n");
}

int main(void)
{
    /* ---------- 1. 定义一次，调用多次 ---------- */
    printf("1. 定义一次，调用多次\n");
    print_line();
    printf("   add(1, 2) = %d\n", add(1, 2));
    printf("   add(10, 20) = %d\n", add(10, 20));
    printf("   add(-5, 3) = %d\n", add(-5, 3));
    printf("   同一段逻辑只写了一遍，靠参数产生不同结果\n");

    /* ---------- 2. 函数的四个组成部分 ---------- */
    printf("2. 一个函数由「返回类型 + 名字 + 形参列表 + 函数体」组成\n");
    printf("   int add(int a, int b) { return a + b; }\n");
    printf("   int  → 给什么输出；add → 叫什么；a, b → 要什么输入\n");
    printf("   调用者只关心这几样，不关心函数体里怎么算的\n");

    /* ---------- 3. void：没有返回值 ---------- */
    printf("3. void 表示「没有返回值」，但仍然可以有参数\n");
    print_line();
    print_sum(3, 4);
    print_line();
    printf("   注意 (void) 表示「没有参数」，不能省成 ()（C 里 () 是「参数未知」）\n");

    /* ---------- 4. 函数里调用函数 ---------- */
    printf("4. 函数可以调用别的函数：先进后出\n");
    outer();
    printf("   调用顺序是 main → outer → inner，回来时反过来 inner → outer → main\n");

    /* ---------- 5. 数组参数：为什么要多传一个 n ---------- */
    printf("5. 数组作参数会退化成指针，所以长度必须另外传\n");
    int data[5] = {3, 1, 4, 1, 5};
    printf("   sum(data, 5) = %d\n", sum(data, 5));
    printf("   函数里用 sizeof(data) 得到的是 %zu（指针大小），不是 20\n",
           sizeof(const int *));

    /* ---------- 6. main 也是函数 ---------- */
    printf("6. main 也是函数，return 0 是退出码\n");
    printf("   main 由运行时启动代码调用，返回值交给操作系统\n");
    printf("   0 表示成功，非 0 表示失败；一个程序有且只有一个 main\n");
    printf("   main 也能收参数：int main(int argc, char **argv)\n");

    /* ---------- 7. 库函数 vs 自定义函数 ---------- */
    printf("7. 库函数和自定义函数用法一样，区别只是「谁写的」\n");
    const char *s = "hello";
    printf("   strlen(\"%s\") = %zu    ← 库函数（需要 #include <string.h>）\n",
           s, strlen(s));
    printf("   sum(data, 5) = %d      ← 自定义函数（本文件里定义）\n", sum(data, 5));

    /* ---------- 8. 小结 ---------- */
    printf("8. 小结：\n");
    printf("    函数 = 有名字的一段代码 + 明确的输入输出\n");
    printf("    组成：返回类型 名字(形参) { 函数体 }，没有输出写 void\n");
    printf("    调用 = 复制实参 + 记返回地址 + 开栈帧 + 跳过去，返回时反过来\n");
    printf("    局部变量属于当前这次调用，函数返回就没了\n");
    printf("    main 也是函数，return 0 是退出码\n");
    printf("    一个函数只做一件事，名字要见名知意\n");

    return 0;
}

