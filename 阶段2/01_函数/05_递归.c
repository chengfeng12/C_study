/*
 * 05_递归.c —— 阶段2 / 第 01 课 / 第 05 个文件：递归
 *
 * 编译：gcc -std=c99 -Wall -Wextra 05_递归.c -o bin/05_递归
 * 运行：./bin/05_递归
 *
 * 递归是"函数调用自己"。它在语法上没有任何新东西 —— 难点全在**想清楚**：
 * 什么时候停、每次规模怎么变小。本篇用调用栈的视角把它拆开。
 *
 * 本文件不演示栈溢出（那会让程序直接崩），只在第 6 节用文字说明边界在哪。
 *
 * ====================== 一、递归是什么 ======================
 *      void f(void) { f(); }        // 语法合法，但会无限递归 → 栈溢出
 *
 * 递归函数和普通函数的唯一区别：函数体里**调用了自己**。
 * 而它成立的前提是：每次调用都比上一次"更接近终点"。
 *
 * ====================== 二、递归三要素（背下来） ======================
 *
 *  (1) **边界条件**（base case）：什么时候不再递归、直接返回
 *          if (n <= 1) return 1;
 *
 *  (2) **规模缩小**：每次调用必须让问题变小、且朝着边界走
 *          fact(n - 1)          // n 每次减 1，一定会撞到 n <= 1
 *
 *  (3) **调用自身**：用缩小后的问题表达原问题
 *          return n * fact(n - 1);
 *
 * 少任何一个都不行：
 *      缺边界 → 无限递归 → 栈溢出（段错误）
 *      不缩小 → 同上
 *      不调用 → 那就不是递归了，只是普通函数
 *
 * 写递归时先问自己三句话：
 *      "最小的情况是什么？"        → 边界
 *      "n 的情况能不能用 n-1 表示？" → 递推式
 *      "每次调用有没有更靠近边界？"  → 终止保证
 *
 * ====================== 三、一次递归调用在栈上是什么样 ======================
 * 以 fact(4) 为例，展开过程：
 *
 *      fact(4) = 4 * fact(3)
 *                    fact(3) = 3 * fact(2)
 *                                  fact(2) = 2 * fact(1)
 *                                                fact(1) = 1   ← 撞到边界
 *
 * 实际执行分两个阶段：
 *
 *      【递推】一路往下压栈，每层都没算完，都在等下一层的返回值
 *          fact(4) 栈帧 → fact(3) 栈帧 → fact(2) 栈帧 → fact(1) 栈帧
 *
 *      【回归】撞到底后一路返回，每层拿到结果才算出自己的值
 *          fact(1)=1 → fact(2)=2 → fact(3)=6 → fact(4)=24
 *
 * 所以递归的内存开销 = **递归深度 × 每层栈帧大小**。
 * 深度 10000 的递归就可能把默认 8MB 栈用光（每层几百字节）。
 *
 * 这也解释了 01 篇说过的：每次调用有独立栈帧，所以递归的每层
 * 形参、局部变量互不干扰 —— 这是递归能工作的根本原因。
 *
 * ====================== 四、经典例子 ======================
 *
 *  (1) 阶乘 —— 最标准的"递推 + 回归"
 *          long long fact(int n)
 *          {
 *              if (n <= 1) return 1;
 *              return n * fact(n - 1);
 *          }
 *      注意溢出：13! 已经超过 32 位 int，21! 超过 long long。
 *
 *  (2) 斐波那契 —— 反例，教会我们"递归不等于高效"
 *          fib(n) = fib(n-1) + fib(n-2)，边界 fib(0)=0, fib(1)=1
 *      朴素递归会**重复计算**：fib(5) 里 fib(3) 算了两遍，fib(2) 三遍……
 *      调用次数呈指数增长（fib(20) 需要两万多次调用）。
 *      正确写法是迭代，或加"记忆化"（缓存算过的结果）。
 *
 *  (3) 十进制转二进制 —— 递归天然处理"倒序输出"
 *          先递归处理 n/2，再打印 n%2
 *      因为递归的**回归顺序**正好是从高位到低位，比自己收集余数再反转更简洁。
 *
 *  (4) 汉诺塔 —— 递归思维的经典
 *          把 n 个盘子从 A 移到 C：
 *            ① 把上面 n-1 个从 A 移到 B（借助 C）
 *            ② 把最大的从 A 移到 C
 *            ③ 把 n-1 个从 B 移到 C（借助 A）
 *      移动次数 = 2^n - 1，n=64 时是 1.8e19 次 —— 递归写法优雅，
 *      但真要跑完是不可能的。
 *
 * ====================== 五、递归 vs 迭代 ======================
 *
 *      维度        递归                      迭代（循环）
 *      ----------  ------------------------  ----------------------
 *      可读性      贴合数学定义，短          需要自己想清楚状态
 *      性能        有调用开销，可能很慢      通常更快
 *      内存        深度 × 栈帧               常数
 *      风险        栈溢出                    基本没有
 *      适用        树/图/分治/回溯/天然递归  线性遍历、简单累加
 *
 * 经验法则：
 *
 *      - 问题本身是递归结构（树、分治、回溯）→ 用递归
 *      - 只是"重复做 N 次" → 用循环
 *      - 递归写出来更短但深度可能很大 → 优先循环
 *
 * ====================== 六、尾递归与栈溢出 ======================
 * 如果递归调用是函数的**最后一步**，且返回值直接返回：
 *
 *      int sum_to(int n, int acc)
 *      {
 *          if (n == 0) return acc;
 *          return sum_to(n - 1, acc + n);      // 尾调用
 *      }
 *
 * 理论上编译器可以把它优化成循环（复用同一个栈帧），叫**尾调用优化（TCO）**。
 *
 * ★ 但 C 标准**不要求**编译器做这个优化，GCC 在 -O2 下通常能做，
 *   不开优化就未必。所以：**别指望尾递归来避免栈溢出**，
 *   真要处理大规模数据，直接写循环。
 *
 * 栈溢出的典型现象：程序崩溃（Segmentation fault），
 * 常见于递归深度几千到几万时（取决于每层栈帧大小和系统栈上限）。
 *
 * ====================== 七、常见坑 ======================
 *  1. 忘了边界条件                无限递归 → 栈溢出
 *  2. 边界写错（n <= 1 vs n == 1） 少一层或多一层，可能死循环
 *  3. 规模没缩小                  fact(n) 里调 fact(n)，永远不结束
 *  4. 重复计算                   fib 朴素递归指数级爆炸
 *  5. 递归太深                   大数据量直接用循环
 *  6. 以为 C 一定做尾递归优化      标准不保证
 *  7. 在递归里用全局变量累加        多分支递归时会互相污染（需要用参数传状态）
 *  8. 递归函数返回局部变量地址      局部变量每层都有，返回即悬垂
 *  9. 忘了返回值                 非 void 递归函数漏 return → 未定义行为
 * 10. 递归和迭代混着写           读起来最累，选一种写清楚
 *
 * ====================== 八、实践建议 ======================
 *  - 先写边界，再写递推，最后检查"是否每次都更靠近边界"
 *  - 能用一句话说清"n 的答案怎么由 n-1 的答案得到"
 *  - 深度可能超过几千时，改写成循环或用显式栈
 *  - 有重复子问题时加缓存（记忆化），或改用动态规划
 *  - 递归函数内部尽量只依赖参数，少用全局变量
 *  - 调试递归时打印"进入/退出 + 层数"，一眼就能看清调用树
 */

#include <stdio.h>

/* ---------- 1. 阶乘：最标准的递归 ---------- */
static long long fact(int n)
{
    if (n <= 1)                       /* ① 边界条件 */
        return 1;
    return (long long)n * fact(n - 1); /* ② 规模缩小 + ③ 调用自身 */
}

/* 带打印的版本：用来看"递推"和"回归"两个阶段 */
static long long fact_trace(int n, int depth)
{
    printf("%*s→ fact(%d) 进入\n", depth * 2, "", n);
    long long r = (n <= 1) ? 1 : (long long)n * fact_trace(n - 1, depth + 1);
    printf("%*s← fact(%d) = %lld\n", depth * 2, "", n, r);
    return r;
}

/* ---------- 2. 斐波那契：朴素递归（反例） ---------- */
static long long g_calls;             /* 统计调用次数（全局变量，06 篇讲细节） */

static long long fib(int n)
{
    g_calls++;
    if (n < 2)
        return n;
    return fib(n - 1) + fib(n - 2);
}

/* 记忆化：把算过的结果存起来，避免重复计算（0 表示"还没算"） */
static long long g_memo[64];

static long long fib_memo(int n)
{
    g_calls++;
    if (n < 2)
        return n;
    if (g_memo[n] != 0)               /* 算过就直接取，不再往下递归 */
        return g_memo[n];
    g_memo[n] = fib_memo(n - 1) + fib_memo(n - 2);
    return g_memo[n];
}

/* 迭代版：同样的结果，线性时间 */
static long long fib_iter(int n)
{
    long long a = 0, b = 1;
    for (int i = 0; i < n; i++) {
        long long t = a + b;
        a = b;
        b = t;
    }
    return a;
}

/* ---------- 3. 十进制转二进制：递归天然倒序 ---------- */
static void to_binary(unsigned int n)
{
    if (n > 1)
        to_binary(n / 2);             /* 先处理高位 */
    putchar('0' + (int)(n % 2));      /* 回归时才打印，正好从高位到低位 */
}

/* ---------- 4. 汉诺塔：递归思维的经典 ---------- */
static void hanoi(int n, char from, char to, char via, int *moves)
{
    if (n == 0)                       /* 边界：没有盘子要移动 */
        return;
    hanoi(n - 1, from, via, to, moves);        /* ① n-1 个先挪到中转柱 */
    (*moves)++;
    printf("   第 %d 步：%c → %c（移动盘子 %d）\n", *moves, from, to, n);
    hanoi(n - 1, via, to, from, moves);        /* ③ 再从 中转柱 挪到目标柱 */
}

/* ---------- 5. 递归深度：看栈能撑多深 ---------- */
static int depth_probe(int n)
{
    if (n == 0)
        return 0;
    return 1 + depth_probe(n - 1);
}

int main(void)
{
    /* ---------- 1. 递归三要素 ---------- */
    printf("1. 递归三要素：边界、缩小、调用自身\n");
    printf("   fact(5)  = %lld\n", fact(5));
    printf("   fact(10) = %lld\n", fact(10));
    printf("   边界 n <= 1 返回 1；规模每次减 1；用 n * fact(n-1) 表达原问题\n");

    /* ---------- 2. 递推与回归（打印调用链） ---------- */
    printf("2. 一次递归的两个阶段：先一路压栈，再一路返回\n");
    long long r4 = fact_trace(4, 1);
    printf("   fact(4) 最终 = %lld\n", r4);
    printf("   → 是递推（进栈），← 是回归（出栈），两头顺序正好相反\n");

    /* ---------- 3. 溢出：递归也躲不过数据类型上限 ---------- */
    printf("3. 递归不解决溢出问题：只看数据类型上限\n");
    printf("   fact(20) = %lld（long long 还能装下，约 2.43e18）\n", fact(20));
    printf("   21! 约 5.1e19，超过 long long 上限 9.2e18 → 有符号溢出是未定义行为\n");
    printf("   所以这里故意不算 fact(21)：算了也只会得到不可靠的结果\n");
    printf("   13! 就超过 32 位 int，21! 超过 64 位 long long\n");

    /* ---------- 4. 斐波那契：朴素递归为什么慢 ---------- */
    printf("4. 斐波那契：朴素递归会重复计算\n");
    g_calls = 0;
    long long f20 = fib(20);
    printf("   fib(20) = %lld，递归调用次数 = %lld\n", f20, g_calls);
    printf("   迭代版 fib_iter(20) = %lld，只循环 20 次\n", fib_iter(20));
    printf("   同一层 fib(3) 被算了多遍 —— 这就是指数级复杂度的来源\n");
    g_calls = 0;
    long long fm20 = fib_memo(20);
    printf("   记忆化版 fib_memo(20) = %lld，递归调用次数 = %lld\n", fm20, g_calls);
    printf("   记忆化 = 递归 + 缓存：算过的直接取，复杂度降到线性\n");

    /* ---------- 5. 十进制转二进制：回归顺序的妙用 ---------- */
    printf("5. 十进制转二进制：递归的回归顺序正好是高位到低位\n");
    unsigned int num = 10;
    printf("   %u 的二进制 = ", num);
    to_binary(num);
    printf("\n   先递归处理 n/2，回来再打印 n%%2，所以顺序天然正确\n");

    /* ---------- 6. 汉诺塔 ---------- */
    printf("6. 汉诺塔：把一个 n 层问题拆成两个 n-1 层问题\n");
    int moves = 0;
    hanoi(3, 'A', 'C', 'B', &moves);
    printf("   n = 3 共 %d 步（公式：2^n - 1 = %d）\n", moves, (1 << 3) - 1);
    printf("   n = 64 时是 1.8e19 步 —— 写法优雅，但物理上跑不完\n");

    /* ---------- 7. 递归深度 ---------- */
    printf("7. 递归深度就是栈的深度\n");
    printf("   depth_probe(1000) = %d（1000 层还能撑住）\n", depth_probe(1000));
    printf("   每层都要占一个栈帧，深度几万时可能直接栈溢出（段错误）\n");
    printf("   本程序不演示崩溃：把 1000 改成 1000000 就会崩\n");

    /* ---------- 8. 小结 ---------- */
    printf("8. 小结：\n");
    printf("    递归 = 边界条件 + 规模缩小 + 调用自身，三者缺一不可\n");
    printf("    执行分两阶段：递推压栈、回归出栈，顺序相反\n");
    printf("    开销 = 递归深度 × 每层栈帧，深度大就会栈溢出\n");
    printf("    朴素递归求斐波那契会重复计算，改用迭代或记忆化\n");
    printf("    树、分治、回溯适合递归；单纯重复 N 次用循环\n");
    printf("    C 不保证尾递归优化，别靠它避免栈溢出\n");

    return 0;
}

