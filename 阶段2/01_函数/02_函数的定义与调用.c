/*
 * 02_函数的定义与调用.c —— 阶段2 / 第 01 课 / 第 02 个文件：函数的定义与调用
 *
 * 编译：gcc -std=c99 -Wall -Wextra 02_函数的定义与调用.c -o bin/02_函数的定义与调用
 * 运行：./bin/02_函数的定义与调用
 *
 * 01 篇回答了"函数是什么"，本篇把**写函数的语法**拆开逐块讲：
 * 返回类型、函数名、形参列表、函数体、return，以及怎么调用。
 *
 * ====================== 一、定义的完整语法 ======================
 *
 *      返回类型  函数名  形参列表
 *         │        │       │
 *      ┌──┴──┐  ┌──┴──┐ ┌──┴──────────┐
 *      int    max2   (int a, int b)
 *      {
 *          if (a > b) return a;        ← 函数体：语句 + return
 *          return b;
 *      }
 *
 * 六种常见的返回类型：
 *
 *      void          f(void);        什么也不返回
 *      int           f(int);         返回整数
 *      double        f(double);      返回浮点
 *      const char *  f(void);        返回指针（阶段1 第 06 课第 04 篇）
 *      struct Point  f(void);        返回结构体（会整体拷贝一份）
 *      int *         f(int *);       返回指针，注意别返回局部变量地址
 *
 * ★ 数组**不能**作为返回类型：`int f(void)[10];` 是错的。
 *   想"返回一组数据"只有三条路：返回指针（指向调用方缓冲区 / static / malloc）、
 *   打包成结构体、或者干脆让调用方把数组传进来（03 篇）。
 *
 * ★ 返回值是**右值**：不能取地址、不能赋值。
 *      &f()        ✗ 编译错误
 *      f() = 1;    ✗ 编译错误
 *   它只是"调用方拿到的一份副本"，用完就没了。
 *
 * ====================== 二、形参和实参 ======================
 *
 *      int max2(int a, int b);     // a、b 是**形参**：定义时的占位符
 *      max2(x, y);                 // x、y 是**实参**：调用时真正传进去的值
 *
 * 三条规则：
 *
 *  1) **按位置对应，不按名字**。形参叫 a、b，实参叫 x、y 完全没问题；
 *     但第一个实参一定进第一个形参。
 *
 *  2) **个数和类型要对上**。少了/多了都编译不过；类型不匹配会隐式转换
 *     （比如传 double 给 int 形参，会截断小数部分，且不报错）。
 *
 *  3) 形参是**局部变量**，只在函数内部有效，函数返回就消失。
 *     所以"在函数里改形参"改不到外面（03 篇详讲值传递）。
 *
 * ====================== 三、return 的三种用法 ======================
 *
 *  (1) 返回一个值
 *          return a + b;
 *      类型要能转成返回类型。非 void 函数**必须**保证每条路径都有 return，
 *      否则一旦走到函数末尾就是未定义行为（拿到的返回值不确定）。
 *
 *  (2) 提前返回（early return）：把"特殊情况"先处理掉
 *          if (v < lo) return lo;
 *          if (v > hi) return hi;
 *          return v;
 *      这比层层嵌套 if-else 更好读，也叫"卫语句"。
 *
 *  (3) void 函数里的裸 return：提前结束，不带值
 *          if (n < 0) return;
 *
 * ★ return 一旦执行，后面的语句都不会再执行。
 *
 * ====================== 四、返回值的类型转换 ======================
 *
 *      int f(double d) { return d; }        // d 会先被截断成 int
 *      f(3.99)   →   3                       // 不是四舍五入！
 *
 * 编译器不一定报错（-Wall -Wextra 也不一定），所以**别依赖隐式转换**：
 * 该强转就写 (int)d，或者在参数上就用对类型。
 *
 * 反过来，`int` 返回给 `double` 变量是安全的（升宽），不用担心丢数据。
 *
 * ====================== 五、调用的三种形式 ======================
 *
 *      print_line();                          // ① 语句调用：只为副作用
 *      int s = add(1, 2);                     // ② 表达式调用：为了拿结果
 *      printf("%d\n", add(mul(2, 3), 4));     // ③ 嵌套调用：函数套函数
 *
 * 还可以直接当条件用：
 *
 *      if (is_even(n)) ...
 *
 * 函数调用也是表达式，有值、有类型 —— 这点和变量一样，
 * 所以它能出现在任何"需要一个值"的地方。
 *
 * ====================== 六、没有参数要写 (void) ======================
 *      void f(void);       // ✓ 明确表示"不收参数"
 *      void f();           // ⚠ 在 C 里表示"参数未知"，不是"没有参数"
 *
 * 第二种写法在 C 里是**旧式声明**：调用时可以传任意参数，编译器不检查。
 * C++ 里 `f()` 才等于"没有参数"，C 不是。所以**一律写 (void)**。
 *
 * ====================== 七、函数不能嵌套定义 ======================
 *      void outer(void)
 *      {
 *          void inner(void) { }       // ✗ C 不允许在函数里定义函数
 *      }
 *
 * C 没有嵌套函数（GCC 有扩展，但那是方言，别用）。
 * 需要"内部辅助函数"时，就在文件里平级定义，用 static 限制可见性（04 篇）。
 *
 * ====================== 八、常见坑 ======================
 *  1. 非 void 函数漏了 return     走到末尾是未定义行为
 *  2. 只在某个分支 return        其余分支的返回值不确定
 *  3. 以为形参名字要和实参一样     按位置对应，名字无关
 *  4. 无参函数写成 f()            C 里表示参数未知，要写 f(void)
 *  5. 依赖隐式类型转换             double→int 是截断，不是四舍五入
 *  6. 函数里定义函数               C 不支持嵌套定义
 *  7. 函数名起得太随意            a1、f2、test，三个月后自己都看不懂
 *  8. 一个函数塞十几件事          调用者无法预期它的副作用
 *  9. 返回局部变量的地址           见阶段1 第 06 课第 04/07 篇
 * 10. 在头文件里写函数定义         （配合 04 篇）多个 .c 包含它会重复定义
 *
 * ====================== 九、实践建议 ======================
 *  - 名字用动词/判断词开头：sum、print_line、is_even、find_max
 *  - 参数不超过 4 个；再多就考虑结构体打包
 *  - 不修改的指针参数一律加 const
 *  - 用卫语句代替深层嵌套
 *  - 一个函数只做一件事，能一句话说清它干什么
 *  - 先写调用代码，再写实现：接口会更自然
 */

#include <stdio.h>

/* ---- 单个 return ---- */
static int add(int a, int b)
{
    return a + b;
}

/* ---- 提前返回（卫语句） ---- */
static int max2(int a, int b)
{
    if (a > b)
        return a;
    return b;
}

/* ---- 多个分支都有 return ---- */
static int clamp(int v, int lo, int hi)
{
    if (v < lo)
        return lo;                   /* 提前返回：下面两条就不用再判断了 */
    if (v > hi)
        return hi;
    return v;
}

/* ---- void 函数里的裸 return ---- */
static void report(int n)
{
    if (n < 0) {
        printf("   %d 是负数，直接返回\n", n);
        return;                      /* 不带值的 return */
    }
    printf("   %d 是非负数，正常处理\n", n);
}

/* ---- 返回值会被隐式转换 ---- */
static int truncate_double(double d)
{
    return (int)d;                   /* 显式截断；不写强转也能编过，但会静默丢小数 */
}

/* ---- 无参函数：写 (void) ---- */
static void print_line(void)
{
    printf("   ----\n");
}

/* ---- 两个参数、按位置对应 ---- */
static int total(int x, int y)
{
    return x + y;
}

/* ---- 不满足交换律，用来看"顺序真的会影响结果" ---- */
static int sub(int a, int b)
{
    return a - b;
}

int main(void)
{
    /* ---------- 1. 语法拆解 ---------- */
    printf("1. int max2(int a, int b) { ... } 逐块看\n");
    printf("   返回类型 int：给调用者一个 int\n");
    printf("   函数名 max2：以后靠它调用\n");
    printf("   形参 (int a, int b)：要两个 int 输入\n");
    printf("   函数体 { ... return b; }：干活 + 交结果\n");

    /* ---------- 2. 形参与实参按位置对应 ---------- */
    printf("2. 形参叫 a、b，实参叫 x、y，按位置对应，跟名字无关\n");
    int x = 7, y = 9;
    printf("   max2(x, y) = %d（第一个实参进第一个形参）\n", max2(x, y));
    printf("   sub(x, y) = %d，sub(y, x) = %d（顺序一换，结果就变）\n",
           sub(x, y), sub(y, x));
    printf("   total(x, y) = %d（同一个 x、y 传给不同函数）\n", total(x, y));

    /* ---------- 3. return 的三种用法 ---------- */
    printf("3. return 的三种用法\n");
    printf("   ① 返回值：add(2, 3) = %d\n", add(2, 3));
    printf("   ② 提前返回（卫语句）：clamp(15, 0, 10) = %d\n", clamp(15, 0, 10));
    printf("      clamp(-3, 0, 10) = %d，clamp(5, 0, 10) = %d\n",
           clamp(-3, 0, 10), clamp(5, 0, 10));
    printf("   ③ void 里的裸 return：\n");
    report(-1);
    report(8);

    /* ---------- 4. 返回值的隐式转换 ---------- */
    printf("4. 返回值类型不匹配会隐式转换\n");
    printf("   truncate_double(3.99) = %d（截断，不是四舍五入）\n",
           truncate_double(3.99));
    printf("   反过来 int → double 是安全的升宽：%f\n", (double)add(1, 2));

    /* ---------- 5. 调用的三种形式 ---------- */
    printf("5. 调用的三种形式\n");
    print_line();                             /* ① 语句调用 */
    int s = add(4, 5) * 2;                    /* ② 表达式调用 */
    printf("   ② int s = add(4, 5) * 2 → s = %d\n", s);
    printf("   ③ 嵌套调用 add(add(1, 2), add(3, 4)) = %d\n",
           add(add(1, 2), add(3, 4)));

    /* ---------- 6. 无参写 (void) ---------- */
    printf("6. 没有参数要写 (void)，不能写 ()\n");
    print_line();
    printf("   (void) 表示「明确没有参数」；() 在 C 里表示「参数未知」\n");
    printf("   C++ 里 () 才等于没有参数，写 C 时别混用\n");

    /* ---------- 7. 小结 ---------- */
    printf("7. 小结：\n");
    printf("    定义：返回类型 名字(形参列表) { 函数体 }\n");
    printf("    形参和实参按位置对应，名字可以完全不同\n");
    printf("    return 三种用法：返回值、提前返回、void 里的裸 return\n");
    printf("    非 void 函数每条路径都要有 return\n");
    printf("    函数调用本身是表达式，能嵌套、能当条件\n");
    printf("    无参写 (void)；C 不支持函数嵌套定义\n");

    return 0;
}

