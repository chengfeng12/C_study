/*
 * 04_函数的声明与多文件.c —— 阶段2 / 第 01 课 / 第 04 个文件：函数的声明、原型与多文件
 *
 * 编译：gcc -std=c99 -Wall -Wextra 04_函数的声明与多文件.c -o bin/04_函数的声明与多文件
 * 运行：./bin/04_函数的声明与多文件
 *
 * 到这一篇为止，函数都是写在一个 .c 里的。真实项目不会这样：
 * 一个函数可能定义在别的文件里，编译器编译当前文件时**看不到**它。
 * 这一篇讲清楚"编译器怎么知道有这个函数"，以及多文件怎么组织。
 *
 * 本文件只演示**同文件内**的声明与 extern；多文件的编译链接在注释里讲，
 * 因为仓库约定"一篇一个 .c"，不额外制造多个源文件。
 *
 * ====================== 一、编译器是"从上往下"读的 ======================
 * C 编译器只读一遍代码。遇到调用 `f(1)` 时，它必须**已经见过** f 的声明，
 * 否则不知道：
 *
 *      - f 是不是函数（还是变量？）
 *      - 要几个参数、什么类型
 *      - 返回值是什么类型（这决定了以后怎么用它）
 *
 * 所以下面这样写会出错：
 *
 *      int main(void) { return twice(21); }   // ✗ 此时 twice 还没出现
 *      int twice(int x) { return x * 2; }
 *
 * 两种解决办法：
 *      1) 先把函数定义写在前面（顺序调整）
 *      2) 先写**函数原型**（声明），定义放后面 —— 这是工程里的标准做法
 *
 * ====================== 二、函数原型（声明） ======================
 *
 *      int twice(int x);        // 原型：只描述"长什么样"
 *      int twice(int);          // 等价写法：参数名可以省略
 *      int twice(int x) { ... } // 定义：真正产生代码
 *
 * 原型的作用就一句话：**告诉编译器这个函数的存在和签名。**
 * 它不分配空间、不产生任何机器码，纯属"信息"。
 *
 * 原型通常放在文件开头（或者头文件里），好处是：
 *
 *      - 调用处不用关心定义的顺序
 *      - 同一个原型能约束多处调用，编译器会检查参数类型和个数
 *      - 函数之间的调用关系一目了然（读开头就知道这个文件用到哪些外部函数）
 *
 * ====================== 三、声明 vs 定义 ======================
 *
 *      声明（原型）：int twice(int);        可以出现**多次**
 *      定义：        int twice(int x) { }   只能出现**一次**
 *
 * 记法：带 `{ }` 函数体的就是定义；带分号、没有函数体的就是声明。
 *
 * 变量也一样：
 *      extern int g_total;     // 声明：这里不分配空间
 *      int g_total = 100;      // 定义：真正分配并初始化
 *
 * ====================== 四、隐式声明：C89 的老坑，C99 起禁止 ======================
 * 很久以前（C89），调用一个没声明过的函数是"合法"的：编译器会**猜**
 * 它返回 int、参数类型按实参推断。这叫隐式声明。
 *
 * 后果很严重，最经典的是 malloc：
 *
 *      // 忘了 #include <stdlib.h>
 *      int *p = malloc(sizeof *p);        // C89：编译器以为 malloc 返回 int
 *                                        // 指针被截断成 32 位 → 运行期崩
 *
 * C99 起隐式声明被禁止，GCC 会给出警告/错误：
 *      warning: implicit declaration of function 'malloc'
 *
 * ★ 看到这条警告**不要**靠强转 (int *) 消掉它，
 *   正确做法是补上 #include（阶段1 第 06 课第 08 篇讲过这个细节）。
 *
 * ====================== 五、头文件：把声明集中起来 ======================
 * 多个 .c 都要用同一个函数时，把原型放进 .h，大家 #include：
 *
 *      // ---- math_utils.h ----
 *      #ifndef MATH_UTILS_H           ← 头文件保护，防止重复包含
 *      #define MATH_UTILS_H
 *
 *      int  add(int a, int b);
 *      int  mul(int a, int b);
 *
 *      #endif
 *
 *      // ---- math_utils.c ----
 *      #include "math_utils.h"        ← 自己包含自己的头文件，让编译器核对
 *      int add(int a, int b) { return a + b; }
 *      int mul(int a, int b) { return a * b; }
 *
 *      // ---- main.c ----
 *      #include "math_utils.h"
 *      int main(void) { return add(1, 2); }
 *
 * 三个要点：
 *
 *  1) `#include` 就是**文本替换**，不是"导入模块"。编译器把 .h 的内容
 *     原样贴到这一行，仅此而已。
 *  2) 头文件里**默认只放声明**（原型、宏、类型定义），不要放**普通**函数体。
 *     普通函数定义放了会怎样：两个 .c 都包含它 → 链接时"重复定义"。
 *  3) `#include "x.h"` 先找当前目录，`#include <x.h>` 找系统目录。
 *
 * ★ 唯一的例外：极小的函数写成 `static inline` 放进头文件，是允许且常见的。
 *
 *      // ---- utils.h ----
 *      static inline int max_int(int a, int b) { return a > b ? a : b; }
 *
 *   为什么不会重复定义：`static` 让每个包含它的 .c 各自有一份**内部副本**
 *   （第七节的内部链接），`inline` 只是建议编译器把调用展开，二者不冲突。
 *
 *   代价：每个 .c 都带一份代码，头文件越"重"编译产物越大 ——
 *        所以只放一两行的极小函数，别把大函数塞进头文件。
 *
 *   对比：写成普通 `int max_int(...)` 放头文件 → 每个 .c 各定义一次 →
 *        链接报 multiple definition，正是第 2 点说的坑。
 *
 * ====================== 六、多文件怎么编译和链接 ======================
 * 以三个文件为例：
 *
 *      main.c    math_utils.c    math_utils.h
 *
 * 一步到位：
 *      gcc -std=c99 -Wall -Wextra main.c math_utils.c -o bin/app
 *
 * 分步（工程里更常见，改一个文件只重编一个）：
 *      gcc -std=c99 -Wall -Wextra -c main.c        → main.o
 *      gcc -std=c99 -Wall -Wextra -c math_utils.c  → math_utils.o
 *      gcc main.o math_utils.o -o bin/app          → 链接
 *
 * 三个阶段的职责：
 *
 *   预处理  展开 #include、宏替换         → 变成一个大 .c
 *   编译    每个 .c 单独翻译成 .o         → 此时还允许"有声明没定义"
 *   链接    把所有 .o 拼起来，找函数地址  → 缺定义会报 undefined reference
 *
 * 所以"函数在哪个文件定义的"对调用方是透明的 —— 只要链接时能找到。
 *
 * ====================== 七、static 与 extern：链接属性 ======================
 * 同一份代码跨文件时，两个关键字决定"谁看得见谁"：
 *
 *      static int helper(void);        // 只在**本文件**内可见（内部链接）
 *      int  api(int);                  // 默认外部链接，别的文件也能用
 *      extern int g_total;             // 声明：这个变量定义在别处
 *
 * 实用的三条：
 *
 *  1) 只在本文件用到的辅助函数，一律加 static。
 *     好处：不污染全局命名空间、别的文件无法误用、编译器可做更好优化。
 *  2) 全局变量能不用就不用；必须跨文件共享时，在 .h 里写 extern，
 *     在**一个** .c 里写定义。
 *  3) static 和 extern 是**四种组合**里的两种（static 函数/变量、extern 声明），
 *     别在定义上同时写 static 和 extern（矛盾）。
 *
 * ====================== 八、常见坑 ======================
 *  1. 先调用后定义、又忘了写原型        隐式声明警告 / 编译错误
 *  2. 原型和定义签名不一致              编译报"类型冲突"，是好事，别硬改原型迁就
 *  3. 头文件里写函数体                  多个 .c 包含 → 重复定义（链接错误）
 *  4. 忘了头文件保护                    重复包含时报类型/宏重复定义
 *  5. 用 (int *)malloc 消掉隐式声明警告  真正的问题是缺 #include <stdlib.h>
 *  6. 多个 .c 定义了同名全局变量        链接报 multiple definition
 *  7. 只在 .c 里 static 声明、.h 里又是普通声明   链接不到（内部链接 vs 外部）
 *  8. 编译通过就以为没问题              链接阶段才查"有没有定义"（undefined reference）
 *  9. 改了头文件却没重编所有依赖它的 .c   用 make/CMake 管理依赖
 * 10. 把 static 当成"作用域"理解        它管的是**链接**（跨文件可见性），
 *                                      和"块作用域"是两回事（06 篇）
 *
 * ====================== 九、实践建议 ======================
 *  - 每个 .c 文件开头集中放本文件函数原型（或包含自己的 .h）
 *  - 对外接口放 .h，内部实现函数一律 static
 *  - 头文件写好保护宏，且只放声明
 *  - 编译命令固定用 `-std=c99 -Wall -Wextra`，警告当错误看
 *  - 报 undefined reference 时，先看是"没定义"还是"没参与链接"
 *  - 项目大起来就用 make/CMake，别手写一长串 gcc
 */

#include <stdio.h>

/* ================== 函数原型（声明）区 ==================
 * 定义在后面，这里先把"它们存在"这件事告诉编译器。
 * 原型里的参数名可以省略，只留类型。
 */
static int twice(int);
static int power(int, int);          /* 不写参数名也完全合法 */
static void banner(const char *title);

/* 变量的声明：告诉编译器 g_total 定义在别处（本文件末尾） */
extern int g_total;

int main(void)
{
    /* ---------- 1. 先调用、后定义 ---------- */
    printf("1. 先调用、后定义，靠的就是函数原型\n");
    printf("   twice(21) = %d（定义写在 main 后面）\n", twice(21));
    printf("   原型只描述签名，不产生任何代码\n");

    /* ---------- 2. 原型里可以不写参数名 ---------- */
    printf("2. 原型里参数名可以省略：static int power(int, int);\n");
    printf("   power(2, 10) = %d\n", power(2, 10));
    printf("   参数名只是给人和文档看的，编译器只认类型和顺序\n");

    /* ---------- 3. static：只在本文件可见 ---------- */
    printf("3. static 函数：只在本文件内可见\n");
    banner("static 函数");
    printf("   好处：不污染全局命名空间，别的 .c 没法误用\n");

    /* ---------- 4. extern：声明与定义分家 ---------- */
    printf("4. extern 声明不分配空间，定义才分配\n");
    printf("   extern int g_total;  ← 声明（在这一行之前）\n");
    printf("   int g_total = %d;    ← 定义（在文件末尾）\n", g_total);

    /* ---------- 5. 头文件与多文件（只讲，不制造多文件） ---------- */
    printf("5. 多文件的组织方式\n");
    printf("   声明放 .h，定义放 .c，用 #include 把声明贴进来\n");
    printf("   编译：gcc -c main.c -o main.o     每个 .c 单独翻译\n");
    printf("   链接：gcc main.o math_utils.o -o bin/app   拼起来找地址\n");
    printf("   缺定义时链接器报 undefined reference to 'xxx'\n");

    /* ---------- 6. 小结 ---------- */
    printf("6. 小结：\n");
    printf("    编译器从上往下读，调用点之前必须见过声明\n");
    printf("    原型 = 声明，可以多次；带函数体的定义只能一次\n");
    printf("    头文件只放声明，必须写保护宏\n");
    printf("    编译管「有没有声明」，链接管「有没有定义」\n");
    printf("    只在本文件用到的函数一律加 static\n");
    printf("    隐式声明是 C89 的老坑，C99 起禁止，补 #include 才对\n");

    return 0;
}

/* ====================== 本程序的运行结果（对照着看） ======================
 * 编译运行：
 *     mkdir -p bin
 *     gcc -std=c99 -Wall -Wextra 04_函数的声明与多文件.c -o bin/04_函数的声明与多文件
 *     ./bin/04_函数的声明与多文件
 *
 * 输出如下：
 *
 * 1. 先调用、后定义，靠的就是函数原型
 *    twice(21) = 42（定义写在 main 后面）
 *    原型只描述签名，不产生任何代码
 * 2. 原型里参数名可以省略：static int power(int, int);
 *    power(2, 10) = 1024
 *    参数名只是给人和文档看的，编译器只认类型和顺序
 * 3. static 函数：只在本文件内可见
 *    ==== static 函数 ====
 *    好处：不污染全局命名空间，别的 .c 没法误用
 * 4. extern 声明不分配空间，定义才分配
 *    extern int g_total;  ← 声明（在这一行之前）
 *    int g_total = 100;    ← 定义（在文件末尾）
 * 5. 多文件的组织方式
 *    声明放 .h，定义放 .c，用 #include 把声明贴进来
 *    编译：gcc -c main.c -o main.o     每个 .c 单独翻译
 *    链接：gcc main.o math_utils.o -o bin/app   拼起来找地址
 *    缺定义时链接器报 undefined reference to 'xxx'
 * 6. 小结：
 *     编译器从上往下读，调用点之前必须见过声明
 *     原型 = 声明，可以多次；带函数体的定义只能一次
 *     头文件只放声明，必须写保护宏
 *     编译管「有没有声明」，链接管「有没有定义」
 *     只在本文件用到的函数一律加 static
 *     隐式声明是 C89 的老坑，C99 起禁止，补 #include 才对
 *
 * 几个容易忽略的对照点：
 *   第 1 条：twice 的定义在 main 之后，却能调用成功 —— 因为文件开头有原型。
 *           把原型那行注释掉，编译器立刻报隐式声明（C99 下是错误）。
 *   第 2 条：原型写 `power(int, int)`、定义写 `power(int base, int exp)`，
 *           编译器不认为这是不一致 —— 参数名不属于函数类型。
 *   第 4 条：g_total 的 extern 声明在 main 之前、定义在文件末尾，
 *           说明"声明"只是告诉编译器有这么个名字，空间由定义分配。
 *           顺序反过来（先定义后 extern）也合法，只是演示不出区别。
 *   第 5 条：编译阶段允许"有声明没定义"，链接阶段才检查 ——
 *           所以 undefined reference 是链接错误，不是编译错误。
 * ==========================================================================
 */

/* ================== 定义区（都在 main 之后） ================== */

static int twice(int x)
{
    return x * 2;
}

static int power(int base, int exp)
{
    int r = 1;
    for (int i = 0; i < exp; i++)
        r *= base;
    return r;
}

static void banner(const char *title)
{
    printf("   ==== %s ====\n", title);
}

/* 定义：真正分配空间，并初始化 */
int g_total = 100;
