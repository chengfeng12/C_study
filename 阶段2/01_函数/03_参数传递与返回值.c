/*
 * 03_参数传递与返回值.c —— 阶段2 / 第 01 课 / 第 03 个文件：参数传递与返回值
 *
 * 编译：gcc -std=c99 -Wall -Wextra 03_参数传递与返回值.c -o bin/03_参数传递与返回值
 * 运行：./bin/03_参数传递与返回值
 *
 * 本篇回答两个问题：
 *   1) 参数到底是"怎么传进去的"，为什么函数改不了外面的变量？
 *   2) 一个函数只能 return 一个值，那要返回两个结果怎么办？
 *
 * ====================== 一、C 只有值传递 ======================
 * 调用函数时，实参的值被**复制**一份交给形参。形参是这次调用自己的局部变量，
 * 改它不会影响实参。
 *
 *      void try_change(int n) { n = 999; }
 *
 *      int x = 1;
 *      try_change(x);          // x 还是 1
 *
 * 画成图：
 *
 *      main 的 x ┌───┐          try_change 的 n ┌─────┐
 *                │ 1 │           （副本）        │ 999 │
 *                └───┘                           └─────┘
 *                  ↑                                  │
 *                  └──── 复制值，两者互不相干 ─────────┘
 *
 * 所以"C 是值传递"这句要理解成：**永远复制，没有例外**。
 * 传说中"传引用"的效果，本质是"传地址的副本"（第二节）。
 *
 * ====================== 二、传指针为什么能改外面 ======================
 *      void really_change(int *p) { *p = 999; }
 *
 *      int x = 1;
 *      really_change(&x);      // x 变成 999
 *
 * 注意：这**仍然是值传递** —— 复制的是"地址"这个值。
 * 副本和原件存的地址相同，所以顺着副本找到的是同一块内存。
 *
 *      main 的 x ┌───┐ ←──── &x 的副本存的就是这个地址
 *                │ 1 │                 │
 *                └───┘                 │
 *                          形参 p ┌────┴───┐
 *                                 │ 0x...  │ → 顺着地址写，改的就是 x
 *                                 └────────┘
 *
 * 所以判断"能不能改外面"，只看一件事：**传进去的是值，还是地址**。
 * （阶段1 第 06 课第 01 篇第七节的 swap 就是这个道理的应用。）
 *
 * ====================== 三、数组作参数：退化成指针 ======================
 *      void fill(int a[10]);        // 编译器看到的是 int *
 *
 * 三条推论：
 *
 *  1) 函数里 sizeof(a) 是 8（指针大小），不是 40
 *  2) 长度必须另外传：`void fill(int *a, int n)`
 *  3) 函数里改 a[i] 会改到调用方的数组 —— 因为 a 指向的就是原数组
 *
 * 但注意：`a = 别的地址;` 只改副本，调用方的数组名不会变（数组名本来就是常量）。
 *
 * ====================== 四、实参的求值顺序是未指定的 ======================
 *      printf("%d %d\n", f(), g());      // f 和 g 谁先执行？标准没说
 *
 * C 标准只规定"所有实参都求值完再调用"，**没规定顺序**。
 * 不同编译器、不同优化等级可以是左到右，也可以是右到左。
 *
 * 所以下面这种代码是**不可移植**的：
 *
 *      int i = 0;
 *      printf("%d %d\n", i++, i++);      // ✗ 顺序不确定，甚至可能是未定义行为
 *
 * 更危险的是"同时修改同一对象"，那是未定义行为，不只是顺序问题。
 *
 * 规则：**不要在实参里写有副作用的表达式**（++、--、赋值）。
 * 想控制顺序就拆成几条语句。
 *
 * ====================== 五、返回多个结果 ======================
 * `return` 只能带一个值，但有三种办法带回多个结果：
 *
 *  (1) 指针 out 参数（最常用）
 *          int divmod(int a, int b, int *rem);      // return 商，*rem 给余数
 *          int r;
 *          int q = divmod(17, 5, &r);
 *      调用方要额外声明变量，接口略笨，但零开销、最通用。
 *
 *  (2) 返回结构体（C89 起就支持）
 *          typedef struct { int q, r; } DivResult;
 *          DivResult divmod2(int a, int b);
 *      调用处最好读：`DivResult d = divmod2(17, 5); d.q / d.r`
 *      代价是结构体会被整体拷贝（小结构体通常被编译器优化掉）。
 *
 *  (3) 全局变量（不推荐）
 *      隐藏了数据流，难测试、难并发，只在特殊场景用。
 *
 * ====================== 六、返回值也是"按值返回" ======================
 * `return x;` 会把 x 的值复制一份交给调用方：
 *
 *  - 返回值类型是基本类型：直接复制那个数字
 *  - 返回值类型是结构体：整个结构体复制一份（可能被优化成"直接构造在调用方"）
 *  - 返回值类型是指针：复制的是地址 —— **千万别返回局部变量的地址**
 *    （函数返回后局部变量已销毁，阶段1 第 06 课第 04/07 篇讲过）
 *
 * ★ 返回值是**右值**：`&f()`、`f() = 1` 都不合法。
 *   它只是"调用方收到的一份副本"，用完即弃；想留着就赋给变量。
 *   另一方面，数组**不能**当返回类型（`int f(void)[10];` ✗），
 *   只能返回指针或结构体（02 篇第一节）。
 *
 * 想"返回一块数据"的正确做法：
 *      调用方传缓冲区进来 / 返回 static 数组 / 用 malloc（谁申请谁释放）
 *
 * ====================== 七、常见坑 ======================
 *  1. 以为函数能改实参            值是复制的，要改就传地址
 *  2. 传了指针但忘了 &             `f(p)` 应该是 `f(&p)`（阶段1 第 06 课第 05 篇）
 *  3. 函数里 sizeof(数组参数)      永远是指针大小
 *  4. 忘记传长度                  数组参数必须配一个 n
 *  5. 在实参里写 i++              求值顺序未指定，结果不可移植
 *  6. 返回局部变量地址             悬垂指针
 *  7. 返回结构体时以为"不拷贝"     语义上是拷贝，别依赖未定义的行为
 *  8. out 参数没判空就写           `*rem = ...` 前要确保 rem 有效
 *  9. 用全局变量当"多个返回值"     隐藏依赖，后续很难改
 * 10. void 函数当作表达式用        `int x = f();` 编译错误
 *
 * ====================== 八、实践建议 ======================
 *  - 参数能传值就传值（小对象简单），要改或太大才传地址
 *  - 只读指针参数加 const：`void print(const int *a, int n)`
 *  - 数组参数一律 "指针 + 长度" 成对出现
 *  - 多个返回值优先用结构体（可读），其次用 out 参数（通用）
 *  - 实参里不写副作用表达式
 *  - 需要"返回数据"时，优先让调用方传缓冲区
 */

#include <stdio.h>

/* 值传递：改的是副本 */
static void try_change(int n)
{
    n = 999;
    printf("   函数内 n 已经被改成 %d（但那只改了副本）\n", n);
}

/* 传地址：顺着副本里的地址，改到了调用方那块内存 */
static void really_change(int *p)
{
    *p = 999;
}

/* 数组作参数：实际传的是首地址，所以能改元素，但长度要另外给 */
static void double_all(int *a, int n)
{
    for (int i = 0; i < n; i++)
        a[i] *= 2;
}

/* out 参数：return 商，*rem 带出余数 */
static int divmod(int a, int b, int *rem)
{
    if (b == 0 || rem == NULL)           /* 防御：除数为 0 或指针为空 */
        return 0;
    *rem = a % b;
    return a / b;
}

/* 返回结构体：把两个结果打包成一个值 */
typedef struct {
    int q;                               /* 商 */
    int r;                               /* 余数 */
} DivResult;

static DivResult divmod2(int a, int b)
{
    DivResult d;
    d.q = a / b;
    d.r = a % b;
    return d;                            /* 返回时整个结构体被复制一份 */
}

/* 用来观察实参求值顺序（有副作用：会打印） */
static int left_operand(void)
{
    printf("   [left] 被求值\n");
    return 1;
}

static int right_operand(void)
{
    printf("   [right] 被求值\n");
    return 2;
}

int main(void)
{
    /* ---------- 1. 值传递：改不到外面 ---------- */
    printf("1. 值传递：形参是实参的副本\n");
    int x = 1;
    try_change(x);
    printf("   try_change(x) 之后 x = %d（没变，改的是副本）\n", x);

    /* ---------- 2. 传地址：能改到外面 ---------- */
    printf("2. 传地址：复制的还是值，只不过这个值是个地址\n");
    really_change(&x);
    printf("   really_change(&x) 之后 x = %d（顺着地址改到了原变量）\n", x);

    /* ---------- 3. 数组参数：能改元素，长度要单独给 ---------- */
    printf("3. 数组作参数退化成指针，元素能被改，长度必须另外传\n");
    int data[4] = {1, 2, 3, 4};
    printf("   调用前：%d %d %d %d\n", data[0], data[1], data[2], data[3]);
    double_all(data, 4);
    printf("   调用后：%d %d %d %d\n", data[0], data[1], data[2], data[3]);
    printf("   但函数里 sizeof(a) 只有 %zu 字节，所以 n 必须由调用方给\n",
           sizeof(int *));

    /* ---------- 4. 实参求值顺序未指定 ---------- */
    printf("4. 实参的求值顺序，标准没有规定\n");
    printf("   下面两个实参谁先算？本机实测如下（换编译器可能就反过来）：\n");
    printf("   结果：%d %d\n", left_operand(), right_operand());
    printf("   所以别在实参里写 i++ / 赋值这类有副作用的表达式\n");
    printf("   想控制顺序就拆成两条语句，先算好存进变量\n");

    /* ---------- 5. 多个返回值：out 参数 ---------- */
    printf("5. 用 out 参数带回第二个结果\n");
    int rem = 0;
    int q = divmod(17, 5, &rem);
    printf("   divmod(17, 5, &rem) → 商 %d，余数 %d（return 只带得回一个）\n", q, rem);

    /* ---------- 6. 多个返回值：返回结构体 ---------- */
    printf("6. 用结构体把多个结果打包成一个返回值\n");
    DivResult d = divmod2(17, 5);
    printf("   divmod2(17, 5) → q = %d，r = %d（调用处更像「返回了一个结果」）\n",
           d.q, d.r);
    printf("   代价是结构体被整体复制；小结构体一般会被编译器优化掉\n");

    /* ---------- 7. 小结 ---------- */
    printf("7. 小结：\n");
    printf("    C 只有值传递：形参永远是实参的副本，没有例外\n");
    printf("    想要改外面，就传地址（副本里存的是同一个地址）\n");
    printf("    数组参数退化成指针：能改元素，但长度必须另外传\n");
    printf("    实参求值顺序未指定，别在实参里写副作用表达式\n");
    printf("    多个返回值：out 参数（通用）或返回结构体（好读）\n");
    printf("    返回指针时别指向局部变量，那是悬垂指针\n");

    return 0;
}

