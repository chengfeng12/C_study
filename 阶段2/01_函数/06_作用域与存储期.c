/*
 * 06_作用域与存储期.c —— 阶段2 / 第 01 课 / 第 06 个文件：作用域与存储期
 *
 * 编译：gcc -std=c99 -Wall -Wextra 06_作用域与存储期.c -o bin/06_作用域与存储期
 * 运行：./bin/06_作用域与存储期
 *
 * 这一篇讲"变量活在哪、活多久"—— 它是理解函数的基础：
 * 为什么局部变量函数一返回就没了、为什么 static 变量能记住上次的值、
 * 为什么递归里用 static 会出错。
 *
 * 作用域的基础（块作用域、遮蔽）在阶段1 第 12 篇已经讲过；
 * 本篇从**函数**的角度重新组织，并补上 static/extern 与初始化时机。
 *
 * ====================== 一、两个维度：看得见 vs 活得久 ======================
 * 初学者最常把这两件事混为一谈，其实是两个独立的问题：
 *
 *      **作用域（scope）**：代码的哪一段能"看到"这个名字
 *      **存储期（storage duration）**：这块内存什么时候分配、什么时候释放
 *
 * 四种常见组合：
 *
 *      变量           作用域          存储期      初始值        典型写法
 *      -------------  --------------  ----------  ------------  ------------------
 *      局部变量        块（函数内）    自动        不确定        int x = 1;
 *      全局变量        整个文件        静态        0             int g;
 *      static 局部     块（函数内）    静态        0             static int s;
 *      static 全局     整个文件        静态        0             static int g;
 *
 * 注意第三行：**作用域还是局部的，但生命周期变成了整个程序**——
 * 这就是 static 局部变量"能记住上次的值"的全部秘密。
 *
 * ====================== 二、局部变量：块作用域 + 自动存储期 ======================
 *      void f(void)
 *      {
 *          int x = 1;              // 进入函数时分配
 *          {
 *              int y = 2;          // 只在这个内层花括号里可见
 *          }
 *          // y 已经不在了
 *      }                           // 离开函数，x 被销毁
 *
 * 三个要点：
 *
 *  1) 作用域是**块**（{}），不是函数。在 if/for 里定义的变量出了块就没了。
 *  2) 存储期是**自动**的：进块分配、出块回收，不需要（也不能）手动释放。
 *  3) 初始值是**不确定**的：不加初始化就是栈上的残留数据，读到什么全看运气。
 *
 * ====================== 三、全局变量：文件作用域 + 静态存储期 ======================
 *      int g_count;                // 定义在函数外
 *
 *      int main(void) { g_count++; }
 *
 *  1) 作用域是整个文件（从定义处往下），所有函数都能看见。
 *  2) 存储期是静态的：**程序启动前就分配好，程序结束才回收**。
 *  3) 不加初始化就是 **0**（这点和局部变量完全不同）。
 *  4) 别的文件想用，需要在头文件里写 `extern int g_count;`（04 篇）。
 *
 * 为什么不推荐滥用全局变量：
 *      任何函数都能改它 → 数据流看不见 → 难调试、难测试、难并发。
 *      只在"真正的全局状态"（配置、日志句柄）时才用。
 *
 * ====================== 四、static 局部变量：块作用域 + 静态存储期 ======================
 *      int next_id(void)
 *      {
 *          static int id = 0;      // 只在**第一次**调用时初始化一次
 *          return ++id;
 *      }
 *
 *      next_id() → 1
 *      next_id() → 2
 *      next_id() → 3
 *
 * 关键点：
 *
 *  1) 初始化只执行一次，之后每次调用都沿用上次的值（不会重置）。
 *  2) 它活到程序结束，但名字仍然只在这个函数里可见 —— 别人碰不到。
 *  3) 不用它替代全局变量：**把状态藏在函数内部**，接口更干净。
 *
 * 常见用途：计数器、一次性初始化标志、缓存。
 *
 * ★ 代价：**static 局部会让函数不可重入（non-reentrant）**。
 *   状态藏在静态区而不是栈上，所以同一时刻只允许一个调用者在用：
 *
 *      - 递归里会串味（第九节）
 *      - 多线程同时调用会互相踩数据（数据竞争）
 *      - 嵌套调用时，外层还没用完，内层已经把它改了
 *
 *   标准库的 `strtok` 就是受害者：它把"下次从哪继续"存在 static 里，
 *   于是没法同时解析两个字符串，C 才补了 `strtok_r`（r = reentrant）。
 *
 *   要"记住状态"又想保持可重入，两条路：
 *      ① 状态作为参数传入 / 用 out 参数带出
 *      ② 把状态打包进结构体，由调用方自己持有
 *
 * ====================== 五、static 的两个意思，别混 ======================
 * 同一个关键字有两种用法，含义完全不同：
 *
 *      static int g;                // 文件作用域的 static：**内部链接**
 *                                   // 别的 .c 看不见它（04 篇第七节）
 *
 *      void f(void) { static int s; }   // 块作用域的 static：**静态存储期**
 *                                   // 活到程序结束，但只有 f 能访问
 *
 * 记法：**static 作用在"变量/函数"上管链接，作用在"局部变量"上管寿命。**
 *
 * ====================== 六、extern：声明"别处有定义" ======================
 *      extern int g_count;         // 这里不分配空间
 *      int g_count = 0;            // 这里才分配（整个程序只能有一处）
 *
 * 用法：头文件里写 extern，某一个 .c 里写定义。
 * 细节见 04 篇第三节和第六节。
 *
 * ====================== 七、同名遮蔽（shadowing） ======================
 *      int v = 1;
 *      {
 *          int v = 2;              // 内层的 v 遮蔽了外层的
 *          printf("%d", v);        // 2
 *      }
 *      printf("%d", v);            // 1，外层的没变
 *
 * 合法但不推荐：读代码时很容易看错。编译器默认不警告，
 * 加上 `-Wshadow` 才会提示。
 *
 * ====================== 八、初始化时机：静态 vs 自动 ======================
 *
 *      静态存储期（全局、static 局部）：
 *          在程序启动前（main 之前）就完成初始化，且**只做一次**
 *          没写初始值 → 0
 *
 *      自动存储期（普通局部）：
 *          每次进入块时"分配"，但**不初始化**（除非你写了 = 初值）
 *          每次进入都会重新执行初始化语句
 *
 * 这就是为什么 static 变量的 `static int id = 0;` 只跑一次：
 * 它其实是"程序启动时的初始化"，不是"每次调用时的赋值"。
 *
 * ====================== 九、递归里的 static：一个经典陷阱 ======================
 *      int sum(int n)
 *      {
 *          static int total;        // ★ 所有递归层共用这一个变量
 *          if (n == 0) return total;
 *          total += n;
 *          return sum(n - 1);
 *      }
 *
 * 第一次 sum(3) 得到 6，**第二次再调用会继续累加**（total 不会清零）。
 * 正确做法是把状态当参数传：
 *
 *      int sum(int n, int acc)
 *      {
 *          if (n == 0) return acc;
 *          return sum(n - 1, acc + n);
 *      }
 *
 * 规则：**递归函数里不要用 static 局部变量保存中间状态。**
 *
 * ====================== 十、常见坑 ======================
 *  1. 把"作用域"和"存储期"当成一回事     局部变量是块作用域 + 自动存储期
 *  2. 以为局部变量会被自动清零             只有静态存储期才默认 0
 *  3. 在函数里返回局部变量的地址           函数返回后它就被销毁（阶段1 36 篇）
 *  4. 用全局变量在函数间传数据             数据流被藏起来，难维护
 *  5. 以为 static 局部每次调用都会重置     只初始化一次
 *  6. 在递归里用 static 累加               所有层共用一个变量，结果会串
 *  7. 混淆两种 static                     一个管链接，一个管寿命
 *  8. 多层同名变量遮蔽                     合法但难读，开 -Wshadow 能提醒
 *  9. 在 for 里定义变量又想在循环外用       块作用域，出循环就失效
 * 10. 依赖全局变量的初始化顺序            跨文件时顺序不确定，别互相依赖
 *
 * ====================== 十一、实践建议 ======================
 *  - 变量尽量定义在**最靠近使用处**，作用域越小越好
 *  - 需要"记住上次的值"就用 static 局部，不要用全局变量
 *  - 变量定义时就初始化，别依赖"静态的默认 0"
 *  - 递归函数的状态一律通过参数传递
 *  - 只在本文件用的全局变量/函数加 static
 *  - 打开 -Wshadow，能提前发现意外的遮蔽
 */

#include <stdio.h>

/* 全局变量：静态存储期，不写初始化就是 0 */
int g_default;                        /* 自动变成 0 */
int g_touched;                        /* 同上，用来演示能被任何函数改 */

/* static 局部：只初始化一次，之后一直记住 */
static int next_id(void)
{
    static int id = 0;                /* 只有第一次调用会执行这句 */
    return ++id;
}

/* 反例：递归里用 static 累加，多次调用会串味 */
static int sum_with_static(int n)
{
    static int total;                 /* 不会重置！ */
    if (n == 0)
        return total;
    total += n;
    return sum_with_static(n - 1);
}

/* 正解：把状态当参数传 */
static int sum_with_param(int n, int acc)
{
    if (n == 0)
        return acc;
    return sum_with_param(n - 1, acc + n);
}

int main(void)
{
    /* ---------- 1. 局部变量：块作用域 ---------- */
    printf("1. 局部变量是「块作用域 + 自动存储期」\n");
    {
        int in_block = 42;
        printf("   块内 in_block = %d，可以使用\n", in_block);
    }
    printf("   出了这个花括号，in_block 就被销毁，名字也不能再用\n");
    printf("   不加初始化的局部变量是残留数据，本程序不读它\n");

    /* ---------- 2. 全局变量：默认 0 ---------- */
    printf("2. 全局变量默认就是 0（静态存储期）\n");
    printf("   int g_default; 没有初始化，读出来是 %d\n", g_default);
    g_touched = 7;
    printf("   全局变量任何函数都能改（这里直接改成 %d），所以不推荐滥用\n", g_touched);

    /* ---------- 3. static 局部：只初始化一次 ---------- */
    printf("3. static 局部变量：只初始化一次，之后一直沿用\n");
    int id1 = next_id();
    int id2 = next_id();
    int id3 = next_id();
    printf("   next_id() 连续调用三次：%d %d %d（每次 +1，没有重置）\n", id1, id2, id3);
    printf("   这里故意拆成三条语句：若塞进同一个 printf 的实参里，\n");
    printf("   求值顺序是未指定的（03 篇），输出顺序可能反过来\n");

    /* ---------- 4. 同名遮蔽 ---------- */
    printf("4. 内层同名变量会遮蔽外层\n");
    int v = 1;
    {
        int v = 2;                    /* 遮蔽外层的 v */
        printf("   块内 v = %d（内层的）\n", v);
    }
    printf("   块外 v = %d（外层那个没变）\n", v);
    printf("   合法但难读，编译加 -Wshadow 会提醒\n");

    /* ---------- 5. 递归里的 static：经典陷阱 ---------- */
    printf("5. 递归里用 static 保存状态会串味\n");
    int first = sum_with_static(3);
    int second = sum_with_static(3);
    printf("   第一次 sum_with_static(3) = %d（1+2+3）\n", first);
    printf("   第二次 sum_with_static(3) = %d（又累加了一遍，total 没清零）\n", second);
    printf("   正解：状态当参数传 → sum_with_param(3, 0) = %d\n",
           sum_with_param(3, 0));
    printf("   再调一次也是 %d，因为没有共享状态\n", sum_with_param(3, 0));
    printf("   同理：多线程同时调用它也会互相踩数据 —— 这就是不可重入\n");

    /* ---------- 6. 初始化时机 ---------- */
    printf("6. 初始化时机：静态的只做一次，自动的每次进入都执行\n");
    printf("   静态（全局 / static 局部）：程序启动前初始化，没写就是 0\n");
    printf("   自动（普通局部）：每次进块重新分配，不写初值就是不确定值\n");
    printf("   所以 static int id = 0; 里的 =0 只会发生一次\n");

    /* ---------- 7. 小结 ---------- */
    printf("7. 小结：\n");
    printf("    作用域管「谁能看见」，存储期管「活多久」，是两个维度\n");
    printf("    局部变量：块作用域 + 自动存储期，初值不确定\n");
    printf("    全局变量：文件作用域 + 静态存储期，初值 0\n");
    printf("    static 局部：块作用域 + 静态存储期，只初始化一次\n");
    printf("    static 管链接还是管寿命，看它修饰的是全局还是局部\n");
    printf("    递归里不要用 static 保存状态，用参数传\n");

    return 0;
}

