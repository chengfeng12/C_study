/*
 * 17_条件运算符.c —— 阶段1 / 第 03 课 / 第 17 个文件：条件运算符
 *
 * 编译：gcc 17_条件运算符.c -o ternary_demo
 * 运行：./ternary_demo
 *
 * ====================== 一、语法与基本用法 ======================
 * 条件运算符是 C 里唯一的三目运算符（需要三个操作数），所以常被叫作"三目运算符"：
 *
 *      条件 ? 表达式1 : 表达式2
 *       ↑      ↑        ↑
 *      判断   为真取    为假取
 *
 * 执行流程：
 *      1) 先算"条件"，按"非 0 即真、0 即假"判断
 *      2) 为真 → 取表达式1 的值；为假 → 取表达式2 的值
 *      3) 两个分支只会执行一个（见第三节）
 *
 * 最简单的例子：
 *      int max = (a > b) ? a : b;
 *      printf("%s", pass ? "及格" : "不及格");
 *
 * ====================== 二、它和 if/else 的区别 ======================
 *      if 是"语句"，不能出现在表达式里；
 *      ?: 是"运算符"，本身就是表达式，有值，可以嵌进任何需要值的地方。
 *
 *      if 写法：                        ?: 写法：
 *      if (a > b) max = a;              int max = (a > b) ? a : b;
 *      else       max = b;
 *
 * 什么时候用 ?:：
 *      给变量赋"二选一"的值、在 printf 参数里选文案、函数返回值里做简单判断
 * 什么时候用 if：
 *      分支里有多条语句、有副作用、逻辑复杂、嵌套超过两层
 * 一句话：**能写成"一个值"的用 ?:，要"做动作"的用 if。**
 *
 * ====================== 三、短路特性：只算一个分支 ======================
 * 和 && || 一样，?: 也"短路"：
 *      条件为真 → 表达式2 完全不求值
 *      条件为假 → 表达式1 完全不求值
 *
 * 实际意义：
 *      p != NULL ? p->value : 0      // p 为空时不会解引用，安全
 * 如果把两个分支都先算好再选，空指针就会崩。
 *
 * 反过来说，别在分支里写副作用：
 *      flag ? count++ : count--;     // 能跑，但很难读，改用 if
 *
 * ====================== 四、两个分支的类型会统一 ======================
 * ?: 必须有唯一的结果类型，规则同算术运算：两个分支类型不同时按"谁宽听谁的"统一。
 *
 *      int a = 1; double b = 2.5;
 *      a ? a : b                 →  结果类型是 double
 *      sizeof(1 ? 1 : 2.0) == 8
 *
 * 于是会出现：
 *      int y = 0 ? 3 : 4.5;      // 4.5 先按 double 处理，最后截断成 4
 *
 * ★ 最坑的是有符号与无符号混合：
 *      int neg = -1; unsigned int u = 1;
 *      cond ? neg : u            →  结果类型是 unsigned，neg 变成 4294967295
 * 建议：两个分支保持同类型，不同时先显式转换。
 *
 * ====================== 五、优先级与结合性 ======================
 * 从高到低：
 *      算术 + - * / %  >  比较 < <= > >=  >  &&  >  ||  >  ?:  >  赋值 =
 *
 * ?: 低于 && ||，高于赋值：
 *      flag = a > b ? a : b;     等价于  flag = ((a > b) ? a : b)   ✓
 *
 * ?: 是**右结合**，从右往左配对：
 *      a ? b : c ? d : e         等价于  a ? b : (c ? d : e)
 * 这正是"多级判断"能链式书写的原因，但也容易看晕。
 *
 * ====================== 六、常见用法 ======================
 *      (1) 取最值：    max = (a > b) ? a : b;
 *      (2) 绝对值：    abs = (x < 0) ? -x : x;
 *      (3) 默认值：    name = (p != NULL) ? p : "unknown";
 *      (4) 选文案：    printf("%s", ok ? "成功" : "失败");
 *      (5) 多级判断：  level = score >= 90 ? 'A' : score >= 60 ? 'B' : 'C';
 *      (6) 保护除法：  avg = (n != 0) ? total / n : 0;
 *
 * ====================== 七、常见坑 ======================
 *  1. 嵌套太深                       三目套三目，没人看得懂
 *  2. 分支里写副作用 count++          改成 if
 *  3. 两个分支类型不同                 隐式转换、截断、unsigned 陷阱
 *  4. 用 ?: 代替 if 做"多语句分支"     只能放一个表达式，硬塞很丑
 *  5. 条件里少了括号                   a > b && c > d ? x : y 容易看错
 *  6. 把 == 写成 =                     cond = 1 ? ... 这种在条件里赋值
 *  7. 返回类型不一致的三目              一个分支返回 int，一个返回指针
 *  8. 用三目做一些"炫技"写法           可读性优先
 *  9. 忘记 ?: 也是一个表达式            反过来想：它能当参数，也能当返回值
 * 10. 空指针保护顺序写反                p->v != 0 ? p->v : 0 会崩
 *
 * ====================== 八、实践建议 ======================
 *  - 只在"二选一、取值、无副作用"的场合用 ?:
 *  - 嵌套不超过两层，超过就改 if / switch
 *  - 两个分支尽量同类型，必要时 (double) 显式转换
 *  - 条件里有 && || 时加括号
 *  - 需要多条语句、打印、赋值，一律用 if
 *  - 安全取值时把判空写进条件：p ? p->v : 0
 */

#include <stdio.h>

/* 用来观察"只求值一个分支" */
static int calls = 0;
static int probe(void)
{
    calls++;
    return 1;
}

int main(void)
{
    /* ---------- 1. 基本用法：取较大值 ---------- */
    int a = 10, b = 20;
    int max = (a > b) ? a : b;
    printf("1. a=%d b=%d，较小的是 %d，较大的是 %d\n",
           a, b, (a < b) ? a : b, max);

    /* ---------- 2. 绝对值 ---------- */
    int x = -7;
    int abs_x = (x < 0) ? -x : x;
    printf("2. x=%d，绝对值 = %d\n", x, abs_x);

    /* ---------- 3. 选文案：直接在 printf 参数里用 ---------- */
    int score = 75;
    printf("3. score=%d → %s\n", score, (score >= 60) ? "及格" : "不及格");

    /* ---------- 4. 给可能为空的指针准备默认值 ---------- */
    const char *name = NULL;
    const char *show = (name != NULL) ? name : "未命名";
    printf("4. 指针为 NULL，显示为 \"%s\"\n", show);

    /* ---------- 5. 保护除法：避免除零 ---------- */
    int total = 100, n = 0;
    int avg = (n != 0) ? total / n : 0;
    printf("5. n=0，avg 取默认值 %d（避免除零）\n", avg);

    /* ---------- 6. 短路：只求值一个分支 ---------- */
    calls = 0;
    int r1 = 1 ? probe() : 0;       /* 条件为真，只算左边 */
    printf("6. 1 ? probe() : 0 → 调用 %d 次，结果 %d\n", calls, r1);

    calls = 0;
    int r2 = 0 ? 0 : probe();       /* 条件为假，只算右边 */
    printf("   0 ? 0 : probe() → 调用 %d 次，结果 %d\n", calls, r2);

    calls = 0;
    int r3 = 1 ? 42 : probe();      /* 右边完全不执行 */
    printf("   1 ? 42 : probe() → 调用 %d 次，结果 %d\n", calls, r3);

    /* ---------- 7. 空指针保护（短路带来的安全） ---------- */
    int  value = 99;
    int *p = &value;
    int *q = NULL;
    printf("7. p 有效：%d\n", (p != NULL) ? *p : -1);
    printf("   q 为空：%d（不会解引用 q）\n", (q != NULL) ? *q : -1);

    /* ---------- 8. 两个分支的类型会统一 ---------- */
    int    i1 = 1;
    double d1 = 2.5;
    printf("8. 1 ? 1 : 2.5 的结果是 %.2f（类型提升为 double）\n",
           i1 ? 1 : d1);
    printf("   sizeof(1 ? 1 : 2.0) = %zu 字节\n", sizeof(1 ? 1 : 2.0));
    double dval = 4.9;              /* 用变量中转，避免字面量截断警告 */
    int trunc = 0 ? 3 : dval;
    printf("   0 ? 3 : 4.9 赋给 int → %d（截断，不是四舍五入）\n", trunc);

    /* 有符号与无符号混合：结果类型是 unsigned，-1 变成巨大正数 */
    int          neg = -1;
    unsigned int u   = 1;
    unsigned int mixed = i1 ? neg : u;
    printf("   1 ? (-1) : 1u → %u（-1 被转成无符号）\n", mixed);
    printf("   建议：两个分支保持同类型，必要时显式转换\n");

    /* ---------- 9. 多级判断（右结合） ---------- */
    int s1 = 95, s2 = 75, s3 = 50;
    char g1 = (s1 >= 90) ? 'A' : (s1 >= 60) ? 'B' : 'C';
    char g2 = (s2 >= 90) ? 'A' : (s2 >= 60) ? 'B' : 'C';
    char g3 = (s3 >= 90) ? 'A' : (s3 >= 60) ? 'B' : 'C';
    printf("9. %d→%c  %d→%c  %d→%c（多级判断，右结合）\n",
           s1, g1, s2, g2, s3, g3);
    printf("   a ? b : c ? d : e 等价于 a ? b : (c ? d : e)\n");
    printf("   但嵌套超过两层就该改用 if，否则很难读\n");

    /* ---------- 10. 优先级：?: 低于 ||，高于 = ---------- */
    int t = 1, f = 0;
    int prio = t || f ? 100 : 200;   /* (t || f) ? 100 : 200 */
    printf("10. t || f ? 100 : 200 = %d（先算 ||，再算 ?:）\n", prio);
    printf("    赋值优先级最低，所以 flag = a > b ? a : b 是安全的\n");
    printf("    但 x = a ? b : c = d 这种写法要避免，加括号或改 if\n");

    /* ---------- 11. ?: 可以作为函数参数和返回值 ---------- */
    /* 它本身是表达式，所以哪儿都能放 */
    printf("11. 直接当参数：%d\n", (a > b) ? a : b);
    printf("    也能串联：%s\n", (a > b) ? ((a > 15) ? "a 很大" : "a 较大")
                                         : "b 较大");

    /* ---------- 12. 反例：不该用 ?: 的地方 ---------- */
    /* 分支里有副作用、多条语句，就别硬塞：
     *     ok ? printf("成功\n") : printf("失败\n");   // 能跑，但不如 if 清楚
     *     ok ? (a = 1, b = 2) : (a = 3, b = 4);       // 逗号表达式，别折磨同事
     */
    printf("12. 分支里有多个动作时，用 if 更清楚\n");

    /* ---------- 13. 小结 ---------- */
    printf("13. 小结：\n");
    printf("    语法：条件 ? 为真取值 : 为假取值\n");
    printf("    是表达式，有值，能当参数、能赋给变量\n");
    printf("    只求值一个分支（短路），可用来做空指针保护\n");
    printf("    两个分支类型会统一，注意截断和 unsigned 陷阱\n");
    printf("    优先级低于 && ||，高于赋值；嵌套多了就改 if\n");

    return 0;
}

