/*
 * 01_hello.c —— 阶段1 / 第 01 课 / 第 01 个文件（最先看这篇）
 *
 * 作用：在终端打印一行 "Hello，C！"。
 * 编译：gcc 01_hello.c -o hello    （-o hello 指定输出的可执行文件名）
 *       如果不写 -o，gcc 会使用默认名字 a.out（Unix/Linux/macOS），Windows(MinGW) 下是 a.exe。
 *       a.out 是 "assembler output"（汇编器输出）的历史遗留名字。
 * 运行：./hello   （用默认名时则运行 ./a.out）
 *
 * 注意：编译后得到的文件叫可执行文件，Linux/macOS 上没有扩展名要求，
 *       一般不带 .exe；Windows 上才习惯用 .exe 结尾。
 */

/* #include 是"预处理指令"，在真正编译之前由预处理器执行。
 * 它的作用是把标准库头文件 stdio.h 的内容原封不动地"粘贴"到这一行所在的位置。
 * 为什么要包含它：下面的 printf 函数是"声明"在 stdio.h 里的，
 * 不包含它编译器就不知道 printf 的返回值和参数长什么样，会报 implicit declaration 警告甚至错误。
 * 尖括号 <> 表示"到系统头文件目录里去找"；如果是自己写的头文件，则用双引号 ""。 */
#include <stdio.h>

/* main 是整个 C 程序的入口（起点）。程序运行时操作系统就是从 main 开始执行的。
 *
 * int：返回值类型。main 返回一个整数给操作系统，用来表示程序是否正常结束。
 *      return 0 表示"成功"，返回非 0（通常 1）表示"出错了"。
 * main()：括号里是参数列表，这里为空表示不接收命令行参数。
 *      完整写法是 main(int argc, char *argv[])，初学阶段先不写。
 */
int main() {

  /* printf = print formatted（格式化打印），来自标准库。
   * 它把双引号里的字符串输出到标准输出（终端屏幕）。
   *
   * "Hello，C！\n" 中：
   *   - Hello，C！ 是普通字符，原样输出；
   *   - \n 是"转义字符"，表示换行（newline）。它只占一个字符，但会让光标移到下一行开头。
   *     如果没有 \n，终端提示符会紧跟在输出内容后面，看起来不整洁。
   * C 语言里字符串必须用英文双引号包裹，且不能跨行书写。
   *
   * 语句末尾的分号 ; 是 C 语句的结束标志，C 语言强制要求，不能省略。
   * 这行的缩进（前面 2 个空格）只是为了可读性，C 语言本身不靠缩进划分代码块。 */
    printf("Hello，C！\n");
    printf("Hello，B！");

  /* 把 0 返回给操作系统，表示程序正常结束。
   * 如果省略这一句，在 C99 及以后的标准里 main 会隐式返回 0，
   * 但显式写出是更好的习惯，含义更清晰。 */
    return 0;

/* } 结束 main 函数体。函数体必须用一对花括号 {} 包起来，
 * 左括号开始、右括号结束，两者一一对应。 */
}
