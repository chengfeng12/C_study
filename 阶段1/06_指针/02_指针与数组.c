/*
 * 02_指针与数组.c —— 阶段1 / 第 06 课 / 第 02 个文件：指针与数组
 *
 * 编译：gcc -std=c99 -Wall -Wextra 02_指针与数组.c -o bin/02_指针与数组
 * 运行：./bin/02_指针与数组
 *
 * 01 篇讲了"指针是什么"，这一篇讲它最常打交道的邻居：数组。
 * 只打印地址差值，不打印具体地址（地址每次运行都变，差值才稳定）；
 * 越界的读只写在注释里，程序里不跑。
 *
 * ====================== 一、数组名有两种身份 ======================
 * 在**大多数表达式**里，数组名会"退化"（decay）成"指向首元素的指针"：
 *
 *      int a[5];
 *      a        ≡  &a[0]        类型 int *
 *
 * 但这不是数组名的全部。下面**三种情况**它不退化成指针：
 *
 *  (1) sizeof(a)      得到整个数组的字节数，而不是指针的 8 字节
 *  (2) &a             得到"整个数组的地址"，类型是 int (*)[5]
 *  (3) 字符串字面量初始化 char s[] = "hi";
 *
 * 换句话说：数组名只在"需要值"的地方退化成指针，
 * 而 sizeof 和 & 要的是"对象本身"，所以它们看到的是数组。
 *
 * ★ 推论：函数参数 `void f(int a[5])` 里的 a 是**指针**，不是数组。
 *   所以函数里 sizeof(a) 永远是 8，长度必须另外传（第 05 课第 01 篇讲过这个坑）。
 *
 * ====================== 二、指针算术：加减的是"元素"，不是字节 ======================
 * 设 int *p = a;（a 是 int 数组）
 *
 *      p + n       往后第 n 个元素，地址实际加 n * sizeof(int)
 *      p - n       往前第 n 个元素
 *      p++ / p--   挪一个元素（数组名不能这么干，p 可以）
 *      p1 - p2     两个指针相隔几个元素（类型是 ptrdiff_t，不是 int）
 *      p1 < p2     **同一数组内**可以比较大小
 *      *p          解引用，取那个元素
 *
 * 三条边界规则：
 *
 *  1) 指针运算只保证在"同一个数组（或 one-past-the-end）"内有意义。
 *     两个不同数组的指针相减是未定义行为，只能安全地做 == / != 比较。
 *
 *  2) a + n（n 等于数组长度）是合法的：这叫 one-past-the-end，
 *     它表示"最后一个元素的下一个"，**可以算、可以比较、不能解引用**。
 *     C 用它来表达"左闭右开区间"，reverse(a, a + n) 这种写法才成立。
 *
 *  3) 指针减法算的是**元素个数**，不是字节数。要字节数得先转 char *
 *     （`(char *)p1 - (char *)p2`）。为什么只有 char * 能这样"通用地看内存"，
 *     见 08 篇第五节。
 *
 * ====================== 三、下标与指针的四种等价写法 ======================
 *      a[i]  ≡  *(a + i)  ≡  p[i]  ≡  *(p + i)
 *
 * 只要 p 指向数组首元素，四种写法完全一样，连编译出的汇编都差不多。
 * 注意 `p[i]` 里 p 是指针也能用下标 —— 下标运算本质就是"指针 + 偏移 + 解引用"。
 *
 * 所以遍历有四种写法（第 3 节代码里全跑一遍）：
 *
 *      for (int i = 0; i < n; i++)  sum += a[i];          // 下标
 *      for (int i = 0; i < n; i++)  sum += p[i];          // 指针 + 下标
 *      for (int i = 0; i < n; i++)  sum += *(a + i);      // 解引用
 *      for (int *q = a; q < a + n; q++)  sum += *q;       // 指针自增
 *
 * 工程上建议：**默认用下标**，可读性最好；只有在"移动窗口""原地双指针"
 * 这类算法里，指针写法才真的更清楚。
 *
 * ====================== 四、a、&a、&a[0] 三者关系 ======================
 *      int a[5];
 *
 *      表达式    类型           值         +1 走
 *      --------  -------------  ---------  ------
 *      a         int *          首元素地址   4 字节（一个元素）
 *      &a[0]     int *          首元素地址   4 字节（一个元素）
 *      &a        int (*)[5]     首元素地址   20 字节（整个数组）
 *
 * 三者的**值完全相同**，区别只在类型 —— 而类型决定步长。
 * 这就是 "a + 1 走 4 字节、&a + 1 走 20 字节" 的原因。
 *
 * ★ 本节代码用 `(char *)` 把指针换成"按字节计数"的视角来验证步长，这是合法的：
 *   标准允许任何对象按 char / unsigned char 逐字节访问（见 08 篇第五节）。
 *
 * ====================== 五、指针数组 vs 数组指针（差一个括号） ======================
 *      int *p[3];        // 数组，3 个元素，每个元素是 int *
 *      int (*p)[3];      // 指针，指向"int[3]"这种数组
 *
 * 读法（右左法则）：从变量名往外读
 *
 *      int *p[3]     →  p 是数组[3]，元素是 int *        → 指针数组
 *      int (*p)[3]   →  p 是指针，指向 int[3]            → 数组指针
 *
 * 括号的作用是"先把 * 和 p 绑在一起"。没有括号时 [] 的优先级高于 *。
 *
 * 用途区别：
 *
 *      指针数组 int *a[10]     常用来"存一组字符串/一组指针"
 *      数组指针 int (*p)[3]    常用来"指向二维数组的一行"
 *
 * ====================== 六、二维数组与行指针 ======================
 *      int m[2][3];
 *      m        退化成 int (*)[3]       指向第一行
 *      m[i]     退化成 int *            指向第 i 行首元素
 *      m[i][j]  是 int
 *
 * 所以遍历二维数组可以写成：
 *
 *      int (*r)[3] = m;
 *      for (int i = 0; i < 2; i++)
 *          for (int j = 0; j < 3; j++)
 *              printf("%d ", r[i][j]);
 *
 * r + 1 走 12 字节（一整行），r[i] 走 4 字节（一个元素）。
 * 这和第 05 课第 04 篇说过的"a 是行指针、a[i] 是元素指针"是同一件事。
 *
 * ★ 注意：**int ** 不能接二维数组**。二维数组是一整块连续内存，
 *   没有"指针表"这一层；int ** 需要真的存在一张指针数组才行（05 篇细讲）。
 *
 * ====================== 七、常见坑 ======================
 *  1. 以为函数里的 sizeof(a) 是数组大小      形参已退化成指针
 *  2. 数组名自增                    a++ ✗（数组名是常量）；用 p = a 之后 p++ ✓
 *  3. 用 a + n 解引用               合法地址，非法访问；one-past 只能算不能读
 *  4. 不同数组的指针相减            未定义行为；只有 == / != 是安全的
 *  5. 指针减法当字节数用            p1 - p2 是元素个数；字节差要转 char *
 *  6. 混淆 int *p[3] 与 int (*p)[3] 一个是指针数组，一个是数组指针
 *  7. 用 int ** 接二维数组          类型对不上，运行期读到错误地址
 *  8. sizeof(a) / sizeof(a[0]) 写错  a[0] 是元素时才对；二维里 a[0] 是一行
 *  9. 指针越界只查了上界            i >= 0 和 i < n 两头都要查
 * 10. 把字符串字面量赋给 char *    再改它会崩（03 篇详讲）
 *
 * ====================== 八、实践建议 ======================
 *  - 长度一律用 `sizeof(a) / sizeof(a[0])` 算，别手写魔法数
 *  - 传数组给函数就写 `void f(int *a, int n)`，长度显式传
 *  - 循环边界优先用 `i < n`，指针版用 `q < a + n`（半开区间，不用 <=）
 *  - 需要"指向一行"就写 `int (*row)[COLS]`，别硬拿 int * 凑
 *  - 只读参数加 const：`void f(const int *a, int n)`
 *  - 原地算法（逆序、快排分区）用双指针，比下标更直观
 *  - 别返回指向局部数组的指针（04 篇详讲）
 */

#include <stdio.h>

#define N 5

/* 打印数组：只读，所以加 const */
static void print_int_array(const int *a, int n)
{
    for (int i = 0; i < n; i++)
        printf("%d ", a[i]);
    printf("\n");
}

/* 双指针原地逆序：区间是 [first, last)，左闭右开 */
static void reverse(int *first, int *last)
{
    while (first < last) {
        --last;                          /* 先退到最后一个有效元素 */
        int t = *first;
        *first = *last;
        *last = t;
        ++first;
    }
}

int main(void)
{
    /* ---------- 1. 数组名什么时候不是指针 ---------- */
    printf("1. 数组名在 sizeof 和 & 面前不退化成指针\n");
    int a[N] = {1, 2, 3, 4, 5};
    int *pa = a;                         /* 一参与运算，数组名就退化成 &a[0] */
    printf("   sizeof(a)     = %zu 字节：整个数组（%d 个 int）\n", sizeof(a), N);
    printf("   sizeof(pa)    = %zu 字节：退化后的 int *，只剩指针大小\n", sizeof(pa));
    printf("   sizeof(&a)    = %zu 字节：&a 是 int (*)[%d]\n", sizeof(&a), N);
    printf("   sizeof(a[0])  = %zu 字节：一个元素\n", sizeof(a[0]));

    /* ---------- 2. 指针算术 ---------- */
    printf("2. 指针算术：加减的是元素，不是字节\n");
    int *p = a;                          /* a 退化成 &a[0] */
    int *end = a + N;                    /* one-past-the-end：合法但不解引用 */
    printf("   p = a，end = a + %d\n", N);
    printf("   end - p = %ld（元素个数，单位不是字节）\n", (long)(end - p));
    printf("   p + 2 指向 a[2]，*(p + 2) = %d\n", *(p + 2));
    printf("   同一数组内可以比较：p < end 为%s\n", (p < end) ? "真" : "假");

    /* ---------- 3. 遍历的四种等价写法 ---------- */
    printf("3. 遍历的四种写法，结果完全一样\n");
    printf("   ① 下标 a[i]    ：");
    print_int_array(a, N);
    printf("   ② 指针 p[i]    ：");
    for (int i = 0; i < N; i++)
        printf("%d ", p[i]);             /* 指针也能用下标 */
    printf("\n");
    printf("   ③ 解引用 *(a+i)：");
    for (int i = 0; i < N; i++)
        printf("%d ", *(a + i));
    printf("\n");
    printf("   ④ 指针自增 *q  ：");
    for (int *q = a; q < a + N; q++)     /* 改的是 q，不是 a */
        printf("%d ", *q);
    printf("\n");

    /* ---------- 4. a、&a、&a[0]：值一样、步长不同 ---------- */
    printf("4. 值是同一个，类型决定步长\n");
    printf("   a    + 1 走 %ld 字节（一个 int）\n",
           (long)((char *)(a + 1) - (char *)a));
    printf("   &a[0]+ 1 走 %ld 字节（一个 int，和上面相同）\n",
           (long)((char *)(&a[0] + 1) - (char *)&a[0]));
    printf("   &a   + 1 走 %ld 字节（整个数组 = %d × %zu）\n",
           (long)((char *)(&a + 1) - (char *)&a), N, sizeof(int));
    printf("   类型：a 和 &a[0] 是 int *，&a 是 int (*)[%d]\n", N);

    /* ---------- 5. 指针数组 vs 数组指针 ---------- */
    printf("5. int *p[3] 与 int (*p)[3] 差一个括号，差一个世界\n");
    int x = 11, y = 22, z = 33;
    int *parr[3] = {&x, &y, &z};         /* 指针数组：3 个元素，每个是 int * */
    int row[3] = {7, 8, 9};
    int (*prow)  [3] = &row;               /* 数组指针：1 个指针，指向 int[3] */
    printf("   int *parr[3]   → sizeof = %zu（3 个指针），sizeof(parr[0]) = %zu\n",
           sizeof(parr), sizeof(parr[0]));
    printf("      元素是指针：*parr[0] = %d（先取 parr[0]，再解引用）\n", *parr[0]);
    printf("   int (*prow)[3] → sizeof = %zu（只是 1 个指针）\n", sizeof(prow));
    printf("      解引用一层拿到数组：(*prow)[1] = %d，等价 prow[0][1]\n", (*prow)[1]);
    printf("      步长：prow + 1 走 %ld 字节（整个 int[3]）\n",
           (long)((char *)(prow + 1) - (char *)prow));

    /* ---------- 6. 二维数组就是"行指针 + 下标" ---------- */
    printf("6. 二维数组：m 退化成 int (*)[3]（行指针）\n");
    int m[2][3] = {{1, 2, 3}, {4, 5, 6}};
    int (*r)[3] = m;                     /* 指向第一行 */
    for (int i = 0; i < 2; i++) {
        printf("   第 %d 行：", i);
        for (int j = 0; j < 3; j++)
            printf("%d ", r[i][j]);
        printf("   （r + %d 走 %ld 字节）\n",
               i, (long)((char *)(r + i) - (char *)r));
    }
    printf("   sizeof(m) = %zu，sizeof(m[0]) = %zu（一行），sizeof(m[0][0]) = %zu\n",
           sizeof(m), sizeof(m[0]), sizeof(m[0][0]));

    /* ---------- 7. one-past-the-end：能算不能读 ---------- */
    printf("7. one-past-the-end：a + %d 是合法地址，但 *(a + %d) 越界\n", N, N);
    int *edge = a + N;                   /* 合法：只算地址 */
    printf("   a + %d 与 &a[%d] + 1 相等吗？%s\n", N, N - 1,
           (edge == &a[N - 1] + 1) ? "相等" : "不相等");
    printf("   它专门用来做循环上界：q < a + n，这样最后一个元素刚好被处理到\n");
    printf("   注意 (a + %d) - a = %ld，说明这个「越界」地址在算术上是允许的\n",
           N, (long)((a + N) - a));

    /* ---------- 8. 双指针原地逆序 ---------- */
    printf("8. 双指针原地逆序：只用两个指针，不开新数组\n");
    int v[6] = {1, 2, 3, 4, 5, 6};
    printf("   原数组：");
    print_int_array(v, 6);
    reverse(v, v + 6);                   /* 传的是"首"和"末尾后一个" */
    printf("   逆序后：");
    print_int_array(v, 6);
    printf("   reverse(v, v + 6) 的右边界是 one-past，所以不用写 v + 5\n");

    /* ---------- 9. 小结 ---------- */
    printf("9. 小结：\n");
    printf("    数组名只在 sizeof、& 和字面量初始化时不退化\n");
    printf("    a[i] ≡ *(a + i) ≡ p[i] ≡ *(p + i)，本质都是指针加法\n");
    printf("    指针加 N 走 N 个元素；指针相减得元素个数\n");
    printf("    a 与 &a 值相同、步长差一整个数组\n");
    printf("    int *p[3] 是指针数组，int (*p)[3] 是数组指针\n");
    printf("    二维数组退化成 int (*)[列数]，int ** 接不了\n");

    return 0;
}

