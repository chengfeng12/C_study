/*
 * 07_指针的常见错误与调试.c —— 阶段1 / 第 06 课 / 第 07 个文件：指针的常见错误与调试
 *
 * 编译：gcc -std=c99 -Wall -Wextra 07_指针的常见错误与调试.c -o bin/07_指针的常见错误与调试
 * 运行：./bin/07_指针的常见错误与调试
 *
 * ★ 本文件默认**只演示安全写法**，所有会真正触发未定义行为的代码都放在
 *   `#ifdef DEMO_UB` 里，默认不参与编译。想看崩溃现场自己去打开：
 *
 *       gcc -std=c99 -Wall -Wextra -DDEMO_UB 07_指针的常见错误与调试.c -o bin/07_ub
 *       ./bin/07_ub          # 大概率段错误/乱码，属于预期
 *
 *   打开后出现 -Wuninitialized 之类的警告也是预期的（那段就是要复现错误）。
 *
 * ====================== 一、四类致命错误 ======================
 *      ┌──────────┬────────────────────┬────────────────────────────┐
 *      │ 类型     │ 典型代码           │ 后果                       │
 *      ├──────────┼────────────────────┼────────────────────────────┤
 *      │ 野指针   │ int *p; *p = 1;    │ 写到随机地址，可能不崩但改坏数据 │
 *      │ 空指针   │ int *p=NULL; *p=1; │ 立即段错误（地址 0 不可访问） │
 *      │ 悬垂指针 │ free(p); *p;       │ 读写已归还的内存，行为不可预测 │
 *      │ 越界     │ a[n] = 1;          │ 破坏相邻数据 / 栈保护报错     │
 *      └──────────┴────────────────────┴────────────────────────────┘
 *
 * 共同点：**编译器一条都不报**。C 把"你知不知道自己在干什么"完全交给你。
 *
 * ====================== 二、空指针：唯一能安全判断的"坏指针" ======================
 *      int *p = NULL;        // NULL 是宏，通常展开为 ((void *)0)
 *      if (p != NULL) { ... }    // 或者 if (p) { ... }
 *
 * 空指针的好处是**可以被检查**：野指针和悬垂指针都没有可靠的检查手段
 * （它们的值看起来"像个正常地址"）。所以规矩是：
 *
 *      不用了就置 NULL，用之前先判空。
 *
 * 这也是 malloc 的规矩：申请失败返回 NULL，所以必须判空再用。
 *
 * ====================== 三、野指针：C 不会帮你初始化 ======================
 *      int *p;             // 值 = 栈上残留的随机数据
 *      *p = 1;             // ✗ 往一个随机地址写 4 个字节
 *
 * 危险在于它可能"碰巧能写"——程序不崩，但把别的变量悄悄改掉。
 * 这种 bug 的表现是"数据莫名其妙变了"，比崩溃难查十倍。
 *
 * 三条防线：
 *      1) 定义时就初始化：int *p = NULL;
 *      2) 打开 -Wall，它会报"变量可能未初始化"
 *      3) 静态分析/ASAN 能在运行时抓到一部分
 *
 * ====================== 四、悬垂指针（dangling pointer） ======================
 * 指针还在，但它指向的空间已经不属于你了。三种来源：
 *
 *  (1) 指向局部变量，函数已经返回
 *          int *bad(void) { int a[3] = {1,2,3}; return a; }   // ✗
 *      函数一返回，a 的栈空间就被回收，返回的地址立刻悬垂。
 *      gcc 会用 -Wreturn-stack-address 提醒你（这条警告一定要当真）。
 *
 *  (2) 指向 free 过的堆内存
 *          int *p = malloc(sizeof *p);
 *          free(p);
 *          *p = 1;              // ✗ use-after-free
 *      对策：free 之后立刻 p = NULL。
 *
 *  (3) 指向的数组/内存被重新分配、被覆盖
 *          realloc 之后旧地址可能失效；动态数组扩容后旧指针全部作废。
 *
 * 本篇只讲"怎么发现和避免"，至于"要安全地返回一块数据该怎么做"
 * （调用方传缓冲区 / static / 为什么不能返回局部地址），见 04 篇第六节。
 *
 * ====================== 五、越界与 one-past-the-end ======================
 *      int a[4];
 *      a[0] ~ a[3]        合法
 *      a + 4              合法地址（one-past），能算、能比较，不能解引用
 *      a[4]、*(a + 4)     越界，未定义行为
 *
 * 为什么 a + 4 合法？因为 C 要支持"左闭右开区间"的写法：
 *
 *      for (int *p = a; p != a + 4; p++) ...
 *
 * 但"地址合法"不等于"能访问"。这条边界是 C 里少数明确规定的灰色地带。
 *
 * 越界的实际危害：
 *  - 写到数组后面的变量 → 数据被改，现象诡异
 *  - 写到栈保护字（canary）→ 程序带着 "stack smashing detected" 退出
 *  - 写到堆的元数据 → 下一次 malloc/free 时崩在毫不相干的地方
 *
 * ====================== 六、工具：编译器查不到的，交给运行时 ======================
 *
 *  (1) 编译期（默认就该开）
 *          gcc -std=c99 -Wall -Wextra
 *      能查：类型不匹配、格式串不匹配、未初始化变量、返回局部地址、
 *            数组越界访问常量下标（部分情况）
 *
 *  (2) AddressSanitizer（首选，开销小、报错清楚）
 *          gcc -g -fsanitize=address -o bin/x x.c
 *      能查：堆/栈越界、use-after-free、double-free、内存泄漏（配合 LSAN）
 *
 *  (3) valgrind（Linux/macOS 老牌工具，不需要重编译）
 *          valgrind --leak-check=full ./bin/x
 *
 *  (4) UndefinedBehaviorSanitizer（抓有符号溢出、空指针解引用等）
 *          gcc -g -fsanitize=undefined
 *
 *  (5) gdb / lldb：崩了以后 `bt` 看调用栈，定位是哪一行
 *
 * ====================== 七、防御性编程清单 ======================
 *  1. 指针定义即初始化，没有目标写 NULL
 *  2. 解引用前判空，尤其是 malloc 的返回值
 *  3. free 之后立刻置 NULL
 *  4. 函数不返回局部变量的地址
 *  5. 循环边界写成 `i < n`，别用 `<=`
 *  6. 长度和指针成对传递：`void f(int *a, size_t n)`
 *  7. 只读参数加 const，让编译器守住契约
 *  8. 结构体里有指针成员，注释写清"谁负责 free"
 *  9. 关键代码段跑一遍 ASAN，再跑一遍正常编译
 * 10. 别用强制类型转换去"消掉"警告 —— 警告通常是对的
 *
 * ====================== 八、心态 ======================
 * C 的指针不难在语法，难在"没有安全网"。
 * 别指望编译器帮你查越界，而是养成三个肌肉记忆：
 *
 *      初始化 → 判空 → 用完置 NULL
 *
 * 再配合 ASAN 跑一遍，90% 的指针 bug 会自己跳出来。
 */

#include <stdio.h>
#include <stdlib.h>

/* 判空和使用写在一起：调用方永远不用重复这段逻辑 */
static void use_ptr(const int *p)
{
    if (p != NULL)
        printf("   解引用成功：*p = %d\n", *p);
    else
        printf("   p 是 NULL，跳过解引用（硬写 *p 就是段错误）\n");
}

/* 「返回指针的三种做法」（调用方传缓冲区 / static 数组 / ✗ 局部变量地址）
 * 已在 04 篇第六节讲透，本文不再重复代码，只保留"别返回局部地址"这一条结论。
 */

int main(void)
{
    /* ---------- 1. 空指针：唯一能安全判断的坏指针 ---------- */
    printf("1. 空指针：解引用前先判空\n");
    int v = 7;
    use_ptr(&v);
    use_ptr(NULL);
    printf("   空指针 = 指向 0 号地址的指针，而 0 号地址永远不可访问\n");
    printf("   野指针和悬垂指针没法判断（值看着像正常地址），所以只能靠规矩\n");

    /* ---------- 2. 野指针：不声明，只讲 ---------- */
    printf("2. 野指针：C 不会帮你初始化\n");
    printf("   int *p; 的值是栈上残留数据，解引用就是往随机地址读写\n");
    printf("   所以本程序连这样的变量都不声明 —— 读未初始化的指针值本身就是未定义行为\n");
    printf("   防线：定义即置 NULL + 打开 -Wall\n");

    /* ---------- 3. 悬垂指针：free 之后立刻置 NULL ---------- */
    printf("3. 悬垂指针：free 之后立刻置 NULL\n");
    int *h = malloc(sizeof *h);           /* 只申请一个 int */
    if (h == NULL) {                      /* ★ 必须判空 */
        printf("   malloc 返回 NULL，直接结束\n");
        return 1;
    }
    *h = 100;
    printf("   malloc 之后 *h = %d\n", *h);
    free(h);
    h = NULL;                             /* ★ 关键一步 */
    printf("   free 之后置 NULL：h == NULL 为%s\n", (h == NULL) ? "真" : "假");
    printf("   只 free 不置 NULL，指针还在，但内存已归还 —— 这就是悬垂\n");
    printf("   悬垂的三个来源：① 指向已返回的局部变量 ② 指向已 free 的堆\n");
    printf("                   ③ 指向被 realloc / 扩容作废的旧地址\n");

    /* ---------- 4. 越界与 one-past-the-end ---------- */
    printf("4. 越界：合法下标 0 ~ n-1\n");
    int a[4] = {10, 20, 30, 40};
    int n = (int)(sizeof(a) / sizeof(a[0]));
    printf("   n = %d，可访问 a[0] ~ a[%d]\n", n, n - 1);
    int *end = a + n;                     /* one-past：合法地址 */
    printf("   end - a = %ld：可以算出这个边界地址\n", (long)(end - a));
    printf("   但 *(a + %d) 是越界读，属于未定义行为（本程序不跑）\n", n);
    printf("   写越界的危害：改坏相邻变量、踩坏栈保护字、破坏堆元数据\n");

    /* ---------- 5. 编译器能查什么、查不了什么 ---------- */
    printf("5. 静态检查 vs 运行时检查\n");
    printf("   能查（-Wall -Wextra）：类型不匹配、格式串、未初始化变量、\n");
    printf("                            返回局部变量地址（-Wreturn-stack-address）\n");
    printf("   查不了：越界、野指针、悬垂、double free\n");
    printf("   ASAN    ：gcc -g -fsanitize=address -o bin/x x.c\n");
    printf("   UBSAN   ：gcc -g -fsanitize=undefined\n");
    printf("   valgrind：valgrind --leak-check=full ./bin/x\n");
    printf("   崩了先看调用栈：gdb ./bin/x 然后 run / bt\n");

    /* ---------- 6. 危险代码：默认不编译 ---------- */
#ifdef DEMO_UB
    printf("6. DEMO_UB 已打开：下面三行都是未定义行为，崩了是预期结果\n");
    int *wild;                            /* 野指针（未初始化，-Wall 会警告） */
    *wild = 1;                            /* ① 往随机地址写 */
    printf("   ① 写完野指针还没崩？那只是运气好\n");
    int *np = NULL;
    printf("   ② 准备解引用空指针……\n");
    printf("   值 = %d\n", *np);            /* ② 空指针解引用，必崩 */
    a[n + 5] = 0;                         /* ③ 越界写 */
    printf("   ③ 越界写已完成\n");
#else
    printf("6. 危险代码默认不编译\n");
    printf("   打开方式：gcc -std=c99 -DDEMO_UB 07_指针的常见错误与调试.c -o bin/07_ub\n");
    printf("   未定义行为的含义：标准不保证任何结果 —— 可能崩、可能静默改数据，\n");
    printf("   也可能在这台机器上正常、换台机器就崩。所以不能靠「跑通了」判断对错\n");
#endif

    /* ---------- 7. 小结 ---------- */
    printf("7. 小结：\n");
    printf("    四类致命错误：野指针、空指针、悬垂指针、越界，编译器都不报\n");
    printf("    只有空指针能被可靠检查，所以：初始化 → 判空 → 用完置 NULL\n");
    printf("    不返回局部变量地址；要返回就用调用方缓冲区或 static\n");
    printf("    one-past 地址合法但不能解引用，循环边界用它\n");
    printf("    越界/悬垂靠 ASAN 抓：gcc -g -fsanitize=address\n");

    return 0;
}

