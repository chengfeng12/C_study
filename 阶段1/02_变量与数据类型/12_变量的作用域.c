/*
 * 12_变量的作用域.c —— 阶段1 / 第 02 课 / 第 12 个文件：变量的作用域
 *
 * 编译：gcc 12_变量的作用域.c -o scope_demo
 * 运行：./scope_demo
 *
 * ========================= 一、什么是作用域 =========================
 * 作用域（scope）= 一个名字"在代码的哪个范围内可见、能用"。
 * 出了这个范围，名字就不存在了，写它编译器直接报错：
 *      error: 'x' undeclared (first use in this function)
 *
 * ★ 必须先分清两个容易混的概念：
 *      作用域（scope）     名字"看得见"的范围      —— 编译期概念
 *      生命周期（lifetime）变量"活着"的时间      —— 运行期概念
 *   两者相互独立，可以组合出四种情况，见第七节。
 *
 * C 语言一共有四种作用域（C 标准术语，考试常考）：
 *      1) 块作用域   block scope      { } 里面，最常见
 *      2) 文件作用域 file scope       所有函数外面定义的全局变量
 *      3) 函数作用域 function scope   只有 goto 的标签属于这种
 *      4) 原型作用域 prototype scope  函数原型括号里的参数名
 *
 * ========================= 二、块作用域（最常见） =========================
 * 一对花括号 { } 就是一个"块"（block），也叫复合语句。
 * 在块里定义的变量：
 *      作用域：从"定义那一行"开始，到配对的 } 结束
 *      生命周期：进入块时创建（在栈上分配），离开块时销毁
 *
 * 常见的块：
 *      函数体本身
 *      if / else 的分支
 *      for / while / do-while 的循环体
 *      单独写的一对 { }（用来限定变量范围，很实用）
 *
 * ★ 两个细节一定要注意：
 *   (1) 作用域从"声明点"开始，不是从块的开头开始
 *           {
 *               printf("%d", x);   // ✗ 此时 x 还没声明
 *               int x = 1;         // 声明点从这里开始
 *           }
 *   (2) 出了 } 名字就消失，即使程序还在同一个函数里
 *           {
 *               int tmp = 1;
 *           }
 *           printf("%d", tmp);     // ✗ 报错：tmp 已不存在
 *
 * ★ 好处：变量定义得越晚、范围越小，越不容易被误用，也越容易看出它属于谁。
 *   这就是所谓"最小作用域原则"。
 *
 * ======================= 三、文件作用域（全局变量） =======================
 * 在所有函数外面定义的变量，作用域是"整个文件"：
 *      int global_count = 0;          // 从定义处到文件末尾都可见
 *      static int file_private = 0;   // 同样文件内可见，但链接属性不同
 *
 * 全局变量的问题：
 *      1) 谁都能改，改出 bug 很难查
 *      2) 名字容易和别处的重名（尤其多个 .c 文件一起编译时）
 *      3) 程序一启动就存在，一直占内存
 * 所以原则是：能局部就局部，全局越少越好。
 *
 * ★ 3.1 static 修饰全局变量：把"可见范围"限制在本文件
 *      static int file_private = 0;
 *   别的 .c 文件即使写 extern int file_private; 也链接不到它。
 *   这叫"内部链接（internal linkage）"，相当于给文件加了个私有关键字，
 *   是 C 里避免命名冲突最常用的手段。
 *
 * ★ 3.2 extern：声明"这个变量在别的文件里定义了"
 *      extern int other_file_var;     // 只声明，不分配内存
 *   它让编译器先认可这个名字，真正的定义（分配内存）在另一个 .c 文件里。
 *   注意区分：
 *      int x = 1;        // 定义：分配内存
 *      extern int x;     // 声明：不分配内存，告诉编译器"别处有"
 *
 * ====================== 四、函数作用域（只有 goto 标签） ======================
 * 这是 C 里唯一一种"函数作用域"的东西：goto 的标签。
 *      void f(void) {
 *          goto end;      // 可以跳到函数内任意位置的标签
 *      end:               // 标签在整个函数内可见，不受花括号限制
 *          return;
 *      }
 * 特点：
 *      1) 标签的作用域是整个函数，哪怕它写在内层块里
 *      2) 标签不能重名（同一函数内）
 *      3) 现代 C 很少用 goto，除了"多层循环一次性跳出"和"统一清理资源"
 * 局部变量则是块作用域，所以：
 *      标签看得见 ≠ 变量看得见，跳过去之后引用的变量可能还没初始化。
 *
 * ==================== 五、原型作用域（函数原型里的参数名） ====================
 *      int add(int a, int b);       // 这里的 a、b 只在原型这一行有效
 *      int add(int, int);           // 完全等价，参数名可以直接省略
 * 参数名纯粹是给人看的提示（方便阅读），编译器根本不关心，
 * 而且它和函数定义里的参数名**没有任何关系**：
 *      int add(int x, int y);       // 原型用 x、y
 *      int add(int a, int b) { ... }  // 定义用 a、b，完全合法
 * 所以原型里的参数名写不写、写什么都行，但建议写，可读性好。
 *
 * ====================== 六、同名冲突：遮蔽（shadowing） ======================
 * C 允许内层定义和外层同名的变量，此时内层"遮蔽"（shadow）外层：
 *      int v = 1;              // 外层
 *      {
 *          int v = 2;          // 内层，遮蔽外层
 *          // 这里访问到的 v 是 2，外层的 v 被"挡住"了
 *      }
 *      // 出了块，又变回 1
 * 查找规则：从内往外找，找到第一个就停（就近原则）。
 *
 * ★ 遮蔽是合法的，但通常是坏味道：
 *   1) 读代码的人容易看错
 *   2) C 语言没有 `::` 运算符，一旦局部变量遮蔽了全局变量，
 *      **在这个块里就再也访问不到全局的那个了**，只能给全局变量改名
 *   3) 编译器要开 -Wshadow 才会警告
 * 建议：局部变量不要和全局变量、外层变量重名。
 *
 * ================ 七、作用域 vs 生命周期：四象限 ================
 * 两者是正交的，组合出四种典型情况：
 *
 *  情形                作用域      生命周期        例子
 *  普通局部变量         块          进入块→离开块    int a;       （自动存储期）
 *  static 局部变量      块          整个程序运行期间  static int c;（静态存储期）
 *  全局变量             文件         整个程序运行期间  int g;       （静态存储期）
 *  动态分配的内存       由指针决定   从 malloc 到 free  malloc 出来的（动态存储期）
 *
 * ★ 最容易搞混的是 static 局部变量：
 *      void f(void) {
 *          static int count = 0;   // 作用域仍然只是 f 里
 *          count++;                // 但它的值在函数返回后依然保留
 *      }
 *   作用域小（外面看不见），寿命长（一直活着），二者并不矛盾。
 *   这也是它能当"计数器"用的原因：只初始化一次，之后一直记住上次的值。
 *
 * ========================= 八、存储类说明符 =========================
 * 它们控制"存储期"和"链接属性"，和本节主题关系密切：
 *      auto     局部变量的默认值，可省略，现代代码基本不写
 *      static   修饰局部：静态存储期（寿命变长，作用域不变）
 *               修饰全局：内部链接（只本文件可见）
 *               修饰函数：内部链接（只本文件可调用）
 *      extern   声明别处定义的变量/函数
 *      register 建议放寄存器（现代编译器基本忽略，只在极老代码里见到）
 *
 * ========================= 九、常见坑 =========================
 *  1. 出了块还想用块里的变量           → 未声明
 *  2. 以为作用域从块开头开始           → 实际从声明点开始
 *  3. 在 for 初始化里定义变量后又想在循环外用  → C99 起 i 只在循环内有效
 *  4. 局部变量遮蔽全局变量，之后访问不到全局  → C 没有 ::
 *  5. 以为 static 局部变量"作用域变大"  → 变的是寿命，不是可见范围
 *  6. 全局变量在多个 .c 里重复定义      → 链接错误 multiple definition
 *  7. 头文件里定义变量（而不是声明）    → 被多个文件包含就重复定义
 *  8. goto 跳过变量初始化后直接使用      → 值不确定
 *  9. switch 的 case 共用同一个作用域   → 在 case 里定义变量要加 {}
 * 10. 块内变量太多，看不出谁依赖谁      → 违反最小作用域原则
 *
 * ====================== 十、实践建议 ======================
 *  - 变量"就近声明"，第一次用到的地方再定义，作用域尽量小
 *  - 只在文件内部使用的东西全部加 static（变量和函数都适用）
 *  - 避免局部变量与全局变量重名；开 -Wshadow 让编译器帮你查
 *  - 需要"记住上次的值"才用 static 局部变量，别拿它当全局变量用
 *  - 跨文件共享的数据，在头文件里写 extern 声明，在一个 .c 里定义
 *  - 少用 goto；真要跳出多层循环，可以考虑抽成函数
 */

#include <stdio.h>

/* ---------- 文件作用域：所有函数外面 ---------- */
int global_count = 100;         /* 外部链接：别的 .c 文件也能用 extern 访问 */
static int file_private = 7;    /* 内部链接：只有本文件能看见，别的文件链接不到 */

/* ---------- 原型作用域：这里的 a、b 只在本行有效 ---------- */
/* 写成 static int add(int, int); 也完全等价，参数名只是给人看的 */
static int add(int a, int b);

/* ---------- static 局部变量：作用域小，但寿命长 ---------- */
static int next_id(void)
{
    static int id = 0;          /* 作用域：只在 next_id 里；寿命：整个程序 */
    id++;
    return id;
}

int main(void)
{
    /* ---------- 1. 块作用域：花括号就是边界 ---------- */
    {
        int block_only = 1;     /* 只在这个花括号内有效 */
        printf("1. 块内可以访问 block_only=%d\n", block_only);
    }
    /* printf("%d\n", block_only);   取消注释会报错：block_only 未声明 */

    /* ---------- 2. 作用域从"声明点"开始 ---------- */
    /* printf("%d\n", late);         取消注释会报错：late 还没声明 */
    int late = 2;
    printf("2. late=%d（声明之后才能用）\n", late);

    /* ---------- 3. 出了块就失效，同名变量是"新变量" ---------- */
    {
        int temp = 10;
        printf("3. 第一个块 temp=%d\n", temp);
    }
    {
        int temp = 20;              /* 和上面的 temp 毫无关系，是另一个变量 */
        printf("   第二个块 temp=%d（同名但是新变量）\n", temp);
    }

    /* ---------- 4. 遮蔽：三层同名，就近生效 ---------- */
    int v = 1;
    printf("4. 外层 v=%d\n", v);
    {
        int v = 2;                  /* 遮蔽外层的 v */
        printf("   中层 v=%d（被遮蔽）\n", v);
        {
            int v = 3;              /* 再遮蔽一层 */
            printf("   内层 v=%d（被遮蔽）\n", v);
        }
        printf("   回到中层 v=%d\n", v);
    }
    printf("   回到外层 v=%d（外层的值从来没被改过）\n", v);

    /* ---------- 5. for 循环变量的作用域（C99 起） ---------- */
    int sum = 0;
    for (int i = 0; i < 5; i++) {   /* i 的作用域仅限这个 for */
        sum += i;
    }
    printf("5. 循环内累加 sum=%d\n", sum);
    /* printf("%d", i);             取消注释会报错：i 在循环外不可见 */

    /* ---------- 6. 循环体里定义的变量，每轮都是新的 ---------- */
    for (int k = 0; k < 3; k++) {
        int local_in_loop = k * 10;     /* 每轮重新创建、重新初始化 */
        printf("6. 第 %d 轮 local_in_loop=%d\n", k, local_in_loop);
    }

    /* ---------- 7. static 局部变量：作用域 vs 生命周期 ---------- */
    /* 普通局部变量每次调用都重新创建，static 的只创建一次并一直保留 */
    int id1 = next_id();
    int id2 = next_id();
    int id3 = next_id();
    printf("7. next_id 连续三次：%d %d %d（值被记住，作用域仍只在函数内）\n",
           id1, id2, id3);
    /* printf("%d", id);            取消注释会报错：id 在 next_id 外不可见 */

    /* ---------- 8. 局部变量遮蔽全局变量 ---------- */
    /* 下面这行定义的 global_count 是局部变量，把同名的全局变量挡住了 */
    int global_count = 1;
    printf("8. 局部 global_count=%d（全局那个是 100，此刻访问不到）\n",
           global_count);
    /* C 语言没有 :: 运算符，这里无法再访问全局的 global_count，
     * 只能在别的函数里访问，或者把全局变量改名 */

    /* ---------- 9. 文件作用域 + static 内部链接 ---------- */
    printf("9. file_private=%d（本文件可见；别的 .c 文件即使 extern 也链接不到）\n",
           file_private);

    /* ---------- 10. 用花括号主动限定变量范围 ---------- */
    /* 好处：变量及时"退休"，名字不会污染后面的代码 */
    {
        int tmp[8];                 /* 只在这几行需要，用完就消失 */
        for (int i = 0; i < 8; i++) {
            tmp[i] = i * i;
        }
        printf("10. 临时数组 tmp[7]=%d（出了这个块就释放）\n", tmp[7]);
    }

    /* ---------- 11. goto 标签是"函数作用域" ---------- */
    /* 标签在整个函数里都可见，不受花括号限制 */
    int step = 0;
    goto done;                      /* 直接跳到下面的标签 */
    step = 99;                      /* 这一行被跳过，永远不执行 */
done:
    printf("11. goto 跳过了赋值语句，step=%d（标签属于函数作用域）\n", step);

    /* ---------- 12. 原型作用域演示 ---------- */
    /* add 的原型写的是 (int a, int b)，定义里写的是 (int x, int y)，
     * 参数名互不影响，编译器只关心类型和顺序 */
    printf("12. add(3, 4)=%d（原型的参数名与定义的参数名无关）\n", add(3, 4));

    /* ---------- 13. extern 声明（跨文件时使用） ---------- */
    /*
     * 如果另一个 .c 文件里定义了 int shared_value = 5;
     * 这里写：
     *     extern int shared_value;        // 只声明，不分配内存
     *     printf("%d", shared_value);
     * 就能访问到它。但本文件是单文件示例，没有对应的定义，
     * 所以这里只能用注释说明，真写了会链接失败：undefined symbol。
     */

    /* ---------- 14. 总结 ---------- */
    printf("14. 小结：\n");
    printf("    块作用域   { } 内，最常用\n");
    printf("    文件作用域 函数外定义，static 可限制在本文件\n");
    printf("    函数作用域 只有 goto 标签\n");
    printf("    原型作用域 函数原型里的参数名，只在这一行有效\n");
    printf("    作用域管“看得见”，生命周期管“活多久”，两者独立\n");

    return 0;
}

/* ---------- add 的定义：参数名故意和原型不同 ---------- */
static int add(int x, int y)
{
    return x + y;
}

