/*
 * 01_变量.c —— 阶段1 / 第 02 课 / 第 01 个文件：C 语言变量详解
 * 编译：gcc 01_变量.c -o var_demo
 * 运行：./var_demo
 *
 * ============================== 一、变量是什么 ==============================
 * 变量 = 内存里的一块"有名字的存储空间"。
 *      int age = 18;
 * 拆开看：
 *      int   → 类型：决定这块空间有多大（4 字节）、怎么解释里面的 0/1
 *      age   → 名字（标识符）：以后靠这个名字找到这块空间
 *      = 18  → 初始化：往这块空间里写入 18
 *       ;    → 语句结束
 * 变量的三要素：类型、名字、值。三者缺一不可。
 * 为什么需要类型：内存本身只是一串字节，编译器必须知道
 *      - 从哪个地址读几个字节
 *      - 这几个字节按整数解释还是按浮点解释
 * 所以 int 和 float 哪怕都是 4 字节，同样的 0/1 序列读出来的值完全不同。
 *
 * ============================ 二、声明语句的语法 ============================
 *     类型  变量名  [= 初值]  [, 变量名2 [= 初值2]] ... ;
 * 例：
 *      int   a;                 声明（只分配空间，不赋值）
 *      int   b = 10;            定义 + 初始化
 *      int   c = 1, d = 2;      一行声明多个
 *      int   e, f;              两个都未初始化（很危险，见第五节）
 * 注意区分三个词：
 *      声明(declaration) 告诉编译器"有这么个名字，类型是什么"
 *      定义(definition)  真正分配内存（局部变量声明即定义）
 *      初始化(initialization) 定义的同时给初值，一辈子只有一次
 *      赋值(assignment)  之后再用 = 改值，可以很多次
 *     int a = 1;   // 初始化
 *     a = 2;       // 赋值，不是初始化
 *
 * ★ 二点五、先声明后使用（C 的硬性规定，非常重要）★
 * 一句话：C 编译器从上往下读代码，只认"当前位置之前已经见过"的名字。
 * 名字没出现过就直接用，编译报错：
 *      error: 'x' undeclared (first use in this function)
 * 为什么 C 有这条规矩：C 在编译期就要确定每个名字的类型、占多大内存、
 * 在栈上的偏移量，所以必须先看到声明才能生成正确的机器指令。
 * 不像 Python/JS 那样可以"先用后定义"、运行时再去找。
 *
 * 具体体现为四条：
 *   (1) 语句顺序决定可见性
 *           printf("%d", x);    // ✗ 编译报错，此刻 x 还不存在
 *           int x = 1;          // ✓ 声明点从这里才开始
 *   (2) 作用域从"声明那一行"开始，不是从块的开头开始
 *           { ... int late = 9; }   // late 在声明之前看不见
 *   (3) 全局变量也要"先定义后使用"
 *           函数里用了全局变量，该全局变量必须写在函数上方；
 *           否则要在前面写 extern int g; 先声明一下。
 *   (4) 函数要先有"声明（原型）"才能调用
 *           如果函数定义写在 main 后面，就要在 main 前面补一行原型：
 *               static int add(int a, int b);            // 原型：告诉编译器长什么样
 *               int main(void) { int s = add(1, 2); }    // 此时才能调用
 *               static int add(int a, int b) { return a + b; }  // 定义：真正的实现
 *           这也解释了为什么 #include <stdio.h> 不能省——
 *           头文件里装的就是 printf 等函数的原型声明，相当于"先声明"。
 *
 * 补充：声明位置的规定随标准放宽
 *      C89：一个块里的声明必须全部写在块的开头，不能和语句混着写
 *      C99 及以后：允许随用随声明（本文件就是 C99 风格）
 *            int main(void) {
 *                int a = 1;      // C89 允许
 *                printf("%d", a);
 *                int b = 2;      // C89 ✗ 必须先声明 / C99 ✓
 *            }
 *   推荐做法："就近声明"——离第一次使用的地方越近越好，
 *   这样变量作用域最小，不容易被误用，也更容易读。
 *   具体演示见下面代码里标着"【先声明后使用】"的那一段。
 *
 * ========================== 三、基本类型与取值范围 ==========================
 * 32/64 位主流平台上（本机实测，用 sizeof 打印）：
 *      char        1 字节   存单个字符或小整数，范围 -128~127（有符号时）
 *      short       2 字节   -32768~32767
 *      int         4 字节   -2147483648~2147483647
 *      long        8 字节   macOS/Linux 64 位上是 8 字节（Windows 上是 4 字节！）
 *      long long   8 字节   至少 64 位，跨平台更稳妥
 *      float       4 字节   约 6~7 位有效数字
 *      double      8 字节   约 15~16 位有效数字（默认用它）
 * 关键认知：C 标准只规定"最小范围"，不规定字节数。
 *      int 在 16 位机器上是 2 字节，在 32/64 位上是 4 字节；
 *      long 在 Windows 上 4 字节、在 macOS/Linux 上 8 字节。
 * 所以：写跨平台代码时用 sizeof 判断，不要硬编码"int 就是 4 字节"。
 * 取值范围可以在 <limits.h>（整数）和 <float.h>（浮点）里查到：
 *      INT_MAX、INT_MIN、UINT_MAX、LLONG_MAX、FLT_MAX、DBL_EPSILON
 *
 * ======================== 四、有符号 vs 无符号 ========================
 * 先看两个词的英文原义：
 *      signed   = "带符号的"（sign 指正负号 + -），能表示负数
 *      unsigned = "不带符号的"，只有大小，只能表示 0 和正数
 * 二进制上的差别只在最高位：
 *      signed int   最高位当"符号位"（0 非负、1 负数），剩下位表示数值
 *      unsigned int 最高位也当数值位，全部位都表示大小，所以正数上限翻倍
 *      例：同样的 0xFFFFFFFF，按 int 读是 -1，按 unsigned 读是 4294967295
 *      int 默认就是 signed int，写不写 signed 一样
 * 为什么负数能多表示一个（-128 而正数只到 127）：0 占掉了正数的一个位置。
 * 详细图解见 02_整型.c 的"二点一"节。
 * 什么时候用 unsigned：表示"不可能是负数"的量，比如个数、长度、下标、位掩码。
 * 陷阱：unsigned 和 signed 混合运算时，signed 会被悄悄转成 unsigned。
 *      int a = -1;
 *      unsigned b = 1;
 *      if (a < b) → 实际比较的是 4294967295 < 1，结果为假！
 * 所以：不要在同一段逻辑里混用 signed / unsigned，这是 bug 高发区。
 *
 * ============================= 五、初始化 =============================
 * 三种情况，差别巨大：
 *   (1) 全局变量 / static 变量：不写初值，编译器自动置 0（这是标准保证的）
 *   (2) 局部变量：不写初值就是"垃圾值"——那块内存里残留着什么就是什么
 *   (3) 显式初始化：最安全，永远推荐
 * 读一个未初始化的局部变量属于未定义行为（UB），可能得到随机数，
 * 也可能被编译器优化成任何结果。养成习惯：定义时就给初值。
 *
 * ========================== 六、作用域与生命周期 ==========================
 * 作用域：名字在哪里"看得见"。
 * 生命周期：这块内存什么时候存在、什么时候回收。
 *   - 局部变量（在函数/花括号内定义）
 *       作用域：从定义处到所在 } 结束
 *       生命周期：进入块时创建，离开块时销毁（存在栈上）
 *   - 全局变量（在所有函数外面定义）
 *       作用域：整个文件（配合 extern 可跨文件）
 *       生命周期：程序启动到结束
 *   - static 局部变量
 *       作用域：仍是块内
 *       生命周期：整个程序运行期间（只初始化一次，存在静态区）
 *       典型用途：函数内的计数器、缓存
 * 还有 register（建议放寄存器，现代编译器基本忽略）、extern（声明外部变量），
 * 初学阶段知道有这回事即可。
 *
 * ====================== 七、类型转换：隐式与强制 ======================
 * 隐式转换（编译器自动做，按"精度就高"的方向）：
 *      char → short → int → long → float → double
 * 典型坑：两个 int 相除，结果是"整数除法"，小数部分直接丢掉
 *      5 / 2      → 2      （不是 2.5）
 *      5 / 2.0    → 2.5
 * 强制转换（显式，自己负责）：
 *      (double)5 / 2 → 2.5    把 5 先转成 double，再做除法
 *      (int)3.99     → 3      浮点转整数是"截断"，不是四舍五入
 * 转换原则：窄类型 → 宽类型安全；宽 → 窄可能丢失数据，要自己确认。
 *
 * ============================ 八、溢出与精度 ============================
 * 整数溢出：
 *      signed 溢出是未定义行为（UB），不要依赖它的结果；
 *      unsigned 溢出是"回绕"（模 2^N），标准明确规定，可以放心用。
 * 浮点精度：
 *      float/double 是二进制小数，0.1、0.2 这类十进制小数无法精确表示，
 *      所以 0.1 + 0.2 != 0.3。比较浮点数要用"误差范围"：
 *      if (fabs(a - b) < 1e-9) ...
 *      涉及金额不要用 float/double，用整数（以"分"为单位）或定点数。
 *
 * ============================ 九、常见错误清单 ============================
 *   1. 局部变量不初始化就用            → 垃圾值 / UB
 *   2. 用 %d 打印 double、用 %f 打印 int → 未定义行为
 *   3. 整数除法当小数用  1/2 == 0
 *   4. signed 与 unsigned 混合比较
 *   5. 把"="当"=="用：if (a = 0) 恒为假，还会改掉 a 的值
 *   6. 硬编码类型大小，换平台就崩（用 sizeof）
 *   7. float 直接比较相等
 *
 * ============================== 十、命名回顾 ==============================
 * 变量名要见名知义（阶段1/01_入门与输入输出/04_标识符.c 讲过规则）：
 *      int  a;                 ✗ 看不出含义
 *      int  studentCount;      ✓ 小驼峰
 *      int  student_count;     ✓ 下划线派（Linux 风格）
 *      float price;            ✓ 名词
 *      int  is_valid;          ✓ 布尔含义用 is_/has_ 开头
 */

#include <stdio.h>
#include <limits.h>     /* INT_MAX、UINT_MAX、LLONG_MAX 等整数范围宏 */
#include <float.h>      /* FLT_MAX、DBL_EPSILON 等浮点范围宏 */

/* [全局变量] 定义在所有函数之外，程序启动时自动初始化为 0 */
int  global_count;          /* 不写初值也是 0，这是标准保证的 */
int  global_initialized = 100;

/* static 全局变量：作用域限本文件（别的 .c 文件看不见），本例只是演示 */
static int file_only = 5;

/* static 局部变量演示：函数每次调用共享同一个计数器 */
static int next_id(void)
{
    static int counter = 0; /* 只初始化一次，值在函数返回后依然保留 */
    counter++;
    return counter;
}

/* [函数原型 / 声明] 只是"告诉编译器有这么个函数、长什么样"，
 * 真正的函数体在文件最后。没有这一行，main 里调用 add 就会报
 * "implicit declaration" 或 "undeclared" 错误。 */
static int add(int x, int y);

int main(void)
{
    /* ---------- 1. 变量的大小：用 sizeof 实测，别硬编码 ---------- */
    /* sizeof 的结果类型是 size_t，printf 要用 %zu（或转换成 %lu） */
    printf("1. sizeof(char)=%zu  sizeof(short)=%zu  sizeof(int)=%zu\n",
           sizeof(char), sizeof(short), sizeof(int));
    printf("   sizeof(long)=%zu  sizeof(long long)=%zu\n",
           sizeof(long), sizeof(long long));
    printf("   sizeof(float)=%zu  sizeof(double)=%zu\n",
           sizeof(float), sizeof(double));

    /* ---------- 2. 取值范围：从 limits.h / float.h 取宏 ---------- */
    printf("2. INT_MIN=%d  INT_MAX=%d\n", INT_MIN, INT_MAX);
    printf("   UINT_MAX=%u  LLONG_MAX=%lld\n", UINT_MAX, LLONG_MAX);
    printf("   FLT_MAX=%e  DBL_EPSILON=%e\n", (double)FLT_MAX, DBL_EPSILON);

    /* ---------- 3. 声明、初始化、赋值的区别 ---------- */
    int  a;             /* 声明：有空间，但值不确定（这里故意先不用它） */
    int  b = 10;        /* 定义 + 初始化：初值 10 */
    a = 20;             /* 赋值：此时 a 才第一次有确定的值 */
    b = 30;             /* 再次赋值：覆盖原来的 10 */
    printf("3. a=%d  b=%d（b 从 10 被改成 30）\n", a, b);

    /* ---------- 3.5 【先声明后使用】C 的硬性规定 ---------- */
    /* 下面这行如果取消注释，编译会直接报错：
     *     error: use of undeclared identifier 'total'
     * 因为此刻 total 还没声明，编译器不知道它是什么类型、占几个字节，
     * 也就没法为它生成正确的读写指令。 */
    /* printf("total = %d\n", total); */

    /* 先声明（顺带初始化），再使用——顺序反过来就不行 */
    int total = 0;
    printf("3.5 声明之后才能用 total=%d\n", total);

    /* 作用域从"声明点"开始，而不是从块的开头开始：
     * 声明点之前的代码即使在同一对花括号里，也看不见这个名字。 */
    {
        /* printf("%d\n", late);   取消注释会报错：late 未声明 */
        int late = 9;
        printf("    块内 late=%d（声明点之前看不到它）\n", late);
    }

    /* 函数同样要"先声明、后使用"。
     * add 的实现写在文件末尾，所以在 main 之前先写了原型（见文件上方），
     * 编译器看到原型就知道 add 的参数和返回值类型，才允许在这里调用。 */
    printf("    函数 add(2,3)=%d（定义在文件末尾，靠原型提前声明）\n", add(2, 3));

    /* ---------- 4. 全局变量不初始化也是 0 ---------- */
    printf("4. global_count=%d（全局变量默认初始化为 0）\n", global_count);
    printf("   global_initialized=%d  file_only=%d\n",
           global_initialized, file_only);

    /* ---------- 5. static 局部变量：值会"记住" ---------- */
    /* 普通局部变量每次调用都重新创建，static 变量只创建一次 */
    /* 注意：这里故意拆成三行分别调用。写成
     *     printf("%d %d %d", next_id(), next_id(), next_id());
     * 也能编译，但 C 标准没有规定函数参数的求值顺序，
     * 结果可能是 1 2 3，也可能是 3 2 1——这类"依赖求值顺序"的代码要避开。 */
    int id1 = next_id();
    int id2 = next_id();
    int id3 = next_id();
    printf("5. next_id() 三次调用：%d %d %d\n", id1, id2, id3);

    /* ---------- 6. 整数除法：这是新手最容易错的一处 ---------- */
    int    x = 5, y = 2;
    double wrong = x / y;            /* 先做整数除法得 2，再转成 2.0 */
    double right = (double)x / y;    /* 先把 x 转成 double，再做浮点除法 */
    printf("6. 5/2 直接算 = %.1f（整数除法丢掉小数）\n", wrong);
    printf("   (double)5/2 = %.1f（强制转换后正确）\n", right);

    /* ---------- 7. 浮点精度：0.1 + 0.2 不等于 0.3 ---------- */
    /* 因为二进制无法精确表示 0.1，只能存一个非常接近的值 */
    double sum = 0.1 + 0.2;
    printf("7. 0.1+0.2 = %.17f\n", sum);        /* 打印 17 位就能看到尾巴 */
    printf("   和 0.3 相等吗？%s\n", (sum == 0.3) ? "相等" : "不相等");

    /* ---------- 8. unsigned 的回绕（这是标准明确规定的，安全）---------- */
    unsigned int u = UINT_MAX;
    u = u + 1;                       /* 溢出后回到 0，像手表转过 12 点 */
    printf("8. UINT_MAX+1 = %u（无符号回绕，行为确定可依赖）\n", u);
    /* 注意：signed 溢出是未定义行为，不要写 int_max + 1 去试，结果不可信 */

    /* ---------- 9. 类型转换：截断 vs 提升 ---------- */
    double pi    = 3.99;
    int    truncated = (int)pi;      /* 浮点转整数：直接截断小数部分，不四舍五入 */
    char   ch    = 'A';
    int    ascii = ch;               /* 窄类型自动提升为宽类型，安全 */
    printf("9. (int)3.99 = %d（截断，不是 4）\n", truncated);
    printf("   char 'A' 自动提升为 int = %d\n", ascii);

    /* ---------- 10. char 的双重身份：字符 和 小整数 ---------- */
    /* 字符本质就是编码数字，所以 %c 打字符、%d 打编码 */
    char letter = 'Z';
    printf("10. letter 作为字符: %c，作为整数: %d\n", letter, letter);
    /* 注意 char 是否有符号由编译器决定；要明确语义时用 signed char / unsigned char */

    /* ---------- 11. const：值不能再改的"变量" ---------- */
    /* 编译期就固定，好处是防止误改、表达意图（比 #define 有类型检查） */
    const int MAX_STUDENTS = 50;
    const double PI = 3.141592653589793;
    /* MAX_STUDENTS = 60;  取消注释会编译报错：assignment of read-only variable */
    printf("11. MAX_STUDENTS=%d  PI=%.5f\n", MAX_STUDENTS, PI);

    /* ---------- 12. 作用域演示：块内变量出块即失效 ---------- */
    {
        int inner = 1;
        printf("12. 块内 inner=%d\n", inner);
    }
    /* printf("%d", inner);  取消注释会报错：inner 未声明 */

    /* ---------- 13. 变量遮蔽：内层同名变量盖住外层 ---------- */
    int n = 1;
    printf("13. 外层 n=%d\n", n);
    {
        int n = 2;                   /* 新变量，遮蔽外层的 n */
        printf("    内层 n=%d（遮蔽）\n", n);
    }
    printf("    回到外层 n=%d（外层未被修改）\n", n);

    return 0;
}

/* [函数定义] 这才是 add 真正的实现。
 * 顺序上：原型在上面（main 之前）→ 调用在中间 → 实现在这里，
 * 这就是标准的"先声明、后使用"写法。
 * 如果没有上面那行原型，把这个定义放在 main 后面就会编译报错。 */
static int add(int x, int y)
{
    return x + y;
}
