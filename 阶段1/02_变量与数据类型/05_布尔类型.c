/*
 * 05_布尔类型.c —— 阶段1 / 第 02 课 / 第 05 个文件：布尔类型
 * 编译：gcc 05_布尔类型.c -o bool_demo
 * 运行：./bool_demo
 *
 * ======================= 一、C 语言的"布尔"是什么 =======================
 * 布尔（boolean）只有两个值：真 / 假。
 * 但 C 的处理方式和 Java/C#/Python 完全不同，记住一句话：
 *
 *      ★ C 里没有"专门的布尔值"，一切判断都基于整数：0 为假，非 0 为真。
 *
 * 也就是说下面这些写法在 C 里都是"真"：
 *      if (1)      if (-1)      if (42)      if ('A')
 * 这些是"假"：
 *      if (0)      if (0.0)      if ('\0')      if (NULL)
 * 这个规则贯穿 C 的所有条件上下文：if、while、for、?:、&&、||、!。
 *
 * ==================== 二、C89 时代：拿 int 当布尔用 ====================
 * C99 之前标准里没有 bool，大家的写法是：
 *      int flag = 1;            // 1 表示真
 *      int found = 0;           // 0 表示假
 *      if (flag) { ... }
 * 问题：
 *   1) int 占 4 字节，只存 0/1 很浪费（结构体里尤其明显）
 *   2) 语义不清：int 还能存 -1、100、999，读代码的人得猜"这是数量还是标志位"
 *   3) 没有 true/false 这两个词，代码可读性差
 * 所以老代码里常见 #define TRUE 1 / #define FALSE 0，但那是各家自己定的，
 * 标准库从来没提供过（Windows 的 TRUE/FALSE 也不是 C 标准的一部分）。
 *
 * ================= 三、C99 的 bool：_Bool 与 <stdbool.h> =================
 * C99 引入了一个真正的最小布尔类型：_Bool（占 1 字节）
 * 但 _Bool 这个名字带下划线加大写，不符合普通标识符的审美，
 * 于是标准库头文件 <stdbool.h> 提供了三个宏：
 *      #define bool  _Bool
 *      #define true  1
 *      #define false 0
 * 所以：
 *      #include <stdbool.h>
 *      bool ok = true;
 *      bool bad = false;
 * 注意：bool / true / false 是"宏"，不是关键字（_Bool 才是关键字）。
 *      C23 起 true/false 变成了真正的关键字，但用法完全一样。
 * 为什么用 1 字节而不是 4 字节：
 *      大量布尔字段放在结构体里时，1 字节比 4 字节省很多内存
 *      （实际还涉及对齐，见后面结构体章节）。
 *
 * ======================= 四、归一化：非 0 都会变成 1 =======================
 * 这是 _Bool 最特殊的地方：给它赋任何非 0 值，存进去的都是 1。
 *      bool b = 42;        // 存的是 1，不是 42
 *      bool c = -1;        // 存的是 1
 *      bool d = 0.5;       // 存的是 1（0.5 不是 0，所以为真）
 * 原因：_Bool 只有 1 个位有意义（其余位补 0），赋值时编译器做了"归一化"。
 * 对比：用 int 当布尔时，值会原样保留（flag = 42 存的还是 42），
 *       这就是 bool 和 int 当布尔用的实质区别。
 * 实践价值：printf("%d", (int)b) 永远只会打出 0 或 1，不会出现乱七八糟的数。
 *
 * ============== 五、关系运算符返回的是 int，不是 bool ==============
 *      <  <=  >  >=  ==  !=
 * 这六个运算符的结果类型是 **int**，值为 0 或 1，不是 _Bool。
 * 所以：
 *      sizeof(3 > 2) == sizeof(int) == 4     （在 64 位平台上是 4）
 * 这也解释了为什么可以写：
 *      int n = (a > b) + (c > d);    // 数一数有几个条件成立
 * 以及经典写法：
 *      int count = 0;
 *      count += (score >= 60);       // 及格就 +1
 * 用 bool 接收也可以，会自动转成 0/1。
 *
 * ======================= 六、逻辑运算符与短路求值 =======================
 *      &&   逻辑与：两边都为真才为真
 *      ||   逻辑或：有一边为真就为真
 *      !    逻辑非：真变假、假变真
 * 三个操作数都被当作"真/假"看待（非 0 即真），结果也是 int 的 0 或 1。
 *
 * ★ 短路求值（short-circuit）：这是 C 逻辑运算最重要的特性
 *      a && b   →  如果 a 为假，b 根本不会被计算（结果已经确定为假）
 *      a || b   →  如果 a 为真，b 根本不会被计算（结果已经确定为真）
 * 为什么重要：
 *   1) 性能：能省掉不必要的计算
 *   2) 安全：这是 C 里最常用的"空指针保护"写法
 *          if (p != NULL && p->value > 0)     // p 为空时右边不会执行，不会崩溃
 *      如果把顺序写反：p->value > 0 && p != NULL，空指针时直接崩溃
 *   3) 副作用：if (i < n && a[i] > 0) 这种"边界检查 + 访问"依赖短路才安全
 * 一定要记住：&& 和 || 保证"从左到右"计算，且左边能决定结果时右边不执行。
 *
 * ============ 七、逻辑运算 vs 位运算：最容易混淆的一组 ============
 *     逻辑：&&   ||   !        针对"真假"，结果只有 0/1，有短路
 *     位运算：&   |    ^   ~    针对"每一位"，结果保留原始数值，无短路
 * 典型错误：
 *      if (a & b)      ✗ 这是按位与，2 & 4 == 0，被当成假
 *      if (a && b)     ✓ 这才是"a 和 b 都非 0"
 * 用位运算代替逻辑运算，只有在两边都是 0/1 时才"碰巧"正确，
 * 一旦值是 2、4 这类数就会出错，而且编译器不会提醒你。
 * 反过来，位掩码操作（权限、标志位）必须用 & | ^ ~，不能用 && ||。
 * 另外：! 是逻辑非（结果 0/1），~ 是按位取反（0 变全 1），别写混。
 *
 * ======================= 八、三目运算符 ?: =======================
 *      条件 ? 值1 : 值2
 * 条件为真取值1，否则取值2。它也是"非 0 即真"。
 *      int max = (a > b) ? a : b;
 *      printf("%s", ok ? "通过" : "不通过");
 * 注意：两个分支的类型会做统一（比如 int 和 double 混用会提升成 double），
 *       嵌套太多会难读，超过两层就改用 if。
 *
 * ========================== 九、优先级提醒 ==========================
 * 从高到低（只列常见的）：
 *      !            逻辑非
 *      算术运算       + - * / %
 *      关系运算       < <= > >=
 *      相等           == !=
 *      &&            逻辑与
 *      ||            逻辑或
 *      赋值           =
 * 所以：
 *      !a == b      意思是 (!a) == b，不是 !(a == b)
 *      a > b && c < d  意思是 (a > b) && (c < d)，没问题
 *      a = b && c    意思是 a = (b && c)，把逻辑结果赋给 a
 * 记不清就加括号，括号不要钱，bug 要命。
 *
 * ============================ 十、常见坑 ============================
 *  1. if (a = 0)      把 == 写成 =，条件恒假，还顺手改掉了 a（编译器会给警告）
 *  2. if (x == 1)     判断"为真"不能这么写！任何非 0 都是真，x=2 时这里却是假
 *                     ✓ 正确：if (x) 或 if (x != 0)
 *  3. if (a & b)      位运算当逻辑用
 *  4. 浮点直接比较     if (f == 0.1)，要用误差范围
 *  5. 短路被忽略       if (p->x && p != NULL) 顺序写反导致崩溃
 *  6. bool 当 int 打印 printf("%d", b) 没问题，但 "%s" 不行
 *  7. 把 true 当 1 用    bool 参与算术虽然可以，但语义上不如直接用 int
 *  8. 用 ! 判断非零     !x 是"x 为 0 时才是真"，容易把意思看反
 *  9. 逻辑运算符不返回"原值"    a && b 的结果是 0/1，不是 a 或 b
 */

#include <stdio.h>
#include <stdbool.h>    /* bool / true / false（C99 起） */

/* 用来演示短路求值：函数被调用一次，计数器 +1 */
static int call_count = 0;
static int probe(void)
{
    call_count++;
    return 1;               /* 返回值本身为真 */
}

/* 另一个演示：用 int 当布尔的老写法 */
static void old_style(void)
{
    int flag = 1;           /* 1 表示真 */
    int found = 0;          /* 0 表示假 */
    if (flag) {
        printf("   C89 风格：int flag=1 可以当条件用\n");
    }
    if (!found) {
        printf("   C89 风格：int found=0 取反后为真\n");
    }
}

int main(void)
{
    /* ---------- 1. bool 有多大 ---------- */
    printf("1. sizeof(bool)=%zu  sizeof(_Bool)=%zu（1 字节，比 int 省）\n",
           sizeof(bool), sizeof(_Bool));
    printf("   sizeof(3 > 2)=%zu（关系运算的结果其实是 int，不是 bool）\n",
           sizeof(3 > 2));

    /* ---------- 2. 基本用法 ---------- */
    bool ok    = true;
    bool fail  = false;
    printf("2. ok=%d  fail=%d\n", ok, fail);

    /* ---------- 3. 归一化：非 0 一律变 1 ---------- */
    bool b1 = 42;
    bool b2 = -1;
    double half = 0.5;      /* 用变量中转，否则字面量 0.5 会触发 -Wliteral-conversion */
    bool b3 = half;         /* 非 0 即真 */
    bool b4 = 0;
    printf("3. 把 42 赋给 bool → %d\n", b1);
    printf("   把 -1 赋给 bool → %d\n", b2);
    printf("   把 0.5 赋给 bool → %d（非 0 即真）\n", b3);
    printf("   把 0 赋给 bool  → %d\n", b4);
    /* 对照组：int 当布尔不会归一化 */
    int flag = 42;
    printf("   对照：int flag=42 仍然是 %d（不会变成 1）\n", flag);

    /* ---------- 4. 一切非 0 都算真 ---------- */
    int nums[] = {0, 1, -1, 100};
    printf("4. ");
    for (int i = 0; i < 4; i++) {
        if (nums[i]) {
            printf("%d→真  ", nums[i]);
        } else {
            printf("%d→假  ", nums[i]);
        }
    }
    printf("\n");

    /* ---------- 5. 关系运算返回 0/1，可以直接相加计数 ---------- */
    int a = 10, b = 20;
    printf("5. (a > b)=%d  (a < b)=%d  (a == b)=%d\n", a > b, a < b, a == b);
    int passed = (a > 5) + (b > 5);      /* 两个条件都成立，累加得 2 */
    printf("   用加法数“有几个条件成立”：%d\n", passed);

    /* ---------- 6. 逻辑运算符 ---------- */
    printf("6. 真值表\n");
    printf("   a  b | a&&b  a||b  !a\n");
    for (int i = 0; i <= 1; i++) {
        for (int j = 0; j <= 1; j++) {
            printf("   %d  %d |  %d     %d     %d\n",
                   i, j, i && j, i || j, !i);
        }
    }

    /* ---------- 7. 短路求值：右边可能根本不执行 ---------- */
    call_count = 0;
    if (0 && probe()) { }        /* 左边为假，probe 不会被调用 */
    printf("7. 0 && probe()  → probe 被调用 %d 次（短路了）\n", call_count);

    call_count = 0;
    if (1 || probe()) { }        /* 左边为真，probe 不会被调用 */
    printf("   1 || probe()  → probe 被调用 %d 次（短路了）\n", call_count);

    call_count = 0;
    if (1 && probe()) { }        /* 左边为真，必须看右边，probe 被调用 */
    printf("   1 && probe()  → probe 被调用 %d 次\n", call_count);

    /* ---------- 8. 短路是 C 里"空指针保护"的标准写法 ---------- */
    int   value = 7;
    int  *p = &value;
    int  *q = NULL;
    if (p != NULL && *p > 0) {   /* p 有效时才会解引用 */
        printf("8. p 有效，*p = %d\n", *p);
    }
    if (q != NULL && *q > 0) {   /* q 为空，右边不执行，不会崩溃 */
        printf("   q 有效\n");
    } else {
        printf("   q 为空，短路生效，没有崩溃\n");
    }

    /* ---------- 9. 逻辑 vs 位运算：本质区别 ---------- */
    int x = 2, y = 4;
    printf("9. 2 && 4 = %d（逻辑与：两边都非 0 → 真）\n", x && y);
    printf("   2 &  4 = %d（按位与：0010 & 0100 = 0000）\n", x & y);
    printf("   2 || 0 = %d，2 | 0 = %d\n", x || 0, x | 0);
    printf("   !2 = %d，~2 = %d（逻辑非 vs 按位取反）\n", !x, ~x);

    /* ---------- 10. 三目运算符 ---------- */
    int score = 85;
    printf("10. score=%d → %s\n", score, (score >= 60) ? "及格" : "不及格");
    int max = (a > b) ? a : b;
    printf("    a=%d, b=%d，较大的是 %d\n", a, b, max);

    /* ---------- 11. 常见错误：把"真"等同于 1 ---------- */
    int v = 2;
    printf("11. v=%d 时：\n", v);
    printf("    if (v)        → %s（正确写法）\n", v ? "真" : "假");
    printf("    if (v == 1)   → %s（错误写法！v 是 2，但它是真）\n",
           (v == 1) ? "真" : "假");
    /* 正确判断"非 0"应该写 if (v) 或 if (v != 0) */

    /* ---------- 12. C89 老写法对照 ---------- */
    old_style();

    /* ---------- 13. 建议 ---------- */
    printf("13. 建议：\n");
    printf("    表示“是/否”用 bool（记得 #include <stdbool.h>）\n");
    printf("    变量名用 is_/has_/can_ 开头：is_valid、has_next\n");
    printf("    判断非 0 直接写 if (x)，不要写 if (x == 1)\n");
    printf("    指针 / 边界检查靠 && 短路，把“可能为空的东西”放左边\n");

    return 0;
}
