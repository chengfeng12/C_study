/*
 * 06_浮点类型.c —— 阶段1 / 第 01 课 / 第 6 个文件：浮点类型
 * 编译：gcc 06_浮点类型.c -o float_demo
 * 运行：./float_demo
 *
 * ========================= 一、浮点数是什么 =========================
 * "浮点"= 小数点位置可以浮动，也就是科学计数法：
 *      3.14  →  3.14 × 10^0
 *      0.001 →  1.0 × 10^-3
 * 计算机用二进制存，格式是 IEEE 754，把 32 位切成三段：
 *      [ 符号 1 位 ][ 指数 8 位 ][ 尾数 23 位 ]        ← float
 *      [ 符号 1 位 ][ 指数 11 位][ 尾数 52 位]         ← double
 *   - 符号位：0 正、1 负
 *   - 指数：决定"小数点往哪浮"，也就是能表示多大/多小
 *   - 尾数：决定"有效数字有几位"，也就是精度
 * 因为尾数位数固定，所以：
 *      float  约 6~7 位有效数字
 *      double 约 15~16 位有效数字
 * 这也是浮点"不能精确表示 0.1"的根本原因——
 * 十进制 0.1 换成分母是 2 的幂的二进制小数是无限循环的，尾数存不下，只能近似。
 *
 * ====================== 二、三种浮点类型对比 ======================
 * 类型          字节  有效数字     典型范围            说明
 * float          4    约 6~7 位    约 ±3.4e38         省空间，精度差
 * double         8    约 15~16 位  约 ±1.8e308        默认首选
 * long double    8或16 依平台而定  至少和 double 一样   x86 Linux 上是 16 字节，
 *                                                      macOS/ARM 上只有 8 字节（等同 double）
 *
 * ★ 记法：日常一律用 double。float 只在"内存/带宽紧张"（大量数据、图形、嵌入式）时用。
 *   float 省一半内存，但只有 6 位有效数字，累计计算误差会明显放大。
 *
 * ==================== 三、精度的三个必知结论 ====================
 * 1) 十进制小数大多存不准
 *        0.1 存进 double 实际是 0.1000000000000000055511151231257827...
 *        打印 17 位就能看出尾巴
 * 2) 不要用 == 比较浮点数
 *        0.1 + 0.2 == 0.3   →  结果几乎总是"假"
 *        正确做法：判断差值小于误差范围
 *            fabs(a - b) < 1e-9          （要 #include <math.h>）
 *        或者自己写： (a - b) < eps && (b - a) < eps
 * 3) 累计误差
 *        把 0.1 加 1000 次，结果不等于 100.0，误差一点点累积。
 *        涉及"钱"的场景绝对不能用浮点，用整数（以"分"为单位）或定点数/十进制库。
 *
 * ======================= 四、浮点的特殊值 =======================
 * IEEE 754 保留了几种特殊状态（<math.h> 提供判断宏）：
 *      INFINITY    无穷大：1.0 / 0.0（注意：整数除 0 是崩溃，浮点除 0 是 inf）
 *      -INFINITY   负无穷
 *      NAN         "不是一个数"：0.0 / 0.0、sqrt(-1)
 * NaN 有个怪性质：它和任何值比较（包括自己）都返回假，
 *      所以判断要用 isnan(x)，不能写 x == NAN。
 *
 * ======================= 五、字面量与后缀 =======================
 *      3.14        double（默认）
 *      3.14f       float（f/F 后缀）
 *      3.14L       long double（L 后缀）
 *      1e3         科学计数法 = 1000.0
 *      .5          省略整数部分也合法，等于 0.5
 *      1.         省略小数部分也合法，等于 1.0
 * 注意：3.14 和 3.14f 不是同一个值——float 版本精度更低。
 *
 * ======================= 六、浮点与整数互转 =======================
 *      浮点 → 整数：直接截断小数部分，不是四舍五入
 *            (int)3.99   → 3
 *            (int)-3.99  → -3
 *            想四舍五入用 round()（<math.h>），或者 (int)(x + 0.5)（仅对正数成立）
 *      整数 → 浮点：可能丢精度
 *            超过 2^53 的整数转 double 会丢低位（因为尾数只有 52 位）
 *
 * ======================= 七、printf 输出浮点 =======================
 *      %f     默认 6 位小数        3.140000
 *      %.2f   保留 2 位            3.14
 *      %e     科学计数法           3.140000e+00
 *      %g     自动选短的形式       3.14
 *      %Lf    long double（注意大写 L）
 * 注意：printf 里 float 会自动提升成 double，所以 %f 就够，
 *       %lf 也合法但多余（scanf 里则必须用 %lf）。
 *
 * =========================== 八、常见坑 ===========================
 *  1. if (f == 0.1) 几乎永远为假
 *  2. 用 %d 打印 float/double    → 未定义行为
 *  3. 用浮点表示金额，1 分钱算着算着就丢了
 *  4. float 做大量累加，误差越滚越大
 *  5. (int) 转换是截断不是四舍五入
 *  6. 忘记 f 后缀，3.14 是 double 不是 float（与 float 运算会来回转换）
 *  7. 用 == 判断 NaN，应该用 isnan()
 *  8. 直接 printf("%f", 1/2) 里的 1/2 早在传参前就算成了 0
 */

#include <stdio.h>
#include <float.h>      /* FLT_MAX、DBL_MAX、FLT_EPSILON、DBL_EPSILON、FLT_DIG ... */
#include <math.h>       /* fabs、isnan、INFINITY、NAN */

int main(void)
{
    /* ---------- 1. 三种浮点的大小与有效位数 ---------- */
    printf("1. sizeof(float)=%zu  sizeof(double)=%zu  sizeof(long double)=%zu\n",
           sizeof(float), sizeof(double), sizeof(long double));
    printf("   float 有效位数=%d  double 有效位数=%d\n", FLT_DIG, DBL_DIG);
    printf("   float 最大值=%e  double 最大值=%e\n",
           (double)FLT_MAX, DBL_MAX);

    /* ---------- 2. 0.1 根本存不准：打印 17 位看尾巴 ---------- */
    float  f = 0.1f;
    double d = 0.1;
    printf("2. float  0.1 的 17 位 = %.17f\n", (double)f);
    printf("   double 0.1 的 17 位 = %.17f\n", d);
    printf("   都不是精确的 0.1，只是最接近的近似值\n");

    /* ---------- 3. float 与 double 精度差多少 ---------- */
    float  third_f = 1.0f / 3.0f;
    double third_d = 1.0 / 3.0;
    printf("3. 1/3 用 float : %.15f\n", (double)third_f);
    printf("   1/3 用 double: %.15f\n", third_d);
    printf("   float 后面那些数字是“凑出来的”，不可信\n");

    /* ---------- 4. 不要用 == 比较浮点 ---------- */
    double a = 0.1 + 0.2;
    double b = 0.3;
    printf("4. 0.1+0.2 = %.17f\n", a);
    printf("   0.1+0.2 == 0.3 ? %s\n", (a == b) ? "相等" : "不相等");
    /* 正确做法一：差值绝对值小于一个极小值（推荐） */
    double eps = 1e-9;
    printf("   fabs(a-b) < 1e-9 ? %s\n", (fabs(a - b) < eps) ? "相等" : "不相等");
    /* 正确做法二：不用 math.h 的写法 */
    printf("   不用 math.h 的写法：%s\n",
           ((a - b) < eps && (b - a) < eps) ? "相等" : "不相等");

    /* ---------- 5. 累计误差：加 1000 次 0.1 ---------- */
    double sum = 0.0;
    for (int i = 0; i < 1000; i++) {
        sum += 0.1;
    }
    printf("5. 0.1 累加 1000 次 = %.15f\n", sum);
    printf("   等于 100.0 吗？%s（误差一点点累积出来了）\n",
           (sum == 100.0) ? "是" : "不是");

    /* ---------- 6. 浮点转整数是截断，不是四舍五入 ---------- */
    double x = 3.99;
    printf("6. (int)3.99 = %d， (int)-3.99 = %d（直接砍掉小数）\n",
           (int)x, (int)-3.99);
    printf("   round(3.99) = %.0f（这才是四舍五入）\n", round(x));

    /* ---------- 7. 特殊值：inf 与 nan ---------- */
    double zero = 0.0;
    double inf  = 1.0 / zero;       /* 浮点除 0 得到无穷大，不崩溃 */
    double nan  = 0.0 / zero;       /* 0/0 得到 NaN */
    printf("7. 1.0/0.0 = %f（无穷大）\n", inf);
    printf("   0.0/0.0 = %f，isnan 判断 = %d\n", nan, isnan(nan));
    printf("   nan == nan ? %s（NaN 和谁比都不相等，必须用 isnan）\n",
           (nan == nan) ? "真" : "假");

    /* ---------- 8. 字面量与后缀 ---------- */
    float       lf = 3.14f;         /* f 后缀：float */
    double      ld = 3.14;          /* 默认就是 double */
    long double ll = 3.14L;         /* L 后缀：long double */
    double      sci = 1e3;          /* 科学计数法 = 1000.0 */
    printf("8. 3.14f=%.6f  3.14=%.15f  3.14L=%.15Lf 1e3=%.1f\n",
           (double)lf, ld, ll, sci);

    /* ---------- 9. 金额为什么不能用浮点 ---------- */
    /* 演示：0.1 元 + 0.2 元 不等于 0.3 元 */
    double money = 0.1 + 0.2;
    printf("9. 0.1 元 + 0.2 元 = %.17f 元\n", money);
    printf("   正确的做法：用整数以“分”为单位，10 + 20 = %d 分\n", 10 + 20);

    /* ---------- 10. 有效数字与打印位数 ---------- */
    /* 打印超过有效位数的部分只是噪声，不代表真的算得那么准 */
    printf("10. double 1.0/7.0 = %.20f\n", 1.0 / 7.0);
    printf("    超过 15~16 位之后的数字没有意义\n");

    /* ---------- 11. 选型建议 ---------- */
    printf("11. 选型：默认 double；内存紧张才 float；\n");
    printf("    需要更高精度用 long double（但不一定比 double 好，看平台）；\n");
    printf("    金额用整数分；比较用误差范围。\n");

    return 0;
}
