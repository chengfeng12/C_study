/*
 * printf_tutorial.c —— printf 用法教程（配套 01/hello.c）
 *
 * 编译：gcc printf_tutorial.c -o printf_demo
 * 运行：./printf_demo
 *
 * 阅读顺序：从上到下，每一节都先看注释，再看代码，最后看运行结果对照。
 * ---- 目录 ----
 *   1. 最基本用法
 *   2. 整型占位符
 *   3. 浮点占位符
 *   4. 字符与字符串
 *   5. 宽度 / 精度 / 对齐
 *   6. 常用转义字符
 *   7. printf 的返回值
 *   8. 新手最容易踩的坑
 *   9. puts / putchar 与 printf 的区别
 *
 * ============================== 占位符速查表 ==============================
 * 记忆口诀
 *   d 十进制   u 无符号   o 八进制   x 十六进制   f 浮点   e 科学计数
 *   c 字符     s 字符串   p 指针     % 百分号      n 已输出字符数
 *
 * ---- 整型 ----
 *   %d  / %i   有符号十进制 int          printf("%d", -42);      -> -42
 *   %u         无符号十进制 unsigned     printf("%u", 42u);      -> 42
 *   %o         八进制                    printf("%o", 8);        -> 10
 *   %x  / %X   十六进制（小写 / 大写）   printf("%x", 255);      -> ff
 *   %hd        short                     printf("%hd", s);
 *   %ld        long
 *   %lld       long long
 *   %zu        size_t（sizeof 的返回类型，无符号）
 *
 * ---- 浮点（float 会先自动提升成 double，所以统一用 %f 系列即可）----
 *   %f         小数形式，默认保留 6 位   printf("%f", 3.14);     -> 3.140000
 *   %.2f       保留 2 位小数（四舍五入） printf("%.2f", 3.14159);-> 3.14
 *   %e  / %E   科学计数法                printf("%e", 314.0);    -> 3.140000e+02
 *   %g  / %G   自动选较短的写法，去掉尾随的 0
 *   %Lf        long double
 *
 * ---- 字符、字符串、其它 ----
 *   %c         单个字符                  printf("%c", 'A');      -> A
 *   %s         字符串（必须以 '\0' 结尾）printf("%s", "abc");    -> abc
 *   %p         指针地址                  printf("%p", (void*)p); -> 0x7ffd...
 *   %%         输出一个百分号本身        printf("80%%");         -> 80%
 *   %n         把"已输出的字符数"写回 int*（极少用，有安全隐患）
 *
 * ---- 常用修饰（写在字母前面，可组合）----
 *   %5d    宽度 5，右对齐                [   42]
 *   %-5d   宽度 5，左对齐                [42   ]
 *   %05d   宽度 5，补 0                   [00042]
 *   %+d    强制带正负号                  [+42]
 *   %8.2f  总宽 8，小数 2 位             [    3.14]
 *   %-8s   字符串左对齐，宽 8            [ab      ]
 *
 * ---- 三条铁律 ----
 *   1. 占位符的字母必须来自 C 标准清单，自己编（如 %y）是未定义行为；
 *   2. 字母前的大小写有意义：%x 小写、%X 大写，不是随便写；
 *   3. 参数类型必须和占位符匹配，用 %d 打印 double/long 属于未定义行为。
 * ==========================================================================
 */

/* printf 声明在 stdio.h 中，必须包含，否则编译器不知道它的原型。 */
#include <stdio.h>

int main(void)
{
    /* ================================================================
     * 1. 最基本用法
     * ================================================================
     * 语法：printf("格式字符串", 参数1, 参数2, ...);
     * 格式字符串里的普通字符原样输出，以 % 开头的是"占位符"，
     * 会按顺序被后面的参数替换掉。
     * 参数个数、类型必须和占位符一一对应，编译器不会帮你检查类型（只对部分情况给警告）。
     */
    printf("1. Hello, printf!\n");

    /* ================================================================
     * 2. 整型占位符
     * ================================================================
     * %d / %i  十进制有符号整数（int），两者在 printf 里没有区别
     * %u       十进制无符号整数（unsigned）
     * %o       八进制
     * %x / %X  十六进制，小写 / 大写
     * %ld      长整型（long）；short 有对应的 %hd
     * 注意：用 %d 打印 long 或 float 属于未定义行为，结果不可靠。
     */
    int num = 255;

    /* 同一个变量用不同进制打印，数值不变，只是"写法"变了 */
    printf("2. 十进制=%d  八进制=%o  十六进制=%x  大写十六进制=%X\n",
           num, num, num, num);

    /* %u 要用无符号类型的值匹配，显式转换一下最稳妥 */
    printf("   无符号输出=%u\n", (unsigned)num);

    /* 一个 printf 可以同时有多个占位符，参数按从左到右的顺序填进去 */
    int a = 3, b = 4;
    printf("   a=%d, b=%d, a+b=%d\n", a, b, a + b);

    /* ================================================================
     * 3. 浮点占位符
     * ================================================================
     * %f   double / float（C 语言里 float 传参时会自动提升为 double，所以用 %f 就够）
     *      float 在 printf 里会自动"升级"成 double，这是默认参数提升规则，
     *      所以旧代码里的 %lf 在 printf 中其实是多余的（但合法）。
     * %e  科学计数法；%g 自动选择较短的形式
     * %.2f 表示保留 2 位小数（四舍五入），这是"精度"
     */
    double pi     = 3.14159265;
    double big    = 123456789.0;
    double tiny   = 0.00000123;

    printf("3. pi 默认 6 位小数 = %f\n", pi);   /* 默认保留 6 位 */
    printf("   pi 保留 2 位     = %.2f\n", pi);  /* .2 就是精度 */
    printf("   pi 保留 0 位     = %.0f\n", pi);  /* 会四舍五入成 3 */
    printf("   科学计数法       = %e\n", big);
    printf("   自动选择         = %g\n", tiny);
    /* 这里看到 0.000001 说明 %g 会自己决定用普通写法还是科学计数法 */

    /* ================================================================
     * 4. 字符与字符串
     * ================================================================
     * %c   单个字符
     * %s   字符串（以 '\0' 结尾的字符数组）
     * %p   指针地址（一般配合强制转换使用）
     * %%   输出一个百分号本身
     */
    char   ch     = 'A';
    char   name[] = "小明";   /* 中文字符串在 UTF-8 下占多个字节，但 %s 照样能完整输出 */

    printf("4. 字符=%c, 它的 ASCII=%d\n", ch, ch);  /* 字符本质是小整数，所以能用 %d 打出编码 */
    printf("   字符串=%s\n", name);
    printf("   变量 name 的地址=%p\n", (void *)name); /* 指针要转换成 void* 才符合标准 */
    printf("   折扣 80%%\n");                        /* 想打印 % 必须写 %% */

    /* ================================================================
     * 5. 宽度 / 精度 / 对齐
     * ================================================================
     * %5d     至少占 5 个字符宽，右对齐（不够左边补空格）
     * %-5d    同样宽度，但左对齐（不够右边补空格）
     * %05d    用 0 补齐而不是空格
     * %+d     强制显示正负号
     * %8.2f   总宽 8，其中小数 2 位
     * %-8s    字符串左对齐占 8 宽
     */
    printf("5. [%5d][%-5d][%05d][%+d]\n", 42, 42, 42, 42);
    printf("   [%8.2f][%-8.2f]\n", pi, pi);
    printf("   [%8s][%-8s]\n", "ab", "ab");

    /* 实际用途：对齐表格。宽度给足，各列就整齐了
     * 注意！宽度按"字节"算，不是按"显示宽度"算。
     * UTF-8 下一个汉字占 3 字节，"姓名"正好 6 字节，会填满 %-6s 而不补空格，
     * 于是中文列会挤在一起（运行结果里就能看到）。
     * 纯英文/数字的表格没有这个问题；中文表格要么把宽度调大，要么另想办法对齐。 */
    printf("   %-6s%-6s%-6s\n", "姓名", "语文", "数学");
    printf("   %-6s%-6d%-6d\n", "小明", 90, 85);
    printf("   %-6s%-6d%-6d\n", "小红", 78, 96);

    /* ================================================================
     * 6. 常用转义字符
     * ================================================================
     * \n  换行      \t  制表符（Tab，用来对齐）   \\  反斜杠本身
     * \"  双引号    \'  单引号                    %%  百分号
     * \a  响铃（很多终端已无声音）
     * \r  回车（回到行首，常用来做进度条刷新）
     */
    printf("6. 第一行\n   第二行（\n 换行）\n");
    printf("   列1\t列2\t列3\n");
    printf("   路径写法：C:\\code\\demo.c\n");
    printf("   引号写法：\"双引号\" 和 '单引号' 在字符串里可以直接写\n");

    /* ================================================================
     * 7. printf 的返回值
     * ================================================================
     * printf 返回"实际输出了多少个字符"，出错时返回负数。
     * 注意：\n 也只算 1 个字符；中文在 UTF-8 下占 3 个字节，会被算成 3 个字符。
     */
    int n = printf("7. abc\n");
    printf("   上一行 printf 返回了 %d\n", n);

    /* ================================================================
     * 8. 新手最容易踩的坑
     * ================================================================
     * 下面这些代码故意注释掉了，因为它们要么是未定义行为，要么会崩溃。
     * 想验证的话，一次只取消注释一行，编译时加上 -Wall 看警告。
     *
     * (1) 用 %d 打印 double：类型不匹配，输出是垃圾值
     *     double d = 1.5;
     *     printf("%d\n", d);
     *
     * (2) 占位符数量和参数数量不一致：
     *     printf("%d %d\n", 1);        // 少给一个，第二个会读到栈上的垃圾
     *
     * (3) 字符串没加 '\0'：%s 会越界一直读到内存里的 0 才停
     *     char s[3] = {'a', 'b', 'c'};
     *     printf("%s\n", s);
     *
     * (4) 用 %s 打印空指针：直接崩溃
     *     char *p = NULL;
     *     printf("%s\n", p);
     *
     * (5) 忘记写 \n：下一次输出会黏在同一行，看起来像"输出丢了"
     *
     * 记忆口诀：占位符 = 类型的"门牌号"，门牌号写错，进去的就是别人家。
     */

    /* ================================================================
     * 9. puts / putchar 与 printf 的区别
     * ================================================================
     * puts(s)    输出字符串并自动补一个换行，不需要写 \n，比 printf 快一点
     * putchar(c) 输出单个字符
     * printf     最灵活，能格式化，但开销也最大
     * 只输出一整行固定文本时，puts 更省事；需要拼数字、对齐时才用 printf。
     */
    puts("9. 我是 puts，我会自动换行");
    putchar('A');
    putchar('\n');

    /* main 返回 0 告诉操作系统"程序正常结束" */
    return 0;
}
