/*
 * 11_输入输出函数.c —— 阶段1 / 第 01 课 / 第 11 个文件：输入输出函数
 *
 * 编译：gcc 11_输入输出函数.c -o io_demo
 * 运行：./io_demo
 *      程序中途会让你输入，按提示敲完回车即可。
 *      想一次性跑完，也可以用管道喂数据：
 *          printf '42\nhello world\n' | ./io_demo
 *
 * ====================== 一、C 的输入输出是怎么回事 ======================
 * C 语言本身**没有**输入输出语句（不像 Python 的 print/input 关键字），
 * 所有 I/O 都靠标准库 <stdio.h> 里的函数完成。
 *
 * stdio = standard input/output。它把一切 I/O 都抽象成"流"（stream）：
 *      stdin    标准输入    默认是键盘
 *      stdout   标准输出    默认是终端屏幕
 *      stderr   标准错误    默认也是屏幕，但可以单独重定向
 * 程序启动时这三个流自动打开，不需要你手动打开文件。
 *
 * 常用函数一览（本篇逐个演示）：
 *      格式化输出：printf、sprintf、snprintf、fprintf
 *      格式化输入：scanf、sscanf、fscanf
 *      字符级：    getchar、putchar
 *      行级：      fgets、puts、fputs
 *
 * ★ 一条贯穿全篇的主线：
 *   输入函数用起来比输出函数危险得多，因为"用户输入"是你控制不了的东西。
 *   所有输入都必须：检查返回值、限制长度、考虑非法输入。
 *
 * ========================== 二、printf 输出 ==========================
 * 语法：printf("格式串", 参数...);
 * 返回值：成功输出的字符数，失败返回负数。
 * 常用占位符（详见 02 篇）：
 *      %d %u %ld %lld   整数      %f %.2f   浮点
 *      %c %s            字符/串   %x %o    进制
 *      %p               指针      %%       百分号
 *
 * 变体：
 *      fprintf(fp, "...")   输出到指定流，比如 stderr
 *      sprintf(buf, "...")  输出到字符串（危险！不检查长度）
 *      snprintf(buf, n, "...") 输出到字符串并限制长度（安全，推荐）
 *
 * ★ sprintf 是经典的缓冲区溢出源头：
 *      char buf[10];
 *      sprintf(buf, "%s", "一段很长很长的文字");   // ✗ 直接踩坏内存
 *   应该用 snprintf：
 *      snprintf(buf, sizeof(buf), "%s", "很长...");  // ✓ 最多写 9 字符 + '\0'
 *   snprintf 的返回值是"原本想写多少字符"，不是"实际写了多少"，
 *   所以判断是否被截断要比较返回值 >= 缓冲区大小。
 *
 * ========================= 三、字符级输出：putchar =========================
 *      putchar(c)     输出一个字符，成功返回该字符，失败返回 EOF
 * 比 printf("%c", c) 更轻量，循环里输出字符时常用。
 *
 * ======================== 四、行级输出：puts / fputs ========================
 *      puts(s)        输出字符串并自动补一个 '\n'    ✓ 简单场景首选
 *      fputs(s, fp)   输出字符串，不自动换行
 * 注意 puts 会自动换行，所以不用再写 \n，写了会多一个空行。
 * puts 失败返回 EOF，成功返回非负数。
 *
 * ===================== 五、scanf：格式化输入（重点） =====================
 * 语法：scanf("格式串", &变量1, &变量2, ...);
 *
 * ★ 三个必须记住的点：
 *   1) 后面必须传"地址"，所以基本类型要加 &（数组名本身是地址，不加）
 *          scanf("%d", &n);         ✓
 *          scanf("%d", n);          ✗ 崩溃或乱写内存
 *          scanf("%s", str);        ✓ 数组名已是地址
 *   2) 返回值是"成功匹配并赋值的项数"，不是 EOF/成功
 *          int n = scanf("%d %d", &a, &b);
 *          n == 2  → 两个都读到了
 *          n == 1  → 只读到第一个
 *          所以要检查：if (scanf("%d", &a) != 1) { 处理错误 }
 *   3) 输入格式必须匹配。用户输入了字母，%d 会失败，
 *      而且失败的字符会**留在缓冲区里**，下次调用继续失败 → 死循环。
 *
 * ★ scanf 的六个经典坑：
 *   (1) 忘记 &          → 段错误
 *   (2) %s 不限制长度    → 输入超长就溢出，要写 %49s（留 1 字节给 '\0'）
 *   (3) %c 会读到空白字符 → 前面残留的换行符会被当成一个字符读走
 *                          解决：写成 " %c"（格式串里加一个空格，跳过空白）
 *   (4) 换行符残留       → scanf("%d") 读完数字后，'\n' 还在缓冲区，
 *                          接着 fgets 会读到一个空行
 *   (5) 不检查返回值     → 用户乱输入时程序行为不可控
 *   (6) 想读整行用 scanf("%s") 是错的  → %s 遇到空格就停，
 *                          "hello world" 只能读到 "hello"，读整行要用 fgets
 *
 * ★ 5.1 格式串里的普通字符（逗号、短横线）必须原样输入
 * 课件里的这个例子最能说明问题：
 *      int a, b, c;
 *      scanf("%d,%d,%d", &a, &b, &c);      // 注意格式串里有两个英文逗号
 *      int result = a * b * c;
 *      printf("result = %d\n", result);
 * 这里的逗号不是"给程序员看的说明"，而是 scanf 要逐个比对的**字面字符**：
 *      用户输入 1,2,3    → 匹配成功，a=1 b=2 c=3，返回 3
 *      用户输入 1 2 3    → 读完 1 之后期待逗号却遇到空格，立即停止，
 *                          返回 1，b 和 c 保持原值（通常是垃圾值或 0）
 * 同理：
 *      "%d-%d"   要求输入 1-2
 *      "%d/%d"   要求输入 1/2
 *      "%d %d"   要求输入 1 2（空白字符可以匹配任意多个空格/换行，比较宽松）
 * 因此：
 *   1) 一定要检查返回值，== 3 才能相信三个变量都被赋值了
 *   2) 提示语里必须告诉用户"用逗号分隔"，否则用户按习惯敲空格就全错了
 *   3) 如果想让"空格和逗号都接受"，scanf 难以胜任，
 *      应该先 fgets 读一整行，再用 sscanf/strtok 自己解析
 *
 * ===================== 六、fgets：读一整行（推荐） =====================
 *      char line[100];
 *      fgets(line, sizeof(line), stdin);
 * 特点：
 *   1) 最多读 n-1 个字符，剩下的位置留给 '\0' —— 天然防溢出
 *   2) 读到 '\n' 也会存进去（scanf 的 %s 不会）
 *      所以通常要手动去掉行尾换行：
 *          line[strcspn(line, "\n")] = '\0';
 *   3) 遇到 EOF 或出错返回 NULL，必须检查
 *   4) 如果一行超过缓冲区，剩下的部分会留在缓冲区里，下次继续读
 *
 * ★ gets 已经被 C11 从标准中删除，永远不要用：
 *      它不检查长度，任何超长输入都会溢出，是历史上最著名的安全漏洞之一。
 *
 * ====================== 七、getchar：读单个字符 ======================
 *      int c = getchar();      返回 int 而不是 char，见下面说明
 * 为什么返回 int：
 *      需要能返回 EOF（通常是 -1）。char 可能是无符号的，装不下 -1，
 *      所以标准规定用 int 接收。这是很多初学者写错的地方。
 *
 * 标准读法：
 *      int c;
 *      while ((c = getchar()) != EOF) {   // 括号不能少！
 *          putchar(c);
 *      }
 * 这个循环会把输入原样输出（类似 cat 命令），按 Ctrl+D（macOS/Linux）
 * 或 Ctrl+Z 回车（Windows）表示输入结束，也就是 EOF。
 *
 * ★ 常用技巧：清空输入缓冲区
 *      int c;
 *      while ((c = getchar()) != '\n' && c != EOF) { }
 *   在 scanf 读了数字、下一次要用 fgets 读整行时，必须做这一步，
 *   否则缓冲区里剩下的 '\n' 会被 fgets 当成一个空行读走。
 *
 * ====================== 八、输出格式的一些实用细节 ======================
 *      对齐表格：%-10s %5d %8.2f（详见 02 篇第 5 节）
 *      输出到标准错误：fprintf(stderr, "错误：...\n");
 *          好处：标准输出可以被重定向到文件，错误信息仍然显示在屏幕上
 *      刷新缓冲：printf 的数据先存在缓冲区，遇 '\n' 或程序结束才真正输出；
 *          调试时程序崩溃了却看不到输出，可以在 printf 后加 fflush(stdout);
 *      换行也有缓冲意义：交互式程序里没有 '\n' 时，提示语可能迟迟不显示
 *
 * ========================== 九、选型建议 ==========================
 *  输出：
 *      只输出一个字符串并换行       puts
 *      只输出一个字符               putchar
 *      需要拼数字、对齐、格式       printf
 *      拼到字符串里                 snprintf（不要用 sprintf）
 *      输出错误信息                 fprintf(stderr, ...)
 *  输入：
 *      读一整行                     fgets + 去换行
 *      读若干个格式化的值           scanf（记得检查返回值）
 *      从已有的字符串里解析         sscanf
 *      逐字符处理                   getchar
 *      永远不要用                   gets
 */

#include <stdio.h>
#include <string.h>     /* strcspn */

int main(void)
{
    /* ---------- 1. printf 基本输出 ---------- */
    printf("1. printf：整数 %d，浮点 %.2f，字符 %c，字符串 %s\n",
           42, 3.14159, 'A', "hello");

    /* ---------- 2. putchar：输出单个字符 ---------- */
    printf("2. putchar 输出三个字符：");
    putchar('A');
    putchar('B');
    putchar('C');
    putchar('\n');          /* putchar 不会自动换行，要自己加 */

    /* ---------- 3. puts：输出字符串并自动换行 ---------- */
    puts("3. puts 会自动换行，不用再写 \\n");

    /* ---------- 4. snprintf：把内容拼进字符串（安全版 sprintf） ---------- */
    char buf[32];
    int  need = snprintf(buf, sizeof(buf), "姓名=%s 年龄=%d", "小明", 20);
    printf("4. snprintf 结果：\"%s\"\n", buf);
    printf("   返回值 need=%d（本该写 %d 个字符），缓冲区大小 %zu\n",
           need, need, sizeof(buf));

    /* 演示截断：缓冲区太小会发生什么 */
    char small[10];
    int  need2 = snprintf(small, sizeof(small), "%s", "0123456789ABCDEF");
    printf("   截断演示：small=\"%s\"，need2=%d\n", small, need2);
    printf("   注意 need2=%d 大于缓冲区，说明被截断了（返回值不是实际写入长度）\n",
           need2);

    /* ---------- 5. sscanf：从字符串里解析数据 ---------- */
    /* 它和 scanf 用法一样，只是"输入源"是一个字符串，不会阻塞等待 */
    const char *record = "张三 95 88.5";
    char  name[20];
    int   chinese;
    float math;
    int   got = sscanf(record, "%19s %d %f", name, &chinese, &math);
    printf("5. sscanf 从 \"%s\" 解析到 %d 个字段：\n", record, got);
    printf("   姓名=%s 语文=%d 数学=%.1f\n", name, chinese, (double)math);

    /* ---------- 6. 从键盘读一个整数：scanf 的正确写法 ---------- */
    int number = 0;
    printf("6. 请输入一个整数，然后回车：");
    /* 检查返回值：只有等于 1 才说明真的读到了一个整数 */
    if (scanf("%d", &number) == 1) {
        printf("   读到了 %d，它的两倍是 %d\n", number, number * 2);
    } else {
        printf("   输入的不是整数，读取失败\n");
    }

    /* ---------- 7. 清空缓冲区里残留的换行符 ---------- */
    /* scanf("%d") 读完数字就停了，用户按的 '\n' 还留在缓冲区里 */
    int c;
    while ((c = getchar()) != '\n' && c != EOF) {
        /* 一直读到换行为止，什么也不做，相当于"清空" */
    }
    printf("7. 已经清掉缓冲区里残留的换行符\n");

    /* ---------- 8. fgets：读一整行（含空格） ---------- */
    char line[100];
    printf("8. 请再输入一行文字（可以带空格），然后回车：");
    if (fgets(line, sizeof(line), stdin) != NULL) {
        /* fgets 会把 '\n' 也存进来，先去掉它 */
        line[strcspn(line, "\n")] = '\0';
        printf("   读到了：\"%s\"（长度 %zu）\n", line, strlen(line));
    } else {
        printf("   读取失败或遇到 EOF\n");
    }

    /* ---------- 9. 三个整数相乘：格式串里带逗号的 scanf（课件例子） ---------- */
    /* 课件里的写法：
     *     scanf("%d,%d,%d", &a, &b, &c);
     *     int result = a * b * c;
     *     printf("result = %d\n", result);
     *
     * ★ 关键点：格式串里的逗号、短横线、冒号，都是"普通字符"，
     *   必须原样出现在输入里。scanf 会逐个字符比对，对不上就停止。
     *
     *     "%d,%d,%d"   要求输入   1,2,3     ← 英文逗号分隔
     *     "%d %d %d"   要求输入   1 2 3     ← 空白分隔（空格/制表/换行都算）
     *     "%d-%d-%d"   要求输入   1-2-3
     *
     * 如果格式串里写了逗号，用户却用空格输入：
     *     输入 "1 2 3"
     *     scanf 读完第一个 %d 得到 1，接着期待一个逗号，却看到空格 →
     *     匹配失败，立即返回 1，后两个变量保持原值（这里是 0）。
     * 所以返回值检查非常关键：只有等于 3 才算三个都读到了。
     */
    int n1 = 0, n2 = 0, n3 = 0;
    printf("9. 请输入三个整数，用英文逗号分隔（例如 1,2,3），然后回车：");
    if (scanf("%d,%d,%d", &n1, &n2, &n3) == 3) {
        int result = n1 * n2 * n3;
        printf("   result = %d\n", result);
    } else {
        printf("   格式不匹配！格式串里的逗号必须原样输入\n");
    }
    /* 读完之后同样要清掉行尾残留，否则会影响后面的输入 */
    while ((c = getchar()) != '\n' && c != EOF) {
        /* 空循环，只负责吃掉残留字符 */
    }

    /* ---------- 10. 字符串与字符的对照 ---------- */
    /* %s 遇到空白就停，%c 只读一个字符 */
    char word[20] = {0};
    sscanf("hello world", "%19s", word);
    printf("10. sscanf(\"hello world\", \"%%19s\") 只得到 \"%s\"（空格处停止）\n",
           word);

    /* ---------- 11. 输出到标准错误 ---------- */
    /* stderr 不参与 stdout 的缓冲，适合输出错误信息 */
    fprintf(stderr, "11. 这一行是写到 stderr 的（屏幕上和 stdout 混在一起，"
                    "但重定向时可以分开）\n");

    /* ---------- 12. getchar 的 EOF 循环（这里用注释说明） ---------- */
    /*
     * int c;
     * while ((c = getchar()) != EOF) {
     *     putchar(c);          // 原样回显，类似 cat
     * }
     * 注意：
     *   1) c 必须是 int，不能是 char（要能装下 EOF 的 -1）
     *   2) while 里的括号不能少：(c = getchar()) != EOF
     *      写成 c = getchar() != EOF 意思是 c = (getchar() != EOF)，逻辑全错
     *   3) Ctrl+D（macOS/Linux）或 Ctrl+Z 回车（Windows）表示 EOF
     */
    printf("12. getchar/EOF 循环的写法见注释（Ctrl+D 表示输入结束）\n");

    /* ---------- 13. 常见坑总结 ---------- */
    printf("13. 记住这几条：\n");
    printf("    scanf 基本类型要加 &，用 %%49s 限制长度\n");
    printf("    scanf 要检查返回值，等于期望的项数才算成功\n");
    printf("    格式串里的逗号等普通字符，输入时必须原样写出来\n");
    printf("    读整行用 fgets，不要用 scanf(\"%%s\")\n");
    printf("    scanf 之后接 fgets 之前，先清掉残留的 '\\n'\n");
    printf("    拼字符串用 snprintf，不要用 sprintf\n");
    printf("    永远不要用 gets（已从标准中删除）\n");

    return 0;
}

