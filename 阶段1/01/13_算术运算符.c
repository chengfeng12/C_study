/*
 * 13_算术运算符.c —— 阶段1 / 第 01 课 / 第 13 个文件：算术运算符
 *
 * 编译：gcc 13_算术运算符.c -o arith_demo
 * 运行：./arith_demo
 *
 * ======================= 一、C 的算术运算符有哪些 =======================
 *      二元（两边各一个操作数）：
 *          +    加
 *          -    减
 *          *    乘
 *          /    除      ← 本节主角，int/int 和浮点除法的行为完全不同
 *          %    取模（求余）  ← 只能用于整数
 *      一元（只有一个操作数）：
 *          +a   正号（几乎不用）
 *          -a   负号
 *          ++   自增（a++ / ++a）
 *          --   自减（a-- / --a）
 *      复合赋值：
 *          +=  -=  *=  /=  %=
 *
 * ======================= 二、优先级与结合性 =======================
 * 从高到低：
 *      1) ++ --（后缀）  ()  []
 *      2) ++ --（前缀）  + -（一元）  !  ~
 *      3) *  /  %
 *      4) +  -
 *      5) <<  >>
 *      6) <  <=  >  >=
 *      7) ==  !=
 *      ...
 * 同级的 * / % 和 + - 都是"从左往右"结合：
 *      a - b - c   等价于   (a - b) - c
 *      a / b / c   等价于   (a / b) / c
 * 记不住就加括号——括号不花钱，bug 才花钱。
 *
 * ================== 三、int / int：最容易出错的运算 ==================
 * ★ 核心规则：两个整数相除，结果还是整数，小数部分直接丢掉（向零截断）。
 *
 *      7 / 2   == 3      （不是 3.5）
 *      -7 / 2  == -3     （C99 起规定向零截断，不是向下取整 -4）
 *      7 / -2  == -3
 *      5 / 9   == 0      （装不下一个 9，商就是 0）
 *      1 / 2   == 0
 *
 * 为什么：C 要让"整数除法"尽量快，用整数除法指令一步到位，
 * 结果自然就是整数。想要小数，必须让至少一个操作数是浮点类型。
 *
 * ★ 三种拿到"带小数结果"的写法（任选其一）：
 *      (double)a / b           // 强制转换，最明确
 *      a / (double)b
 *      a * 1.0 / b             // 乘个 1.0 提升成 double
 * 注意括号位置：
 *      (double)(a / b)  ✗ 先把整数除法算完再转，小数早没了
 *      (double)a / b    ✓ 先转再除
 *
 * ★ int / int 的典型事故场景：
 *   1) 求平均分
 *          int avg = total / count;        // 85.67 变成 85
 *          double avg = (double)total / count;
 *   2) 求百分比
 *          int pct = 5 / 9 * 100;          // 先算 5/9 = 0，再乘 100 还是 0
 *          double pct = 5.0 / 9 * 100;
 *   3) 华氏转摄氏
 *          int c = 5 / 9 * (f - 32);       // 恒为 0
 *   4) 金融计算
 *          int yuan = fen / 100;           // 丢掉分，需要四舍五入要自己处理
 *   5) 缩放比例
 *          int scaled = value / 1000;      // 小数部分全丢
 *   结论：只要脑子里想的是"小数结果"，就先把操作数转成 double。
 *
 * ========================== 四、取模 % ==========================
 *      %   求余数，只能用于整数（浮点要用 <math.h> 的 fmod）
 *
 *      7 % 3   == 1
 *      7 % 7   == 0
 *      5 % 9   == 5     （除不尽，余数就是被除数本身）
 *      -7 % 3  == -1    （C99：余数符号跟随"被除数"，不是除数）
 *      7 % -3  == 1
 *
 * 经典用途：
 *      判断奇偶：n % 2 == 0  → 偶数
 *      循环取模：i % 10       → 拿到最后一位
 *      周期切换：i % 3        → 0,1,2,0,1,2...
 *      判断整除：n % k == 0
 * 注意：负数取模的结果可能为负，所以"判断奇偶"更稳的写法是 n % 2 != 0。
 *
 * ====================== 五、整数溢出 ======================
 * int 只有 4 字节，范围 -2147483648 ~ 2147483647，超出就溢出：
 *      signed  溢出 → 未定义行为（UB），结果不可预测，别依赖
 *      unsigned 溢出 → 回绕（模 2^32），标准明确规定
 *
 * 常见的溢出场景：
 *      两个大数相加 / 相乘（中间结果超范围）
 *      阶乘、累加、斐波那契等循环增长的量
 *      把 long 的结果塞回 int
 *
 * 安全做法：
 *   1) 运算前先判断：if (a > INT_MAX - b) 说明 a+b 会溢出
 *   2) 用更宽的类型：long long 或 int64_t
 *   3) 用编译器内置函数：__builtin_add_overflow（GCC/Clang）
 *
 * ============ 六、0.1 + 0.2 为什么不等于 0.3 ============
 * 这是浮点最著名的现象，原因是二进制无法精确表示十进制的 0.1：
 *      0.1（十进制） = 0.0001100110011001100...（二进制，无限循环）
 * double 只有 52 位尾数，存不下无限循环，只能截断成近似值。
 * 于是：
 *      0.1  ≈ 0.1000000000000000055511151231257827
 *      0.2  ≈ 0.2000000000000000111022302462515654
 *      相加 ≈ 0.3000000000000000444089209850062616
 * 而 0.3 的近似值是 0.29999999999999998889776975374843...
 * 两者不相等，所以：
 *      if (0.1 + 0.2 == 0.3)   →  假
 *
 * ★ 正确做法：
 *   1) 用误差范围比较：
 *          #include <math.h>
 *          if (fabs(a - b) < 1e-9)   认为相等
 *   2) 不要用浮点存金额：
 *          float 存 0.1 元，累加 1000 次 ≠ 100 元
 *          要用整数以"分"为单位：10 分 + 20 分 = 30 分
 *   3) 需要高精度计算用专门的库（如 GMP、十进制库）
 *
 * ★ 另一类精度问题：大整数转浮点会丢低位
 *      float 只有约 7 位有效数字，int 最多 10 位，
 *      超过 2^24 的整数转 float 就不精确了。
 *
 * ================== 七、混合类型运算：int 与 double ==================
 * 规则（详见 09 篇）：运算前先统一类型，整数会向浮点靠拢。
 *      int / int      → 整数除法（小数丢失）
 *      int / double   → 浮点除法
 *      double / int   → 浮点除法
 *      sizeof(1 + 1.5) == 8     结果类型是 double
 * 记住：**只要有一个操作数是浮点，整个表达式就是浮点运算**。
 *
 * ====================== 八、自增自减 ++ / -- ======================
 *      ++a   前缀：先加 1，再取值
 *      a++   后缀：先取值，再加 1
 *      --a / a--  同理
 * 例子：
 *      int a = 5;
 *      int b = ++a;    // a 先变 6，b 得 6
 *      int c = a++;    // c 得 6，a 再变 7
 * ★ 危险写法（未定义行为，结果因编译器而异）：
 *      int i = 0;
 *      i = i++ + ++i;          // ✗ 同一个变量在一个表达式里被改多次
 *      printf("%d %d", i++, i++);  // ✗ 参数求值顺序未指定
 * 规则：一个表达式中，同一个变量最多被修改一次。
 * 建议：别在复杂表达式里用 ++/--，单独写一行最清楚。
 *
 * ====================== 九、复合赋值运算符 ======================
 *      a += b   等价于   a = a + b
 *      a -= b   等价于   a = a - b
 *      a *= b   等价于   a = a * b
 *      a /= b   等价于   a = a / b
 *      a %= b   等价于   a = a % b
 * ★ a /= b 这里同样遵循整数除法规则：
 *      int a = 7; a /= 2;    → a 变成 3，不是 3.5
 * 复合赋值还有个隐藏好处：左边只求值一次（对数组下标、指针解引用有意义）。
 *
 * ====================== 十、除以零 ======================
 *      整数除零：1 / 0        → 未定义行为，程序通常直接崩溃（SIGFPE）
 *      整数取模零：1 % 0      → 同样崩溃
 *      浮点除零：1.0 / 0.0    → 得到 inf（无穷大），不崩溃
 *                0.0 / 0.0    → 得到 nan（不是数）
 * 所以做除法前一定要确认除数不为 0，这是最基本的防御性编程。
 *
 * ====================== 十一、常见坑 ======================
 *  1. int/int 得到整数，以为会自动变小数      5/2 == 2
 *  2. (double)(a/b) 写错括号，小数早就丢了
 *  3. 负数除法/取模的符号记错                -7/2 == -3，-7%3 == -1
 *  4. int 溢出                               结果变成负数或乱码
 *  5. 用 == 比较浮点                         0.1+0.2 == 0.3 恒假
 *  6. 用浮点算钱                             0.1 累加 10 次不等于 1
 *  7. 表达式里多次修改同一变量               i = i++ 未定义行为
 *  8. 除数为 0 没检查                        整数除零直接崩
 *  9. a * b 的中间结果溢出，再赋给 long long  转类型要在"运算前"做
 * 10. % 用在浮点上                          编译报错，要用 fmod
 *
 * ====================== 十二、实践建议 ======================
 *  - 要小数，一开始就用 double，不要用 int 算完再转
 *  - 整数相除前先问自己：我要的是"商"还是"精确比值"？
 *  - 浮点比较永远用误差范围，不用 ==
 *  - 金额用整数（分），比例用 double
 *  - 大数运算前先估算范围，必要时用 long long
 *  - 除法前检查除数是否为 0
 *  - 别在复杂表达式里用 ++/--，拆成多行
 */

#include <stdio.h>
#include <limits.h>     /* INT_MAX */
#include <math.h>       /* fabs */

int main(void)
{
    /* ---------- 1. 五个基本运算符 ---------- */
    int a = 17, b = 5;
    printf("1. a=%d b=%d：a+b=%d  a-b=%d  a*b=%d  a/b=%d  a%%b=%d\n",
           a, b, a + b, a - b, a * b, a / b, a % b);

    /* ---------- 2. 优先级与结合性 ---------- */
    printf("2. 2+3*4   = %d（先乘后加）\n", 2 + 3 * 4);
    printf("   (2+3)*4 = %d（括号优先）\n", (2 + 3) * 4);
    printf("   100/10/2= %d（同级从左往右：(100/10)/2）\n", 100 / 10 / 2);

    /* ---------- 3. int / int：结果还是 int ---------- */
    int x = 7, y = 2;
    printf("3. 7/2  = %d（不是 3.5）\n", x / y);
    printf("   -7/2 = %d（向零截断，不是 -4）\n", -7 / 2);
    printf("   5/9  = %d（装不下一个 9，商为 0）\n", 5 / 9);
    printf("   1/2  = %d\n", 1 / 2);

    /* ---------- 4. 想要小数结果：三种写法 ---------- */
    printf("4. (double)7/2  = %.2f（推荐：先转再除）\n", (double)x / y);
    printf("   7/(double)2  = %.2f\n", x / (double)y);
    printf("   7*1.0/2      = %.2f\n", x * 1.0 / y);
    printf("   (double)(7/2)= %.1f ← 错误！先把 3 算出来再转，小数早丢了\n",
           (double)(x / y));

    /* ---------- 5. 取模 %：余数符号跟随被除数 ---------- */
    printf("5. 7%%3  = %d\n", 7 % 3);
    printf("   5%%9  = %d（除不尽，余数就是自己）\n", 5 % 9);
    printf("   -7%%3 = %d（C99 起：符号跟被除数）\n", -7 % 3);
    printf("   7%%-3 = %d\n", 7 % -3);
    /* 判断奇偶的标准写法，负数也安全 */
    int n = -7;
    printf("   %d 是%s\n", n, (n % 2 != 0) ? "奇数" : "偶数");

    /* ---------- 6. 典型事故：平均分与百分比 ---------- */
    int total = 257, count = 3;
    printf("6. 平均分（错误写法）total/count = %d\n", total / count);
    printf("   平均分（正确写法）(double)total/count = %.2f\n",
           (double)total / count);

    int part = 5, whole = 9;
    printf("   百分比（错误）5/9*100 = %d\n", part / whole * 100);
    printf("   百分比（正确）5.0/9*100 = %.2f%%\n", 5.0 / whole * 100);

    /* ---------- 7. 整数溢出 ---------- */
    /* signed 溢出是未定义行为，这里不真的去算，只演示"运算前判断"的思路 */
    int big1 = 2000000000, big2 = 2000000000;
    if (big1 > INT_MAX - big2) {
        printf("7. %d + %d 会溢出，已被提前拦住\n", big1, big2);
    } else {
        printf("7. %d + %d = %d\n", big1, big2, big1 + big2);
    }

    /* 无符号溢出是"回绕"，标准保证，可以依赖 */
    unsigned int u = UINT_MAX;
    printf("   UINT_MAX + 1 = %u（回绕到 0）\n", u + 1);

    /* 用更宽的类型避免溢出：先转再做乘法 */
    int m1 = 100000, m2 = 100000;
    long long safe = (long long)m1 * m2;    /* 关键：转类型要在乘法"之前" */
    printf("   100000*100000 用 long long = %lld\n", safe);

    /* ---------- 8. 0.1 + 0.2 的经典问题 ---------- */
    double d1 = 0.1, d2 = 0.2;
    double sum = d1 + d2;
    printf("8. 0.1 + 0.2 = %.17f\n", sum);
    printf("   0.3         = %.17f\n", 0.3);
    printf("   两者相等吗？%s\n", (sum == 0.3) ? "相等" : "不相等");

    /* ---------- 9. 浮点比较的正确做法 ---------- */
    double eps = 1e-9;
    printf("9. fabs(sum-0.3) = %.2e\n", fabs(sum - 0.3));
    printf("   差值 < 1e-9 就认为相等 → %s\n",
           (fabs(sum - 0.3) < eps) ? "相等" : "不相等");

    /* ---------- 10. 浮点累计误差：钱不能这么算 ---------- */
    double money = 0.0;
    for (int i = 0; i < 10; i++) {
        money += 0.1;                   /* 每次加 1 毛钱 */
    }
    printf("10. 0.1 累加 10 次 = %.17f（不等于 1.0）\n", money);
    printf("    等于 1.0 吗？%s\n", (money == 1.0) ? "是" : "不是");
    /* 正确做法：用整数以"分"为单位 */
    int fen = 0;
    for (int i = 0; i < 10; i++) {
        fen += 10;                      /* 每次 10 分 */
    }
    printf("    用整数分累加 = %d 分，即 %.1f 元（精确）\n", fen, fen / 100.0);

    /* ---------- 11. 混合类型运算 ---------- */
    int    i1 = 5;
    double d3 = 2.0;
    printf("11. 5/2        = %d（int/int）\n", 5 / 2);
    printf("    5/2.0      = %.1f（有 double 参与，自动转浮点）\n", 5 / 2.0);
    printf("    sizeof(5+2.0) = %zu 字节（结果类型是 double）\n", sizeof(5 + 2.0));
    printf("    用变量也一样：i1/d3 = %.1f\n", i1 / d3);

    /* ---------- 12. 自增自减 ---------- */
    int p = 5;
    int pre  = ++p;         /* p 先变 6，pre 得 6 */
    int post = p++;         /* post 得 6，p 再变 7 */
    printf("12. ++p 后 pre=%d，p++ 后 post=%d，此时 p=%d\n", pre, post, p);
    /* 注意：不能写成 printf("...", p--, p)——同一个变量在一个表达式里
     * 既被修改又被访问，属于未定义行为，编译器会警告 -Wunsequenced。
     * 正确做法：先取值存起来，再看 p 的值。 */
    int old_p = p--;
    printf("    p-- 表达式值是 %d，之后 p=%d\n", old_p, p);

    /* ---------- 13. 复合赋值 ---------- */
    int q = 7;
    q += 3;  printf("13. q+=3  → %d\n", q);
    q -= 2;  printf("    q-=2  → %d\n", q);
    q *= 4;  printf("    q*=4  → %d\n", q);
    q /= 5;  printf("    q/=5  → %d（整数除法，不是 6.4）\n", q);
    q %= 4;  printf("    q%%=4  → %d\n", q);

    /* ---------- 14. 除以零 ---------- */
    /* 整数除零这里不写：1/0 是未定义行为，程序会直接崩溃（SIGFPE） */
    double zero = 0.0;
    printf("14. 1.0/0.0 = %f（浮点除零得到 inf，不崩溃）\n", 1.0 / zero);
    printf("    整数除零不演示：1/0 会直接崩溃，务必先判断除数是否为 0\n");

    /* ---------- 15. 小结 ---------- */
    printf("15. 小结：\n");
    printf("    int/int 结果还是 int，小数部分直接丢\n");
    printf("    要小数：先把某个操作数转成 double，注意括号位置\n");
    printf("    %% 只能用于整数，余数符号跟被除数\n");
    printf("    浮点是近似值，0.1+0.2 != 0.3，比较要用误差范围\n");
    printf("    金额用整数分，大数用 long long，除法先判零\n");

    return 0;
}

