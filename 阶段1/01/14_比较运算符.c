/*
 * 14_比较运算符.c —— 阶段1 / 第 01 课 / 第 14 个文件：比较运算符
 *
 * 编译：gcc 14_比较运算符.c -o compare_demo
 * 运行：./compare_demo
 *
 * ====================== 一、六个比较（关系）运算符 ======================
 *      ==   等于        （两个等号！一个等号是赋值）
 *      !=   不等于
 *      >    大于
 *      <    小于
 *      >=   大于等于
 *      <=   小于等于
 *
 * ★ 核心规则：比较的结果是 **int** 类型的 0 或 1，不是专门的布尔类型。
 *      成立 → 1（真）
 *      不成立 → 0（假）
 *   例如：
 *      5 < 8   →  1
 *      5 > 8   →  0
 *      5 == 5  →  1
 *      5 != 5  →  0
 * 所以可以直接打印：printf("%d", 5 < 8);   输出 1
 * 也可以直接参与算术：int n = (a > b) + (c > d);  数一数几个条件成立。
 * （想用 true/false 的写法，要 #include <stdbool.h>，详见 08 篇）
 *
 * ====================== 二、优先级与结合性 ======================
 * 从高到低（只列相关部分）：
 *      算术运算   + - * / %      ← 先算
 *      关系运算   < <= > >=
 *      相等运算   == !=
 *      逻辑与     &&
 *      逻辑或     ||
 *      赋值       =
 *
 * 两个必须记住的结论：
 *   1) 算术先于比较：a + 1 > b  等价于  (a + 1) > b
 *   2) 比较先于赋值：a = b > c  等价于  a = (b > c)  ← 把 0/1 赋给 a
 * 第三点最坑：比较运算符是"从左往右"结合的，但它**不能连写**：
 *      a < b < c    等价于   (a < b) < c
 *    (a < b) 得到 0 或 1，再拿它和 c 比较，逻辑完全错了！
 *      想表达"b 在 a 和 c 之间"，必须写：a < b && b < c
 *
 * ====================== 三、== 和 = 的区别（头号事故） ======================
 *      a = 1      赋值：把 1 放进 a，整个表达式的值是 1（恒为真）
 *      a == 1     比较：判断 a 是否等于 1，结果是 0 或 1
 * 经典错误：
 *      if (a = 0) { ... }      // ✗ 把 0 赋给 a，条件恒为假，代码永远不执行
 *      if (a == 0) { ... }     // ✓ 这才是"判断 a 是否为 0"
 * 现代编译器会给出警告（-Wparentheses），但**不一定是错误**，程序照样能编译运行。
 * 防御技巧：把常量写在左边
 *      if (0 == a)             // 万一漏写等号，0 = a 无法编译，立刻暴露
 *
 * ====================== 四、比较的常见用途 ======================
 *   1) 条件判断：      if (score >= 60) 及格
 *   2) 循环条件：      while (i < n)
 *   3) 计数：          count += (x > 0);
 *   4) 找最值：        if (x > max) max = x;
 *   5) 排序比较函数：  return (a > b) - (a < b);   // 返回 1/0/-1
 *   6) 提前返回：      if (p == NULL) return;
 *
 * ====================== 五、整数比较与浮点比较 ======================
 * ★ 5.1 整数和浮点比较时，整数会先转成浮点（详见 09 篇）
 *      2 == 2.0    →  1（真）
 *      1 == 1.0000000000000002  →  0（后者不是精确的 1）
 *
 * ★ 5.2 整数除法会先算完，再比较
 *      1 / 2 == 0.5    →  先算 1/2 得 0，再比较 0 == 0.5 → 假
 *      1.0 / 2 == 0.5  →  真
 *
 * ★ 5.3 浮点数几乎不能用 ==
 *      0.1 + 0.2 == 0.3    →  假（详见 13 篇）
 * 原因：浮点是近似值，两个"本该相等"的计算过程可能得到不同的末位。
 * 正确做法：判断差值小于误差范围
 *      #include <math.h>
 *      fabs(a - b) < 1e-9
 * 什么时候可以安全用 ==：
 *      和 0.0 比较（前提是值确实是直接赋的 0）
 *      比较两个完全相同的字面量或同一次计算的结果
 *      任何"数值参与过运算"的场合，都改用误差范围。
 *
 * ====================== 六、字符串比较：不能用 == ======================
 *      char a[] = "abc";
 *      char b[] = "abc";
 *      a == b          // ✗ 比较的是两个数组的地址，永远为假
 *      strcmp(a, b) == 0   // ✓ 比较内容，相等时返回 0
 * strcmp 的返回值：
 *      < 0   a 小于 b（按字典序）
 *      == 0  相等
 *      > 0   a 大于 b
 * 注意 strcmp 返回 0 表示"相等"，而 0 在 C 里又表示"假"，
 * 所以千万别写成 if (strcmp(a, b)) 来表示"相等"——那正好写反了。
 *
 * ====================== 七、有符号与无符号比较（暗坑） ======================
 *      int a = -1;
 *      unsigned int b = 1;
 *      a < b        // → 假！
 * 因为比较前 a 被隐式转成 unsigned，变成 4294967295，当然大于 1。
 * 这类 bug 编译器默认不一定警告，要开 -Wsign-compare 才容易发现。
 * 建议：不要混用 signed / unsigned 做比较；确需混用就显式转换并写注释。
 *
 * ====================== 八、字符比较就是比较编码 ======================
 *      'a' < 'b'      →  1（ASCII 97 < 98）
 *      'A' < 'a'      →  1（65 < 97）
 *      '0' < '9'      →  1（48 < 57）
 * 所以字符可以按字母顺序排序，但要注意大小写：
 *      'Z' < 'a' 是成立的（90 < 97），因为大写字母编码更小。
 * 判断字符类别不要硬编码编码值，用 <ctype.h>：
 *      isdigit(c)、isalpha(c)、isupper(c)、tolower(c)
 *
 * ====================== 九、指针比较 ======================
 *   可以比较：两个指针是否相等（== / !=），比如和 NULL 比较
 *      if (p != NULL)  ...
 *   也可以比较大小，但**只对指向同一个数组（或同一块内存）的指针有意义**：
 *      int arr[5];
 *      int *p = &arr[1], *q = &arr[3];
 *      p < q     →  1
 *   跨数组/跨对象比较大小是未定义行为，结果没有意义。
 *
 * ====================== 十、比较的返回值可以直接用 ======================
 *      int pass = (score >= 60);          // 0 或 1
 *      int count = 0;
 *      count += (a > 0);                  // 大于 0 就 +1，很常见的写法
 *      return (a > b) - (a < b);          // 三路比较，返回 1 / 0 / -1
 * 这也是为什么"关系运算返回 int"这件事很重要——它让比较结果能参与运算。
 *
 * ====================== 十一、常见坑 ======================
 *  1. if (a = 0)            把 == 写成 =，条件恒假还改了 a
 *  2. if (a < b < c)        连写比较，实际是 (a<b)<c，逻辑错
 *  3. 0.1 + 0.2 == 0.3      浮点不能用 ==
 *  4. 1 / 2 == 0.5          整数除法先算成 0
 *  5. str == "abc"          比较的是地址，要用 strcmp
 *  6. strcmp(a,b) 当条件    返回 0 表示"相等"，但 0 是"假"，语义反了
 *  7. -1 < 1u 为假          signed / unsigned 混用
 *  8. 浮点和整数比较时精度丢失   大整数转 double 后可能不再相等
 *  9. 跨数组比较指针大小      未定义行为
 * 10. 用 != 判空时忘了指针可能悬空   悬空指针 != NULL 但依然不能用
 *
 * ====================== 十二、实践建议 ======================
 *  - 比较一律用 ==，赋值用 =，看到 if (x = y) 先停下来想想
 *  - 常量放左边：if (0 == a)，漏等号会编译报错
 *  - 范围判断用 && 连接，不要连写 a < b < c
 *  - 浮点比较用误差范围，别用 ==
 *  - 字符串比较用 strcmp，判断相等写 strcmp(a, b) == 0
 *  - signed / unsigned 不要混比，开 -Wsign-compare
 *  - 指针只和 NULL 比、或在同一数组内比大小
 *  - 比较结果可以直接参与计算，这是 C 的惯用法，用好了代码很短
 */

#include <stdio.h>
#include <string.h>     /* strcmp */
#include <math.h>       /* fabs */
#include <stdbool.h>    /* bool / true / false */

int main(void)
{
    /* ---------- 1. 六个比较运算符 ---------- */
    int a = 5, b = 8;
    printf("1. a=%d b=%d\n", a, b);
    printf("   a <  b = %d\n", a < b);
    printf("   a <= b = %d\n", a <= b);
    printf("   a >  b = %d\n", a > b);
    printf("   a >= b = %d\n", a >= b);
    printf("   a == b = %d\n", a == b);
    printf("   a != b = %d\n", a != b);

    /* ---------- 2. 结果类型是 int，不是 bool ---------- */
    printf("2. sizeof(a < b) = %zu 字节（结果类型是 int）\n", sizeof(a < b));
    printf("   sizeof(bool) = %zu 字节，sizeof(true) = %zu 字节\n",
           sizeof(bool), sizeof(true));
    printf("   ↑ true 是 <stdbool.h> 里的宏（展开就是 1），类型是 int，所以是 4 字节；\n");
    printf("     bool 本身只有 1 字节。比较的结果是 int，不是 bool。\n");

    /* ---------- 3. 比较结果可以直接参与运算 ---------- */
    int x = 10, y = -3, z = 7;
    int positive_count = (x > 0) + (y > 0) + (z > 0);
    printf("3. 三个数里正数有 %d 个（比较结果相加）\n", positive_count);

    /* ---------- 4. == 与 = 的区别 ---------- */
    int flag = 1;
    if (flag == 1) {
        printf("4. flag == 1 成立（这是比较）\n");
    }
    /* if (flag = 0) { ... }
     * ↑ 错误示范：这是赋值，flag 被改成 0，条件恒为假，
     *   代码块永远不执行，编译器会给 -Wparentheses 警告。
     *   防御写法：if (0 == flag)，漏写等号就编译不过。 */
    printf("   正确写法 if (0 == flag) 可以防漏等号\n");

    /* ---------- 5. 整数与浮点比较：整数会先转成浮点 ---------- */
    printf("5. 2 == 2.0 ? %s\n", (2 == 2.0) ? "真" : "假");
    printf("   1 == 1.0000000000000002 ? %s（两者不相等）\n",
           (1 == 1.0000000000000002) ? "真" : "假");

    /* ---------- 6. 整数除法会先算完再比较 ---------- */
    printf("6. 1/2 == 0.5 ? %s（先算 1/2 得 0，再比较）\n",
           (1 / 2 == 0.5) ? "真" : "假");
    printf("   1.0/2 == 0.5 ? %s（浮点除法才对）\n",
           (1.0 / 2 == 0.5) ? "真" : "假");

    /* ---------- 7. 浮点不能用 == 比较 ---------- */
    double s = 0.1 + 0.2;
    printf("7. 0.1+0.2 == 0.3 ? %s\n", (s == 0.3) ? "真" : "假");
    double eps = 1e-9;
    printf("   fabs(s-0.3) < 1e-9 ? %s（正确做法）\n",
           (fabs(s - 0.3) < eps) ? "真" : "假");

    /* ---------- 8. 字符串比较必须用 strcmp ---------- */
    char str1[] = "abc";
    char str2[] = "abc";
    const char *p1 = str1;
    const char *p2 = str2;
    printf("8. p1 == p2 ? %s（比较的是地址，两个数组不同位置）\n",
           (p1 == p2) ? "真" : "假");
    printf("   strcmp(str1, str2) == 0 ? %s（比较内容，这才是对的）\n",
           (strcmp(str1, str2) == 0) ? "真" : "假");
    printf("   strcmp 的返回值：\"abc\" vs \"abd\" = %d（负数表示小于）\n",
           strcmp("abc", "abd"));

    /* ---------- 9. 有符号与无符号比较的陷阱 ---------- */
    int          neg = -1;
    unsigned int one = 1;
    /* 编译器会隐式把 neg 转成 unsigned，等价于 4294967295 < 1 */
    printf("9. -1 < 1u ? %s（-1 被转成 %u）\n",
           ((unsigned)neg < one) ? "真" : "假", (unsigned)neg);
    printf("   所以 signed 和 unsigned 不要直接比较\n");

    /* ---------- 10. 字符比较就是比较编码 ---------- */
    printf("10. 'a' < 'b' ? %s（97 < 98）\n", ('a' < 'b') ? "真" : "假");
    printf("    'A' < 'a' ? %s（65 < 97，大写字母编码更小）\n",
           ('A' < 'a') ? "真" : "假");
    printf("    'Z' < 'a' ? %s（所以按编码排序时大写全在小写前面）\n",
           ('Z' < 'a') ? "真" : "假");

    /* ---------- 11. 指针比较：只对同一数组有意义 ---------- */
    int arr[5] = {10, 20, 30, 40, 50};
    int *pa = &arr[1];
    int *pb = &arr[3];
    printf("11. &arr[1] < &arr[3] ? %s（同一个数组内比较有意义）\n",
           (pa < pb) ? "真" : "假");
    printf("    *pa=%d  *pb=%d\n", *pa, *pb);
    int *null_ptr = NULL;
    printf("    null_ptr == NULL ? %s（和 NULL 比较是最常见的用法）\n",
           (null_ptr == NULL) ? "真" : "假");

    /* ---------- 12. 连写比较是错的 ---------- */
    int n1 = 3, n2 = 5, n3 = 2;
    printf("12. 3 < 5 < 2 的结果 = %d（等价于 (3<5) < 2，即 1 < 2）\n",
           n1 < n2 < n3);
    printf("    ↑ 看起来像“3 小于 5 小于 2”，实际算的是 (3<5)<2，逻辑完全错\n");
    printf("    正确写法：3 < 5 && 5 < 2 → %s\n",
           (n1 < n2 && n2 < n3) ? "真" : "假");
    printf("    判断 n2 是否在 n1 和 n3 之间：%s\n",
           (n1 < n2 && n2 < n3) ? "在" : "不在");

    /* ---------- 13. 比较结果赋给 bool ---------- */
    int  score = 85;
    bool pass  = (score >= 60);     /* 结果是 int，存进 bool 变成 1 或 0 */
    printf("13. score=%d，pass=%d（比较结果可以直接存进 bool）\n",
           score, pass);

    /* ---------- 14. 三路比较：一个常用技巧 ---------- */
    /* (a > b) - (a < b) 的结果：a>b 得 1，a<b 得 -1，相等得 0 */
    int m = 10, n = 20;
    printf("14. 三路比较 (10 vs 20) = %d（1 大 / 0 相等 / -1 小）\n",
           (m > n) - (m < n));
    printf("    qsort 的比较函数就常写成这种形式\n");

    /* ---------- 15. 小结 ---------- */
    printf("15. 小结：\n");
    printf("    六个运算符：== != > < >= <=\n");
    printf("    结果是 int 的 0/1，可以直接参与运算\n");
    printf("    == 是比较，= 是赋值，常量写左边可防漏等号\n");
    printf("    不能连写 a < b < c，要用 && 连接\n");
    printf("    浮点用误差范围比较，字符串用 strcmp\n");
    printf("    signed/unsigned 不要混比\n");

    return 0;
}

