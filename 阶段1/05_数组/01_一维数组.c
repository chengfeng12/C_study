/*
 * 01_一维数组.c —— 阶段1 / 第 05 课 / 第 01 个文件：数组基本概念与一维数组
 *
 * 编译：gcc 01_一维数组.c -o bin/01_一维数组
 * 运行：./bin/01_一维数组
 *
 * 编译时会看到 1 条警告 -Wsizeof-array-argument（第 3 节故意留的）：
 * 它提醒"函数里的 sizeof(数组形参) 得到的是指针大小"，
 * 这正是数组退化成指针的直接证据，不是错误，程序能正常编译运行。
 *
 * 第 9 节讲越界，**不会真的越界**（那是未定义行为），只用注释和打印说明后果。
 * 打印地址时只输出"地址之间的差值"，不输出具体地址 —— 地址每次运行都可能不同，
 * 差值才是能对照的稳定事实。
 *
 * ====================== 一、数组是什么 ======================
 * 数组 = 一组**同类型**元素，在内存里**挨着**放，用**下标**区分彼此。
 *
 *      int score[5] = {90, 85, 77, 60, 95};
 *
 * 它解决的是"同类数据的批量管理"：
 *      10 个学生的成绩、一张图片的像素、一段文本的字符……
 *      没有数组就只能 int s1, s2, s3... 一个个起名字。
 *
 * 本文件只讲**一维数组**（一条直线上的元素）；
 * 二维数组（矩阵）是下一节的内容，本质是"数组的数组"。
 *
 * ====================== 二、数组的五个特点（本节核心） ======================
 *
 *  (1) 元素在内存中依次、紧密排列，是有序的
 *      下标 0、1、2 ... n-1 严格对应内存里前、后相邻的位置，中间没有空隙。
 *
 *  (2) 创建数组会开辟一整块**连续**空间，大小 = 长度 × 单个元素大小
 *      int a[5]   →  5 × 4 = 20 字节，一整块，不是 5 个分散的小块。
 *      所以 sizeof(a) 一次就能问出总字节数（第 3 节）。
 *
 *  (3) 通过下标可以直接算出元素位置，速度很快（O(1)，与元素个数无关）
 *      编译器做的事就是：地址 = 首地址 + 下标 × sizeof(元素类型)
 *      不需要从头一个个数过去，所以访问 a[0] 和 a[999] 一样快。
 *
 *  (4) 长度一旦确定就不能改
 *      `int a[5];` 就永远是 5 个位置，不能"扩容成 6 个"。
 *      想"动态变化"，只能用"预留足够容量 + 记录实际用了几个"的模式（第 7 节），
 *      或者干脆用 malloc 在堆上重新申请（后面章节再讲）。
 *
 *  (5) 数组名代表这块连续空间的**首地址**
 *      `a` 的值就是 &a[0]，用 %p 打印出来是同一个数。
 *      这一点解释了很多现象：为什么数组不能整体赋值、为什么传参会变成指针、
 *      为什么 sizeof 在函数里就不灵了（第 6 节、第 9 节）。
 *
 * ====================== 三、定义与初始化 ======================
 *
 *      int a[5];                          // 5 个位置，值不确定（垃圾值）
 *      int b[5] = {1, 2, 3, 4, 5};        // 全部给定
 *      int c[5] = {1, 2, 3};              // ★ 只给 3 个，剩下 2 个自动补 0
 *      int d[]  = {4, 5, 6};              // 长度由初始化列表推断 → 3
 *      int e[5] = {0};                    // ★ 常用技巧：全部清零
 *      int f[6] = {[0] = 1, [5] = 9};     // C99 指定初始化器，其余补 0
 *
 * 两条必须记住的规则：
 *
 *      规则 1：只要写了初始化列表，"没写到的元素"一律补 0；
 *              完全没写初始化列表（int a[5];），元素值是**不确定**的。
 *
 *      规则 2：方括号里是长度，不是最大下标。`int a[5]` 的合法下标是 0~4。
 *
 * 长度必须是**编译期常量**：
 *      int n = 5;  int a[n];      // C99 起合法，但这叫变长数组 VLA，见第 7 节
 *      #define N 5  int a[N];    // ✓ 推荐
 *      const int M = 5; int a[M]; // 在 C 里 const 变量不算常量表达式（C++ 才算）
 *
 * 初始化风格建议：
 *      - 数据少、已知 → 直接写初始化列表，最省事也最不容易漏
 *      - 数据多或来自计算 → 先 `= {0}` 清零，再逐个填
 *      - 千万别留"未初始化"的数组去参与计算，读到垃圾值是最难查的 bug
 *
 * ====================== 四、下标访问与遍历 ======================
 *      a[0]      第一个元素
 *      a[n - 1]  最后一个元素
 *      a[n]      ✗ 越界！编译器不检查，运行结果不可预测
 *
 * 遍历的标准写法（背下来）：
 *
 *      int n = (int)(sizeof(a) / sizeof(a[0]));
 *      for (int i = 0; i < n; i++)
 *          printf("%d ", a[i]);
 *
 * 为什么用 i < n 而不是 i <= n：长度 n 的数组，最后一个下标是 n-1。
 *
 * ====================== 五、内存布局 ======================
 *      int a[4] = {10, 20, 30, 40};
 *
 *      假设 a 的首地址是 0x1000（int 占 4 字节）：
 *
 *        地址   0x1000  0x1004  0x1008  0x100C
 *        元素   a[0]    a[1]    a[2]    a[3]
 *        值     10      20      30      40
 *               └────── 一整块连续的 16 字节 ──────┘
 *
 *      相邻元素地址差 = sizeof(int) = 4 字节；
 *      a[i] 的地址 = a 的地址 + i * 4。
 *
 *      这也解释了"下标访问快"：给个 i，算一次乘法加一次加法，直接就到，
 *      和数组有多长完全无关。（对比链表要一个个顺着找，那就慢多了）
 *
 * ====================== 六、数组名到底代表什么 ======================
 *      设 int a[4];
 *
 *      a            → 首元素地址，等价于 &a[0]，类型退化为 int *
 *      &a[0]        → 首元素地址，类型 int *
 *      &a           → 整个数组的地址，类型是 int (*)[4]
 *
 *      a 和 &a[0] 的**值**一样，但 &a 的含义不同：
 *
 *          a + 1      往后走 1 个元素   → 4 字节
 *          &a + 1     往后走 1 个数组   → 16 字节（sizeof(a)）
 *
 *      sizeof 是唯一"看穿"数组的运算符：
 *          sizeof(a)      = 16（整个数组）
 *          sizeof(a[0])   = 4（一个元素）
 *          sizeof(&a[0])  = 8（指针本身）
 *
 * 由此派生的三条限制（都是"数组名=首地址"的后果）：
 *      1) 不能整体赋值：b = a;        ✗
 *      2) 不能整体比较：a == b;       ✗ 比的是地址，不是内容
 *      3) 传参时退化为指针：函数里 sizeof 得到的是指针大小（8）
 *
 * 想复制数组只能用循环或 memcpy；想比较内容只能逐元素比或 memcmp。
 *
 * ====================== 七、长度一旦确定，就不能改 ======================
 *      int a[3];
 *      a[3] = 100;          // ✗ 不是"扩容"，是越界写到数组外面去了
 *
 * C 的静态数组没有"扩容"概念。需要"能变长"的容器时，有三种做法：
 *
 *  (1) 容量 + 计数（最常用、最省心）
 *          int buf[100];        // 预留足够容量
 *          int used = 0;        // 实际用了几个
 *          buf[used++] = 42;    // 追加
 *      长度概念由 used 承担，buf 永远只有 100 个位置。
 *
 *  (2) 变长数组 VLA（C99）
 *          int n; scanf("%d", &n);
 *          int v[n];            // 长度运行期决定
 *      注意：**n 一旦确定，v 的长度也就固定了**，仍然不能扩容；
 *            而且 VLA 不能初始化、不能是全局变量，大数组还有爆栈风险。
 *
 *  (3) 堆上动态分配（malloc / realloc）
 *          长度可以真的变，但要自己 free，后面章节专门讲。
 *
 * ====================== 八、数组的生命周期：什么时候被销毁 ======================
 * 数组不只占内存，还讲"活多久"—— 这叫**存储期**。按定义位置分三类，
 * 销毁规则完全不同：
 *
 *  (1) 局部（自动）数组：定义在函数或代码块里
 *          void f(void) { int a[5]; ... }
 *      离开作用域（走出花括号 / 函数返回）时**自动销毁**：空间被系统收回。
 *      ★ 不需要，也**不能**手动释放 —— 对不是 malloc 来的数组调 free 是未定义行为。
 *      ★ "销毁"≠"清零"：空间只是不再属于你，里面的旧内容可能还在，
 *        但再通过旧地址去读就是悬垂指针，未定义行为。
 *
 *  (2) 静态 / 全局数组：
 *          int g[10];                              // 全局
 *          void f(void) { static int s[10]; }      // 静态局部
 *      它们活到**程序结束**才被系统回收。
 *      静态局部数组只初始化一次，下次进函数沿用的是上次的值（和普通局部数组相反）。
 *
 *  (3) 堆数组：用 malloc 申请
 *          int *p = malloc(n * sizeof *p);
 *          ...
 *          free(p);          // ★ 只有这种数组需要手动"销毁"
 *      free 之后指针变悬垂（不能再访问、不能重复 free）。
 *      malloc / free 在后面的内存管理章节详讲，这里只要记住"谁申请谁释放"。
 *
 * 三句话总结：
 *
 *      ✓ 栈上的数组不用销毁，也没有 API 能删除它；
 *      ✓ memset(a, 0, sizeof a) 是**清空内容**，数组还在、还能继续用；
 *      ✓ 绝不返回局部数组的地址：
 *              int *bad(void) { int a[3] = {1,2,3}; return a; }   // ✗ 悬垂指针
 *        函数一返回 a 就销毁了。要把数组"带出去"，只能让调用方传缓冲区进来、
 *        用 static/全局数组，或者用 malloc（并约定由谁 free）。
 *
 * ====================== 九、常见坑 ======================
 *  1. 越界访问 a[n]          编译器不报错，运行可能正常、也可能崩，属于未定义行为
 *  2. 下标从 0 开始          最后一个元素是 a[n-1]，不是 a[n]
 *  3. 忘记初始化              读到垃圾值；想清零就写 = {0}
 *  4. 以为 `int a[5] = {1}` 是"只初始化第一个、其余垃圾"  → 其实其余补 0
 *  5. 数组不能整体赋值/比较   b = a、a == b 都不行
 *  6. 函数里 sizeof(arr) 不是数组大小   形参已退化成指针
 *  7. 用 int 接收 sizeof 的结果         size_t 是 64 位无符号，用 %zu 或先转 int
 *  8. 长度用变量却以为是常量            C99 VLA 合法，但长度定了仍不能改
 *  9. 字符串数组忘了留 '\0'              char s[5] = "hello"; 放不下，编译警告或截断
 * 10. 下标倒序用了无符号变量            for (unsigned i = n - 1; i >= 0; i--) 死循环
 * 11. 返回局部数组的地址                函数返回后数组已销毁，指针悬垂
 * 12. 对栈数组调用 free                 未定义行为，通常直接崩；只有 malloc 的才能 free
 *
 * ====================== 十、实践建议 ======================
 *  - 数组长度用宏或 sizeof 推导，别把 5、10 这类数字写死在多处
 *  - 遍历统一 `for (int i = 0; i < n; i++)`，n 用 sizeof 算好放变量里
 *  - 需要"变长"就用"容量 + 计数"，别指望数组自己长大
 *  - 下标访问前先想边界：0 ≤ i < n
 *  - 传数组给函数时，长度一起传：`void f(int *a, int n)`
 *  - 大量数据用 malloc；数组这种"编译期定长"的结构适合规模已知的场景
 *  - 别返回局部数组的地址；要把数组带出函数，就让调用方传缓冲区进来
 *  - 栈数组不用 free；malloc 的数组必须 free，且谁申请谁释放
 *  - 打开了 -Wall -Wextra，但越界它查不出来，必要时上 AddressSanitizer
 *    （gcc -fsanitize=address）
 */

#include <stdio.h>
#include <string.h>                       /* memset：用于演示"清空内容 ≠ 销毁" */

/* 传数组 = 传指针：这里的 a 已经不是数组，而是 int * */
static size_t size_in_function(int a[])
{
    return sizeof(a);                 /* 结果是指针大小，不是数组大小 */
}

/* static 局部数组：只初始化一次，之后的调用沿用上次的值 */
static int bump(void)
{
    static int s[3] = {0, 0, 0};      /* 生命周期到程序结束 */
    s[0]++;
    return s[0];
}

int main(void)
{
    /* ---------- 1. 四种初始化写法 ---------- */
    printf("1. 定义与初始化\n");
    int a[5] = {1, 2, 3, 4, 5};              /* 全部给定 */
    int b[5] = {1, 2, 3};                    /* 只给 3 个，其余补 0 */
    int c[]  = {4, 5, 6};                    /* 长度自动推断为 3 */
    int d[6] = {[0] = 1, [5] = 9};           /* C99 指定初始化器 */

    printf("   int a[5] = {1,2,3,4,5};  → ");
    for (int i = 0; i < 5; i++) printf("%d ", a[i]);
    printf("\n   int b[5] = {1,2,3};      → ");
    for (int i = 0; i < 5; i++) printf("%d ", b[i]);
    printf("（没写的补 0）\n");
    printf("   int c[]  = {4,5,6};      → ");
    for (int i = 0; i < 3; i++) printf("%d ", c[i]);
    printf("（长度自动算出 %zu）\n", sizeof(c) / sizeof(c[0]));
    printf("   int d[6] = {[0]=1,[5]=9};→ ");
    for (int i = 0; i < 6; i++) printf("%d ", d[i]);
    printf("\n");

    /* ---------- 2. 下标访问与遍历 ---------- */
    printf("2. 下标访问：a[0] 是第一个，a[n-1] 是最后一个\n");
    int s[5] = {90, 85, 77, 60, 95};
    int n = (int)(sizeof(s) / sizeof(s[0]));
    for (int i = 0; i < n; i++)
        printf("   s[%d] = %d\n", i, s[i]);
    printf("   sizeof(s)      = %zu 字节（整个数组）\n", sizeof(s));
    printf("   sizeof(s[0])   = %zu 字节（一个元素）\n", sizeof(s[0]));
    printf("   元素个数        = %d（%zu / %zu）\n",
           n, sizeof(s), sizeof(s[0]));

    /* ---------- 3. sizeof 只能在本作用域用 ---------- */
    printf("3. 数组传进函数后会退化成指针\n");
    printf("   本作用域 sizeof(s) = %zu 字节\n", sizeof(s));
    printf("   函数内   sizeof(s) = %zu 字节（指针大小！）\n", size_in_function(s));
    printf("   所以长度要在定义数组的地方算好，再当参数传进去\n");

    /* ---------- 4. 内存是连续的：用地址差值验证 ---------- */
    printf("4. 元素在内存里紧密排列\n");
    int m[4] = {10, 20, 30, 40};
    for (int i = 0; i < 3; i++)
        printf("   &m[%d] 到 &m[%d] 相差 %ld 字节\n", i, i + 1,
               (long)((char *)&m[i + 1] - (char *)&m[i]));
    printf("   相邻差恒等于 sizeof(int) = %zu，说明是连续的一整块\n", sizeof(int));
    printf("   m 整块占 %zu 字节 = 4 个元素 × %zu 字节\n", sizeof(m), sizeof(m[0]));

    /* ---------- 5. 数组名 = 首地址 ---------- */
    printf("5. 数组名代表首地址\n");
    printf("   a == &a[0] 吗？%s\n", (a == &a[0]) ? "相等" : "不相等");
    printf("   a  + 1 往后走 %ld 字节（1 个元素）\n",
           (long)((char *)(a + 1) - (char *)a));
    printf("   &a + 1 往后走 %ld 字节（1 整个数组）\n",
           (long)((char *)(&a + 1) - (char *)&a));
    printf("   值一样，但类型不同：a 是 int *，&a 是 int (*)[5]\n");
    printf("   sizeof(a) = %zu，sizeof(&a[0]) = %zu（指针大小）\n",
           sizeof(a), sizeof(&a[0]));

    /* ---------- 6. 清不清零：{0} 的意义 ---------- */
    printf("6. 未初始化与 {0} 的区别\n");
    int zeroed[5] = {0};                 /* 全部清零 */
    printf("   int zeroed[5] = {0};  → ");
    for (int i = 0; i < 5; i++) printf("%d ", zeroed[i]);
    printf("\n   如果写成 int dirty[5]; 不加初始化，元素是垃圾值（不可预测）\n");
    printf("   需要统计求和时，一定要先清零，否则和里会混进垃圾\n");
    int dirty[5];                            /* 只分配空间，不初始化 */
    printf("   比如 int dirty[5]; 确实占了 %zu 字节空间，但 5 个元素的值不确定，\n",
           sizeof(dirty));
    printf("   所以这里**故意不打印它们**——读未初始化的值属于未定义行为\n");

    /* ---------- 7. 长度不可改：容量 + 计数模式 ---------- */
    printf("7. 长度一旦确定不能改，用\"容量 + 计数\"管理\n");
    int buf[10];                         /* 容量 10，一个位置也不多 */
    int used = 0;                        /* 实际用了几个 */
    for (int i = 1; i <= 3; i++)
        buf[used++] = i * 10;            /* 追加三个元素 */
    printf("   容量 %zu，已用 %d：", sizeof(buf) / sizeof(buf[0]), used);
    for (int i = 0; i < used; i++) printf("%d ", buf[i]);
    printf("\n   想再加值继续 buf[used++] = x; 就够了，容量上限由 used < 10 保证\n");
    printf("   C 的静态数组没有扩容一说，a[10] 不会变成 11 个位置\n");

    /* ---------- 8. 生命周期：什么时候被销毁 ---------- */
    printf("8. 数组活多久：栈上自动销毁，静态的活到程序结束\n");
    {
        int local[3] = {1, 2, 3};         /* 生命周期只在这个花括号里 */
        printf("   块内 local[0] = %d，数组有效\n", local[0]);
    }
    printf("   出了这个花括号，local 已被销毁：空间被系统回收，不能再访问\n");
    printf("   栈上的数组不需要也不能 free；对非 malloc 的数组调 free 是未定义行为\n");

    int b1 = bump();                      /* static 数组只初始化一次 */
    int b2 = bump();
    printf("   static 数组只初始化一次：第一次返回 %d，第二次返回 %d\n", b1, b2);

    int cleared[3] = {5, 6, 7};
    memset(cleared, 0, sizeof(cleared));  /* 只是把内容清 0 */
    printf("   memset 之后数组还在，cleared = ");
    for (int i = 0; i < 3; i++) printf("%d ", cleared[i]);
    printf("（清空内容 ≠ 销毁空间）\n");

    /* ---------- 9. 越界：只讲不跑 ---------- */
    printf("9. 边界：合法下标是 0 ~ %d\n", n - 1);
    printf("   s[%d] = %d 是最后一个元素\n", n - 1, s[n - 1]);
    printf("   s[%d] 就是越界：编译器不报错，运行可能不崩，但属于未定义行为\n", n);
    printf("   判断是否越界的正确姿势：i >= 0 && i < n\n");

    /* ---------- 10. 常见操作：求和、平均、最值、逆序 ---------- */
    printf("10. 四种最常用的数组操作\n");
    int v[6] = {3, 9, 1, 7, 5, 2};
    int vn = (int)(sizeof(v) / sizeof(v[0]));
    int sum = 0, max = v[0];
    for (int i = 0; i < vn; i++) {
        sum += v[i];
        if (v[i] > max) max = v[i];
    }
    printf("   数据：");
    for (int i = 0; i < vn; i++) printf("%d ", v[i]);
    printf("\n   求和 = %d，平均 = %.2f，最大值 = %d\n", sum, (double)sum / vn, max);

    for (int i = 0, j = vn - 1; i < j; i++, j--) {   /* 首尾交换 → 逆序 */
        int t = v[i];
        v[i] = v[j];
        v[j] = t;
    }
    printf("   原地逆序：");
    for (int i = 0; i < vn; i++) printf("%d ", v[i]);
    printf("\n   只用了原数组，没申请第二个数组\n");

    /* ---------- 11. 数组不能整体赋值、不能整体比较 ---------- */
    printf("11. 数组名是地址，所以不能整体赋值/比较\n");
    int p1[3] = {1, 2, 3};
    int p2[3] = {1, 2, 3};
    printf("    两个数组内容一样，但 (void *)p1 == (void *)p2 为%s\n",
           ((void *)p1 == (void *)p2) ? "真" : "假");
    printf("    因为比较的是首地址，不是元素内容\n");
    printf("    要复制用循环或 memcpy，要比较内容用循环或 memcmp\n");

    /* ---------- 12. 小结 ---------- */
    printf("12. 小结：\n");
    printf("    数组 = 同类型元素 + 连续内存 + 下标访问\n");
    printf("    大小 = 长度 × sizeof(元素)，sizeof(a) 能一次问出来\n");
    printf("    下标 0 ~ n-1，越界不报错所以必须自己守边界\n");
    printf("    长度编译期确定，之后不能改；要变长用\"容量 + 计数\"或 malloc\n");
    printf("    数组名就是首地址：不能整体赋值/比较，传参会退化成指针\n");
    printf("    栈数组离开作用域自动销毁（不用 free）；malloc 的数组必须自己 free\n");

    return 0;
}

