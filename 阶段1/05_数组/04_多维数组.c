/*
 * 04_多维数组.c —— 阶段1 / 第 05 课 / 第 04 个文件：多维数组（二维为主）
 *
 * 编译：gcc 04_多维数组.c -o bin/04_多维数组
 * 运行：./bin/04_多维数组
 *
 * 编译时会出现 2 条 -Wmissing-braces（第 1 节故意留的）：
 * 它建议给内层也加花括号，但"按行主序平铺初始化"是合法写法，
 * 正是第 1 节要演示的等价形式，不是错误。
 * 打印地址时只输出"地址差值"，不输出具体地址（地址每次运行都不同，差值才稳定）。
 *
 * ====================== 一、多维数组就是"数组的数组" ======================
 *
 *      int a[2][3];
 *
 * 不要读成"2 行 3 列的表格"，而要读成：
 *
 *      a 是一个长度 2 的数组，它的每个元素是 int[3]
 *      a[0] 是 int[3]，a[1] 是 int[3]
 *      a[0][0] 才是 int
 *
 * 类型拆解：
 *      a        int [2][3]    整个二维数组
 *      a[i]     int [3]       一行（一个一维数组）
 *      a[i][j]  int           一个元素
 *
 * 三维同理：int t[2][3][4] 是"长度 2 的数组，元素是 int[3][4]"。
 * 理论上可以任意多维，但超过三维基本就该换数据结构了。
 *
 * ====================== 二、内存里是"一条线"，不是"一张表" ======================
 * 二维只是**写法**上的二维，内存永远是一维连续的。C 用**行主序**（row-major）：
 * 先放完第 0 行，再放第 1 行，一行内部从左到右。
 *
 *      int a[2][3] = {{1,2,3},{4,5,6}};
 *
 *      内存：  1     2     3     4     5     6
 *      下标： a[0][0] a[0][1] a[0][2] a[1][0] a[1][1] a[1][2]
 *      地址： a+0   a+4   a+8   a+12  a+16  a+20  （int 4 字节）
 *
 * 元素地址公式（这就是"下标访问快"的全部秘密）：
 *
 *      &a[i][j] = a + (i * 列数 + j) * sizeof(int)
 *
 *      ★ 这只是编译器内部算地址的方式；写代码时永远写 a[i][j]，
 *        不要自己乘列数拼指针（那既难读，也会越过 a[i] 的边界）。
 *
 * 所以**列数**是编译器算地址时必须知道的信息 —— 这解释了第六节的传参规则：
 * 为什么 `int a[][3]` 可以，`int a[][]` 不行。
 *
 * ====================== 三、定义与初始化 ======================
 *
 *      int a[2][3] = {{1,2,3}, {4,5,6}};    // 最清晰：按行分组
 *      int b[2][3] = {1, 2, 3, 4, 5, 6};    // 等价：按行主序依次填
 *      int c[2][3] = {{1}, {4, 5}};         // 部分初始化：其余补 0
 *      int d[][3]  = {{1,2,3}, {4,5,6}};    // 省略第一维，行数由初始化推断
 *      int e[2][3] = {0};                   // 全部清零（常用）
 *
 * ★ 两条规则：
 *
 *      1) **只能省略第一维**。
 *         `int d[][3]` ✓（编译器数一下有几组就知道行数）
 *         `int d[2][]` ✗（不知道列数 → 算不出每行跨多少字节）
 *
 *      2) 只要写了初始化列表，没写到的元素一律补 0（和 01 篇一维的规则相同）。
 *
 * ====================== 四、访问与遍历 ======================
 *      for (int i = 0; i < rows; i++)          // 行
 *          for (int j = 0; j < cols; j++)      // 列
 *              printf("%d ", a[i][j]);
 *
 * ★ 遍历顺序要**和内存顺序一致**（先 i 后 j、内层走 j）：
 *   这样每次访问的都是内存里相邻的下一个元素，CPU 缓存命中率高。
 *   反过来写（外层 j、内层 i）结果一样，但跳着访问内存，大数组会明显变慢。
 *
 * ====================== 五、sizeof 与行列数 ======================
 *      int a[2][3];
 *
 *      sizeof(a)         = 24   整个数组 = 6 × 4
 *      sizeof(a[0])      = 12   一行 = 3 × 4
 *      sizeof(a[0][0])   = 4    一个元素
 *
 *     行数 = sizeof(a) / sizeof(a[0])              = 2
 *     列数 = sizeof(a[0]) / sizeof(a[0][0])        = 3
 *
 * 注意：这套算法**只能在本作用域**用。传进函数后 a 退化成指针，
 * sizeof 得到 8，行列数都必须由调用方传参（第六节）。
 *
 * ====================== 六、数组名的类型：a、a[i] 差在哪 ======================
 *      int a[2][3];
 *
 *      表达式    类型             +1 走多少字节
 *      --------  --------------  --------------
 *      a         int (*)[3]       12（跨一行）
 *      a[0]      int *             4（跨一个元素）
 *      &a        int (*)[2][3]    24（跨整个数组）
 *      a[0][0]   int               —（值本身）
 *
 * 记忆法：
 *      a    是"指向一行"的指针，所以 +1 跳一整行
 *      a[i] 这一行退化成"指向一个元素"的指针，所以 +1 跳一个元素
 *
 * 这也说明 a 和 a[0] 的值相同（都是首地址），但类型不同、步长不同。
 *
 * ====================== 七、二维数组当函数参数（最容易错的地方） ======================
 * 正确的是这样：
 *
 *      void f(int a[][3], int rows)      // ✓ 列数必须写死
 *      void f(int (*a)[3], int rows)     // ✓ 完全等价的另一种写法
 *
 * 错误写法，以及为什么错：
 *
 *      void f(int a[][], int rows)       // ✗ 编译不过：不知道列数，算不出地址
 *      void f(int **a, int rows)         // ✗ 能编过，但**完全不是同一个东西**
 *
 * `int **` 是"指针的指针"（比如动态分配的指针数组），
 * 而二维数组是一整块连续内存，没有"行指针数组"这一层。
 * 用 `int **` 去接二维数组，运行时会读到错误地址（甚至崩）。
 *
 * C99 还可以用变长数组参数，列数也变成变量：
 *
 *      void f(int rows, int cols, int a[rows][cols])   // rows/cols 必须写在前面
 *
 * ====================== 八、三维及更高维 ======================
 *      int t[2][3][4];        // 2 个 3×4 的块
 *
 *      sizeof(t)          = 96   （2 × 3 × 4 × 4 字节）
 *      sizeof(t[0])       = 48   （一个 3×4 的块）
 *      sizeof(t[0][0])    = 16   （一行 4 个 int）
 *      sizeof(t[0][0][0]) = 4
 *
 * 内存依然是连续的一条线，遍历也是最内层变化最快。
 * 工程上的经验：**超过三维就别用多维数组了**，
 * 改用结构体、或者一维数组 + 自己算下标，可读性和可维护性都更好。
 *
 * ====================== 九、常见坑 ======================
 *  1. 行列写反                a[i][j] 与 a[j][i] 是不同元素，转置/乘法里最常见
 *  2. 省略了第二维            int a[2][] ✗；只有第一维可以省
 *  3. 以为是"指针的指针"       int ** 接二维数组 → 运行期读到错误地址
 *  4. 传参列数写错            f(a, rows) 里写成 [2] 而实际是 [3]，地址全乱
 *  5. 遍历顺序与内存相反      结果对但缓存不友好，大数组慢好几倍
 *  6. 越界只查了行没查列      i < rows 对了，j < cols 忘了
 *  7. 用 sizeof(指针) 算大小   函数里 sizeof(a) 是 8
 *  8. 混淆 char[3][10] 与 char *[3]
 *       char names[3][10]  连续 30 字节，每行都能改
 *       char *names[3]     是 3 个指针，指向别处的字面量（只读）
 *  9. 动态二维（malloc 的指针数组）不是连续内存，不能整块 memcpy
 * 10. 栈上开巨大二维数组       int a[1000][1000] 约 4MB，可能直接爆栈
 *
 * ====================== 十、实践建议 ======================
 *  - 行列数用宏或 sizeof 推导，别在多处手写 3、4 这种魔法数
 *  - 遍历统一 `for (i) for (j)`，内层走 j（与内存顺序一致）
 *  - 传参写 `int a[][COLS]`，并且把 rows 一起传
 *  - 矩阵类需求优先考虑"一维数组 + i*cols+j"，接口更简单
 *  - 二维字符数组存多个字符串时，第二维要给足最大长度（含 '\0'）
 *  - 需要"行数运行期可变"时，要么用 VLA（小心爆栈），要么用动态分配
 */

#include <stdio.h>

/* 二维数组作参数：列数必须写死，行数由调用方传 */
static int sum2d(int a[][3], int rows)
{
    int s = 0;
    for (int i = 0; i < rows; i++)
        for (int j = 0; j < 3; j++)
            s += a[i][j];
    return s;
}

int main(void)
{
    /* ---------- 1. 四种初始化写法 ---------- */
    printf("1. 定义与初始化\n");
    int a[2][3] = {{1, 2, 3}, {4, 5, 6}};      /* 按行分组，最清晰 */
    int b[2][3] = {1, 2, 3, 4, 5, 6};          /* 等价：按行主序依次填 */
    int c[2][3] = {{1}, {4, 5}};               /* 部分初始化，其余补 0 */
    int d[][3]  = {{1, 2, 3}, {4, 5, 6}};      /* 省略第一维，行数自动推断 */

    printf("   a = {{1,2,3},{4,5,6}}\n      ");
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 3; j++) printf("%d ", a[i][j]);
    printf("\n   b = {1,2,3,4,5,6}（等价写法）\n      ");
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 3; j++) printf("%d ", b[i][j]);
    printf("\n   c = {{1},{4,5}}（没写的补 0）\n      ");
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 3; j++) printf("%d ", c[i][j]);
    printf("\n   d[][3] 省略第一维，行数推断为 %zu\n",
           sizeof(d) / sizeof(d[0]));

    /* ---------- 2. 按矩阵形状打印 ---------- */
    printf("2. 双重循环按矩阵打印\n");
    for (int i = 0; i < 2; i++) {
        printf("   ");
        for (int j = 0; j < 3; j++)
            printf("%2d ", a[i][j]);
        printf("\n");
    }
    printf("   外层管行、内层管列；内层走完一整行，才轮到下一行\n");

    /* ---------- 3. 内存连续（只打印差值） ---------- */
    printf("3. 内存里是连续的一条线\n");
    printf("   &a[0][0] 到 &a[0][1] 相差 %ld 字节\n",
           (long)((char *)&a[0][1] - (char *)&a[0][0]));
    printf("   &a[0][2] 到 &a[1][0] 相差 %ld 字节（跨行也是紧挨着）\n",
           (long)((char *)&a[1][0] - (char *)&a[0][2]));
    printf("   整个 a 占 %zu 字节 = 2 行 × 3 列 × %zu 字节\n",
           sizeof(a), sizeof(a[0][0]));

    /* ---------- 4. 行主序：内存连续，但取元素仍靠下标 ---------- */
    printf("4. 行主序：内存连续不代表要自己算下标\n");
    int *row1 = a[1];                     /* 取第 1 行：a[1] 退化成 int *，完全合法 */
    printf("   int *row1 = a[1];  row1[2] = %d（就是 a[1][2]）\n", row1[2]);
    int (*r)[3] = a;                      /* 行指针：一步跨一整行 */
    printf("   int (*r)[3] = a;   r[1][2]  = %d（同样是 a[1][2]）\n", r[1][2]);
    printf("   取元素就用这两种：要某一行用 a[i]，要按行移动用行指针\n");
    printf("   ✗ 别写成 *(flat + i * 3 + j)：要自己乘列数，而且算出了 a[0] 的边界\n");

    /* ---------- 5. sizeof 求行列数 ---------- */
    printf("5. 用 sizeof 求行列数\n");
    int rows = (int)(sizeof(a) / sizeof(a[0]));
    int cols = (int)(sizeof(a[0]) / sizeof(a[0][0]));
    printf("   sizeof(a)=%zu，sizeof(a[0])=%zu，sizeof(a[0][0])=%zu\n",
           sizeof(a), sizeof(a[0]), sizeof(a[0][0]));
    printf("   行数 = %d，列数 = %d（只能在定义它的作用域里这么算）\n", rows, cols);

    /* ---------- 6. 数组名的类型与步长 ---------- */
    printf("6. a、a[0]、&a 的区别：值一样，步长不同\n");
    printf("   a  + 1 走 %ld 字节（跨一整行）\n",
           (long)((char *)(a + 1) - (char *)a));
    printf("   a[0]+1 走 %ld 字节（跨一个元素）\n",
           (long)((char *)(a[0] + 1) - (char *)a[0]));
    printf("   &a + 1 走 %ld 字节（跨整个数组）\n",
           (long)((char *)(&a + 1) - (char *)&a));
    printf("   类型：a 是 int (*)[3]，a[0] 是 int *，&a 是 int (*)[2][3]\n");

    /* ---------- 7. 二维数组作函数参数 ---------- */
    printf("7. 传参：列数必须写死，行数单独传\n");
    printf("   sum2d(a, 2) = %d（1+2+3+4+5+6）\n", sum2d(a, 2));
    printf("   正确原型：int f(int a[][3], int rows)\n");
    printf("   ✗ int a[][] 编译不过；✗ int **a 完全不是同一个东西\n");

    /* ---------- 8. 经典应用：转置与矩阵乘法 ---------- */
    printf("8. 应用：转置与矩阵乘法\n");
    int m[2][3] = {{1, 2, 3}, {4, 5, 6}};
    int t[3][2];
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 3; j++)
            t[j][i] = m[i][j];                /* ★ 行列互换 */
    printf("   原矩阵 2×3：");
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 3; j++) printf("%d ", m[i][j]);
    printf("\n   转置后 3×2：");
    for (int i = 0; i < 3; i++)
        for (int j = 0; j < 2; j++) printf("%d ", t[i][j]);
    printf("\n");

    int A[2][2] = {{1, 2}, {3, 4}};
    int B[2][2] = {{5, 6}, {7, 8}};
    int C[2][2] = {{0, 0}, {0, 0}};
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 2; j++)
            for (int k = 0; k < 2; k++)
                C[i][j] += A[i][k] * B[k][j];  /* 三重循环：行 × 列 × 累加 */
    printf("   A×B = ");
    for (int i = 0; i < 2; i++)
        for (int j = 0; j < 2; j++) printf("%d ", C[i][j]);
    printf("\n   C[i][j] 是 A 的第 i 行与 B 的第 j 列“点乘”的结果\n");

    /* ---------- 9. 二维字符数组：存多个字符串 ---------- */
    printf("9. 二维 char 数组可以存多个字符串\n");
    char names[3][8] = {"Tom", "Jerry", "Spike"};
    for (int i = 0; i < 3; i++)
        printf("   names[%d] = \"%s\"（该行占 %zu 字节）\n",
               i, names[i], sizeof(names[i]));
    printf("   整个 names 占 %zu 字节 = 3 行 × 8 字节，内存连续\n", sizeof(names));
    printf("   对比 char *names[3]：那是指针数组，指向只读字面量，不能改内容\n");

    /* ---------- 10. 三维数组 ---------- */
    printf("10. 三维只是“数组的数组的数组”\n");
    int cube[2][3][4] = {{{0}}};
    printf("    sizeof(cube)          = %zu（2×3×4 个 int）\n", sizeof(cube));
    printf("    sizeof(cube[0])       = %zu（一个 3×4 的块）\n", sizeof(cube[0]));
    printf("    sizeof(cube[0][0])    = %zu（一行 4 个 int）\n", sizeof(cube[0][0]));
    printf("    sizeof(cube[0][0][0]) = %zu（一个元素）\n", sizeof(cube[0][0][0]));
    printf("    遍历依然是最内层变化最快：k 在最里层\n");

    /* ---------- 11. 小结 ---------- */
    printf("11. 小结：\n");
    printf("    多维数组 = 数组的数组；a[2][3] 是 2 个 int[3]\n");
    printf("    内存仍是连续一条线，行主序，&a[i][j] = a + (i*列数 + j)*sizeof(元素)\n");
    printf("    只能省略第一维；初始化没写到的元素补 0\n");
    printf("    a 是 int (*)[3]（跨行），a[i] 是 int *（跨元素）\n");
    printf("    传参写 int a[][3] 并另传行数；int ** 不是二维数组\n");

    return 0;
}

