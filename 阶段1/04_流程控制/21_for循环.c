/*
 * 21_for循环.c —— 阶段1 / 第 04 课 / 第 21 个文件：for 循环
 *
 * 编译：gcc 21_for循环.c -o bin/21_for循环
 * 运行：./bin/21_for循环
 *
 * 本文件能干净编译（-Wall -Wextra 零警告）。
 * ★ 注意第 13 节的"分号坑"编译器**不会**提醒你，
 *   因为 for (...) ; 在语法上完全合法，只是循环体变成了空语句 —— 这正是它危险的原因。
 *
 * ====================== 一、为什么需要循环 ======================
 * 前面的程序都是"顺序 + 分支"：走一遍就结束。可现实里大量任务是重复的：
 *
 *      把 100 个学生的成绩加起来        → 同一个动作做 100 次
 *      打印 9 行乘法表                  → 9 次 × 每行 9 列
 *      在一个数组里找某个值              → 逐个比对，找到为止
 *
 * 手写 100 遍 printf 显然不现实，循环就是让计算机"把同一段代码重复执行"。
 * C 的三种循环：
 *      for       —— 次数明确时首选（本文件）
 *      while     —— 次数不定、只看条件
 *      do-while  —— 至少执行一次
 *
 * ====================== 二、for 的语法与执行顺序 ======================
 *
 *      for (初始化; 条件; 更新) {
 *          循环体;
 *      }
 *           ↑        ↑      ↑
 *         只做一次   每轮先判    每轮最后做
 *
 * 执行顺序（★ 背下来，所有 for 的坑都源于这里）：
 *
 *      1) 初始化           —— 整个循环只执行 1 次
 *      2) 判断条件         —— 为真进 3)，为假直接结束循环
 *      3) 执行循环体
 *      4) 执行更新（i++ 等）
 *      5) 回到 2) 再判断
 *
 *      初始化 → 条件? → [体 → 更新 → 条件?] → [体 → 更新 → 条件?] → ...
 *
 * 三个部分都可以为空，但两个分号不能省：
 *      for (;;)              // 死循环，一般配 break 用
 *      for (; i < n; i++)    // 初始化已在外边做过
 *
 * ====================== 三、五种最常见写法 ======================
 *
 *      // 1) 0 到 n-1：数组、字符串遍历的标准写法（最常用）
 *      for (int i = 0; i < n; i++)
 *
 *      // 2) 1 到 n：计数、"第几个"这类语义
 *      for (int i = 1; i <= n; i++)
 *
 *      // 3) 倒序
 *      for (int i = n - 1; i >= 0; i--)
 *
 *      // 4) 步长不为 1
 *      for (int i = 0; i <= 100; i += 5)
 *      for (int i = 1; i <= 1024; i *= 2)
 *
 *      // 5) 多变量：一个增、一个减，往中间靠
 *      for (int i = 0, j = n - 1; i < j; i++, j--)
 *
 * 记忆点：
 *      用 < 还是 <=，取决于你想不想包含终点；
 *      从 0 开始数就用 i < n（代码界主流），从 1 开始数就用 i <= n。
 *
 * ====================== 四、循环变量的作用域（C99） ======================
 * C99 起允许在 for 的初始化里声明变量，这个变量的作用域只在这个 for 里：
 *
 *      for (int i = 0; i < 3; i++) { ... }
 *      printf("%d", i);              // ✗ 编译报错：i 未声明
 *
 * 好处：不会污染外层命名，多个循环可以都叫 i。
 * 要在循环之后继续用这个值，就得把变量提到外面声明：
 *
 *      int i;
 *      for (i = 0; i < 3; i++) { ... }
 *      printf("循环结束时 i = %d", i);   // ✓ 此时 i 一定是 3
 *
 * 注意：循环正常结束后，i 的值是"第一次让条件为假的值"，
 *      用 break 提前退出时则停在退出那一刻的值。
 *      C89（老教材）不支持在 for 里声明，只能在函数开头先声明。
 *
 * ====================== 五、边界：off-by-one 是最高频的 bug ======================
 *      int a[5];                     // 合法下标 0~4
 *      for (int i = 0; i <= 5; i++)  // ✗ 多跑了 a[5]，越界！
 *      for (int i = 0; i <  5; i++)  // ✓ 正好 5 次
 *
 * 记住两条：
 *      长度是 n 的数组，下标范围是 0 ~ n-1；
 *      写 <= 之前先问一句"终点的下一个是谁"。
 *
 * ====================== 六、break 和 continue ======================
 *      break    —— 立刻跳出整个循环，后面的轮次全部不做了
 *      continue —— 只跳过本轮剩下的语句，直接去做"更新"，然后判条件
 *
 * ★ for 里的 continue 会照常执行 i++，所以不会死循环；
 *   换成 while 时若把 i++ 写在了 continue 后面，就会永远卡住。
 *
 * 常见用法：
 *      查找：找到就 break（不再浪费后续遍历）
 *      过滤：不满足条件的 continue（让主逻辑保持左侧无缩进）
 *
 * ====================== 七、嵌套循环 ======================
 * 外层跑 1 次，内层跑完一整轮：
 *
 *      for (int row = 1; row <= 3; row++) {       // 行
 *          for (int col = 1; col <= row; col++)   // 列
 *              ...
 *      }
 *
 * 总执行次数 = 各层次数相乘（如 3 层各 10 次 = 1000 次），
 * 所以嵌套层数越多越慢，能提前算好的东西别放进内层重复算。
 * break 只跳出**最内层**那个循环，想一次跳出多层需要标志位或 goto。
 *
 * ====================== 八、常见坑 ======================
 *  1. for 后面多加分号          for (...);  循环体变成空语句，下面那句只执行一次
 *  2. 忘写更新                  for (int i = 0; i < n; ) → 死循环
 *  3. 条件方向写反              i >= n 用 ++ → 一次都不执行
 *  4. 用浮点数控制次数          d += 0.1 有误差，可能多跑一轮
 *  5. 无符号变量倒序            unsigned i >= 0 恒真 → 死循环
 *  6. 边界多算一个              i <= n 访问 a[n]，越界
 *  7. 在循环体里改循环变量      for (…) { i = 0; } 死循环，别这么写
 *  8. 循环外用了 for 里的变量   C99 作用域限制，编译报错
 *  9. 内层重复算 strlen/长度    for (i = 0; i < strlen(s); i++) 每次都在扫字符串
 * 10. 内层循环用了和外层同名的计数器  → 互相覆盖，嵌套全乱
 *
 * ====================== 九、for / while / do-while 怎么选 ======================
 *      for       次数明确（遍历数组、跑 n 次）→ 首选
 *      while     次数不定，先判后用（读文件、等条件成立）
 *      do-while  至少执行一次（先做再判，如菜单、输入校验）
 *
 * 这三者可以互相改写，选最贴合语义的那个，代码就最好读。
 *
 * ====================== 十、实践建议 ======================
 *  - 遍历数组统一用 for (int i = 0; i < n; i++)
 *  - 循环变量就近声明（C99 起），循环外要用才提到外面
 *  - 循环体超过 20 行就抽成函数
 *  - 查找类循环记得 break，省时间也省逻辑
 *  - 不要在循环里重复计算长度/属性，提到循环前存好
 *  - 写循环先想三件事：从哪开始、到哪停、每次怎么变
 */

#include <stdio.h>

int main(void)
{
    /* ---------- 1. 最基本的 for ---------- */
    printf("1. 最基本的 for：把 0~4 打印出来\n   ");
    for (int i = 0; i < 5; i++)
        printf("%d ", i);
    printf("\n   循环体执行了 5 次（i = 0,1,2,3,4）；i 变成 5 时条件为假，退出\n");

    /* ---------- 2. 执行顺序：初始化只做一次 ---------- */
    printf("2. 查看每一轮的变化：初始化 → 判条件 → 体 → 更新\n");
    int sum = 0;
    for (int i = 1; i <= 5; i++) {
        sum += i;
        printf("   第 %d 轮：i=%d，sum 累加到 %d\n", i, i, sum);
    }
    printf("   循环结束，sum=%d（1+2+3+4+5）\n", sum);

    /* ---------- 3. 倒序、步长、倍增 ---------- */
    printf("3. 倒序与步长\n   倒序 5→1：");
    for (int i = 5; i >= 1; i--)
        printf("%d ", i);
    printf("\n   步长 2（0,2,4,6,8）：");
    for (int i = 0; i <= 8; i += 2)
        printf("%d ", i);
    printf("\n   每次乘 2（1,2,4,8,16）：");
    for (int i = 1; i <= 16; i *= 2)
        printf("%d ", i);
    printf("\n");

    /* ---------- 4. 一个 for 管多个变量 ---------- */
    printf("4. 一个 for 管两个变量：一个往前走，一个往后退\n");
    for (int i = 0, j = 6; i < j; i++, j--)
        printf("   i=%d, j=%d\n", i, j);
    printf("   初始化、更新都可以写多条，用逗号隔开\n");

    /* ---------- 5. 四种经典用途 ---------- */
    printf("5. 四种最常见的用途：累加、累乘、计数、求最值\n");
    int s = 0;
    for (int i = 1; i <= 100; i++)
        s += i;
    printf("   1+2+...+100 = %d\n", s);

    long long fact = 1;
    for (int i = 1; i <= 10; i++)
        fact *= i;
    printf("   10! = %lld\n", fact);

    int arr[8] = {3, -1, 7, 0, 15, 2, 9, 4};
    int n = (int)(sizeof(arr) / sizeof(arr[0]));
    int odd = 0, max = arr[0];
    for (int i = 0; i < n; i++) {
        if (arr[i] % 2 != 0)
            odd++;
        if (arr[i] > max)
            max = arr[i];
    }
    printf("   数组 %d 个元素：奇数 %d 个，最大值 %d\n", n, odd, max);

    /* ---------- 6. 嵌套循环：行 × 列 ---------- */
    printf("6. 嵌套循环：外层管行，内层管列\n");
    for (int row = 1; row <= 4; row++) {
        printf("   ");
        for (int col = 1; col <= row; col++)
            printf("*");
        printf("\n");
    }
    printf("   内层跑完一整轮，外层才走一步；总次数 1+2+3+4=10\n");

    printf("   九九乘法表前 4 行：\n");
    for (int i = 1; i <= 4; i++) {
        printf("   ");
        for (int j = 1; j <= i; j++)
            printf("%d*%d=%-2d ", j, i, i * j);
        printf("\n");
    }

    /* ---------- 7. break：找到就停 ---------- */
    printf("7. break：找到目标立刻结束整个循环\n");
    int nums[6] = {4, 8, 15, 16, 23, 42};
    int target = 16, found = -1;
    for (int i = 0; i < 6; i++) {
        printf("   检查 nums[%d] = %d\n", i, nums[i]);
        if (nums[i] == target) {
            found = i;
            break;
        }
    }
    printf("   找到 %d 在下标 %d，后面的 23、42 根本没检查\n", target, found);

    /* ---------- 8. continue：跳过本轮 ---------- */
    printf("8. continue：跳过本轮剩余语句，但更新 i++ 照常执行\n   1~10 里的奇数：");
    for (int i = 1; i <= 10; i++) {
        if (i % 2 == 0)
            continue;               /* 偶数，直接进入下一轮 */
        printf("%d ", i);
    }
    printf("\n   ★ for 的 continue 会跳到 i++，所以不会死循环；\n");
    printf("     while 里若把 i++ 写在 continue 之后，就会永远卡住\n");

    /* ---------- 9. 边界：i < n 还是 i <= n ---------- */
    printf("9. 边界：长度 5 的数组，合法下标是 0~4\n");
    int a2[5] = {10, 20, 30, 40, 50};
    int n2 = 5;
    for (int i = 0; i < n2; i++)
        printf("   a2[%d] = %d\n", i, a2[i]);
    printf("   写成 i <= n2 会访问 a2[5]，越界（未定义行为，这里不演示）\n");

    /* ---------- 10. 别用浮点数控制循环次数 ---------- */
    printf("10. 坑：用浮点数当循环变量，次数会多一轮\n");
    int cnt = 0;
    for (double d = 0.0; d < 1.0; d += 0.1)
        cnt++;
    printf("     for (double d = 0; d < 1.0; d += 0.1) 实际跑了 %d 次（直觉是 10）\n", cnt);
    printf("     0.1 在二进制里存不准，累加到第 11 次时仍小于 1.0\n");
    printf("     正确做法：用整数计步，再换算成小数 —— ");
    for (int i = 0; i < 10; i++)
        printf("%.1f ", i / 10.0);
    printf("\n");

    /* ---------- 11. 无符号变量倒序会死循环 ---------- */
    printf("11. 坑：无符号变量倒序，条件恒真（死循环）\n");
    printf("     错误写法（千万别运行）：for (unsigned i = 5; i >= 0; i--)\n");
    printf("     unsigned 永远 >= 0，i-- 到 0 之后会变成 4294967295 继续跑\n");
    printf("     安全写法用 i > 0，需要原值时在体内取 i-1：");
    for (unsigned i = 5; i > 0; i--)
        printf("%u ", i);
    printf("\n");

    /* ---------- 12. 循环变量的作用域 ---------- */
    printf("12. for (int i = ...) 声明的 i，出了循环就不存在了\n");
    for (int i = 0; i < 3; i++)
        printf("   循环内 i=%d\n", i);
    printf("   循环外再写 i 会编译报错（C99 起 i 属于 for 的块作用域）\n");

    int k = 0;
    for (k = 0; k < 3; k++) {
        /* 用外层声明的 k */
    }
    printf("   提到外面声明则可以复用：循环结束后 k=%d（第一次让条件为假的值）\n", k);

    /* ---------- 13. 坑：for 后面多写分号 ---------- */
    printf("13. 坑：for 后面多写一个分号，循环体是空语句\n");
    int hits = 0;
    for (int i = 0; i < 3; i++)
        ;                            /* ← 循环体就是这个分号 */
    {
        hits++;                      /* 这块和 for 没关系，只执行一次 */
    }
    printf("    for (...) ; { hits++; } → hits=%d（不是 3）\n", hits);
    printf("    正确写法：把花括号直接跟在 for 后面\n");

    /* ---------- 14. 小结 ---------- */
    printf("14. 小结：\n");
    printf("    for (初始化; 条件; 更新) 循环体;\n");
    printf("    初始化一次 → 判条件 → 体 → 更新 → 再判条件\n");
    printf("    次数明确用 for；遍历数组用 i = 0; i < n; i++\n");
    printf("    break 跳出整个循环，continue 只跳过本轮（for 里仍会 i++）\n");
    printf("    注意边界 0~n-1、别用浮点/无符号倒序、别在 for 后加分号\n");

    return 0;
}

