/*
 * 22_while循环.c —— 阶段1 / 第 04 课 / 第 22 个文件：while 循环（含 do-while）
 *
 * 编译：gcc 22_while循环.c -o bin/22_while循环
 * 运行：./bin/22_while循环
 *
 * 本文件能干净编译（-Wall -Wextra 零警告）。
 * 第 12 节专门讲了“continue 在 while 里会死循环”的坑，只用注释演示错误写法，
 * 不会真的跑起来（跑了就卡住了）。
 *
 * ====================== 一、while 是什么 ======================
 * for 适合"次数明确"的场景。可很多任务的次数事先根本不知道：
 *
 *      用户输入对不对？错就一直问         → while (输入不合法)
 *      这个数一直除以 2，除到 1 为止        → while (n > 1)
 *      读文件，读到末尾为止                 → while (读到内容)
 *      等一个状态变成 ready                → while (!ready)
 *
 * 这类"只知道什么时候停，不知道跑几次"的重复，用 while 最自然。
 *
 * while 的判定是**先判后做**：条件不成立就一次都不做。
 *
 * ====================== 二、语法与执行流程 ======================
 *
 *      while (条件) {
 *          循环体;
 *      }
 *
 * 流程：
 *      1) 判断条件 → 为假，循环直接结束（可能一次都不执行）
 *      2) 为真，执行循环体
 *      3) 回到 1) 再判断
 *
 *      ┌──────────────┐
 *      │  判断条件     │──假──→ 结束
 *      └──────┬───────┘
 *            真
 *      ┌──────↓───────┐
 *      │   循环体      │
 *      └──────┬───────┘
 *             └──→ 回到判断
 *
 * ★ 三个必须自己保证的事（编译器不会管）：
 *      1) 循环变量在进 while 之前就初始化好
 *      2) 循环体里一定要让条件往"假"的方向走
 *      3) 条件里用的变量别被别处偷偷改掉
 *   少任何一样，都可能变成死循环。
 *
 * ====================== 三、while 和 for 的关系 ======================
 * for 可以理解成"把 while 的三件事写在一行的紧凑版"。两者完全可以互换：
 *
 *      for (int i = 0; i < 5; i++)          int i = 0;
 *          printf("%d ", i);                while (i < 5) {
 *                                               printf("%d ", i);
 *                                               i++;          ← 更新搬进体内
 *                                           }
 *
 * 选择标准：
 *      次数明确、有清晰的计数器       → for（更新写在头部，不容易漏）
 *      次数不定、由条件/输入驱动      → while
 *      无论如何都要先做一次           → do-while
 *
 * 经验：while 里凡是能写成 for 的，优先 for —— 因为 for 把"更新"放在头里，
 *      忘写更新这种 bug 一眼就能看出来。
 *
 * ====================== 四、do-while：先做后判 ======================
 *
 *      do {
 *          循环体;
 *      } while (条件);          ← ★ 这里必须写分号！漏了会编译报错
 *
 * 与 while 的唯一区别：**先执行一次，再判断**，所以至少执行 1 次。
 *
 *      int x = 100;
 *      while (x < 10) { ... }        // 0 次
 *      do { ... } while (x < 10);    // 1 次
 *
 * 典型用途：菜单（先显示再问）、输入校验（先收一次再判断合法性）。
 *
 * 注意：do-while 的循环体是一个块，里面声明的变量出了块就销毁；
 *      而 while/do-while 的条件里不能像 for 那样"声明 + 使用"同一个变量。
 *
 * ====================== 五、while 的四大典型场景 ======================
 *
 *  (1) 计数 / 累加（其实用 for 更好，属于入门练习）
 *          int i = 1, sum = 0;
 *          while (i <= 100) { sum += i; i++; }
 *
 *  (2) 条件驱动：跑到满足某个条件为止
 *          while (n > 1) { n /= 2; steps++; }        // 几次能除到 1
 *          while (n > 0)  { digit = n % 10; n /= 10; }  // 逐位拆数字
 *          while (b != 0) { t = b; b = a % b; a = t; }  // 辗转相除求 gcd
 *
 *  (3) 输入驱动：由"读到什么"决定停不停 —— while 的主场
 *          while (scanf("%d", &x) == 1) { ... }
 *          while ((c = getchar()) != EOF) { ... }
 *        ★ 必须用返回值和 EOF 判断，不能靠"用户输入 0 就停"这种约定，
 *          否则 0 到底是数据还是结束标记说不清。
 *
 *  (4) 无限循环 + break：菜单、服务器主循环、状态机
 *          while (1) {
 *              ...;
 *              if (要退出) break;
 *          }
 *
 * ====================== 六、★ continue 在 while 里的坑 ======================
 * for 的 continue 会跳去执行"更新"，所以安全；
 * while 的更新是**写在循环体里**的，continue 一跳过，更新就永远轮不到：
 *
 *      int i = 0;
 *      while (i < 10) {
 *          if (i % 2 == 0) continue;     // ✗ 死循环！i++ 永远执行不到
 *          printf("%d", i);
 *          i++;
 *      }
 *
 * 正确做法：把更新挪到 continue 之前，或者干脆改用 for。
 *
 *      while (i < 10) {
 *          i++;                          // ✓ 先更新，再判断跳过
 *          if (i % 2 == 0) continue;
 *          printf("%d", i);
 *      }
 *
 * 一句话：**for 的更新在头部，continue 杀不掉；while 的更新在体内，continue 会跳过它。**
 *
 * ====================== 七、常见坑 ======================
 *  1. 忘了更新循环变量                while (i < 10) { printf(...); }  → 死循环
 *  2. continue 跳过了更新             见第六节
 *  3. while 后面多写分号              while (i < 10);  循环体是空语句
 *  4. do-while 末尾漏分号             } while (x < 10)  编译报错
 *  5. 条件里用赋值而不是比较          while (x = 0) 恒假、while (x = 1) 恒真
 *  6. 浮点数做条件                    while (d != 1.0) 可能永远等不到
 *  7. 无符号变量倒序                  while (u >= 0) 恒真
 *  8. 循环变量没初始化                int i; while (i < 5) → 未定义行为
 *  9. 条件里放有副作用的调用          while (next() > 0 && next() > 0) 一轮调用两次
 * 10. 在条件里读输入却忘了判 EOF      while (scanf(...)) 出错时会死循环
 *
 * ====================== 八、for / while / do-while 怎么选 ======================
 *
 *      场景                                 选谁
 *      ------------------------------------ -----------------
 *      遍历数组、跑固定 n 次                  for
 *      有明确计数器、需要步长                 for
 *      "条件成立就一直做"，次数未知           while
 *      读输入 / 读文件到结束                  while
 *      至少要执行一次（菜单、重试）           do-while
 *      无限循环 + break 退出                  for(;;) 或 while(1)
 *
 * 三者都能互相改写，选语义最贴合的那个，代码自然就短。
 *
 * ====================== 九、实践建议 ======================
 *  - 写 while 前先回答三问：初值是什么？谁让它变？什么条件下停？
 *  - 能写成 for 的（有计数器）就写 for，更新不容易漏
 *  - 循环体里尽量少用 continue，非要用就把更新放在它前面
 *  - 输入驱动一定要判返回值/EOF，不要靠哨兵值约定
 *  - 死循环不可怕，while (1) + break 是合法且常用的写法，但要保证有出口
 *  - 调试死循环：先加一句 printf 打印循环变量，看它卡在哪个值
 */

#include <stdio.h>

/* 辗转相除求最大公约数：while 的经典用法 */
static int gcd(int a, int b)
{
    while (b != 0) {
        int t = b;
        b = a % b;
        a = t;
    }
    return a;
}

/* 拆数字：把一个整数的各位逆序打印出来 */
static void digits_reversed(int n)
{
    if (n == 0) {
        printf("0");
        return;
    }
    if (n < 0) {                 /* 先处理负数，避免取模得到负余数 */
        printf("-");
        n = -n;
    }
    while (n > 0) {
        printf("%d", n % 10);    /* 取最后一位 */
        n /= 10;                 /* 去掉最后一位 —— 循环能结束全靠它 */
    }
}

int main(void)
{
    /* ---------- 1. 最基本的 while ---------- */
    printf("1. 最基本的 while：先判后做\n   ");
    int i = 0;
    while (i < 5) {
        printf("%d ", i);
        i++;                     /* ★ 没有这句就是死循环 */
    }
    printf("\n   循环结束时 i=%d（第一次让条件为假的值）\n", i);

    /* ---------- 2. 条件一开始就假：一次都不执行 ---------- */
    printf("2. 条件一开始为假 → 循环体执行 0 次\n");
    int j = 100;
    while (j < 10) {
        printf("   这句不会打印\n");
        j++;
    }
    printf("   j=%d，while (j < 10) 直接跳过，不做任何事\n", j);

    /* ---------- 3. while 与 for 等价改写 ---------- */
    printf("3. 同一个任务，for 和 while 都能写\n   for  ：");
    for (int k = 0; k < 3; k++)
        printf("%d ", k);
    printf("\n   while：");
    int k2 = 0;
    while (k2 < 3) {
        printf("%d ", k2);
        k2++;
    }
    printf("\n   区别只是“更新”写在哪：for 在头部，while 在体内\n");

    /* ---------- 4. 计数与累加 ---------- */
    printf("4. 计数与累加\n");
    int n = 1, sum = 0;
    while (n <= 100) {
        sum += n;
        n++;
    }
    printf("   1+2+...+100 = %d，循环跑了 %d 次\n", sum, n - 1);

    /* ---------- 5. 条件驱动：不知道要跑几次 ---------- */
    printf("5. 条件驱动：一直除以 2，直到变成 1\n");
    int v = 100, steps = 0;
    printf("   100");
    while (v > 1) {
        v /= 2;
        steps++;
        printf(" → %d", v);
    }
    printf("\n   共除了 %d 次（次数事先算不出来，这正是 while 的用处）\n", steps);

    /* ---------- 6. 拆数字：n % 10 取位，n /= 10 推进 ---------- */
    printf("6. 逐位拆数字（逆序输出）\n");
    int d1 = 2025, d2 = -408;
    printf("   %d → ", d1);
    digits_reversed(d1);
    printf("\n   %d → ", d2);
    digits_reversed(d2);
    printf("\n   能结束的关键：每轮 n /= 10 都在变小\n");

    /* ---------- 7. 辗转相除求 gcd ---------- */
    printf("7. 辗转相除求最大公约数：while (b != 0)\n");
    printf("   gcd(12, 18)  = %d\n", gcd(12, 18));
    printf("   gcd(1071, 462) = %d\n", gcd(1071, 462));
    printf("   每轮把 (a, b) 变成 (b, a %% b)，b 变 0 就停\n");

    /* ---------- 8. 哨兵值：读到约定的值就停 ---------- */
    printf("8. 哨兵值循环：读到 -1 表示结束\n");
    int data[9] = {5, 8, 12, -1, 99, 7, -1, 3, 4};
    int idx = 0, total = 0, count = 0;
    while (idx < 9 && data[idx] != -1) {
        total += data[idx];
        count++;
        idx++;
    }
    printf("   读到哨兵 -1 停下：共 %d 个数，和 = %d\n", count, total);
    printf("   注意条件里要先判下标 < 9，否则可能越界\n");

    /* ---------- 9. 输入驱动：用 scanf 的返回值判断 ---------- */
    printf("9. 输入驱动：靠 scanf 的返回值决定停不停\n");
    const char *text = "12 34 56";        /* 模拟输入流 */
    int pos = 0, used = 0, val = 0, tsum = 0, tcnt = 0;
    while (sscanf(text + pos, "%d%n", &val, &used) == 1) {
        tsum += val;
        tcnt++;
        pos += used;                      /* 手动往后挪 */
    }
    printf("   从 \"%s\" 里读到 %d 个数，和 = %d\n", text, tcnt, tsum);
    printf("   真实代码写法：while (scanf(\"%%d\", &x) == 1) { ... }\n");
    printf("   ★ 判“返回值为 1”才继续，读到 EOF 或非法输入自动停\n");

    /* ---------- 10. do-while：至少执行一次 ---------- */
    printf("10. do-while：先做后判，至少一次\n");
    int tries = 0;
    int guess;
    int secret = 7;
    int inputs[3] = {3, 7, 9};            /* 模拟用户的三次输入 */
    do {
        guess = inputs[tries];
        tries++;
        printf("    第 %d 次猜：%d → %s\n", tries, guess,
               guess == secret ? "猜对了" : (guess < secret ? "小了" : "大了"));
    } while (guess != secret && tries < 3);
    printf("   猜对或次数用完才退出，循环体至少执行了 1 次\n");

    /* ---------- 11. while vs do-while：条件一开始就假 ---------- */
    printf("11. 条件一开始就假时，两者的差别\n");
    int x = 100, w = 0, dw = 0;
    while (x < 10) w++;                   /* 不执行 */
    do { dw++; } while (x < 10);          /* 执行一次 */
    printf("    while (x < 10) 执行了 %d 次，do-while 执行了 %d 次\n", w, dw);
    printf("    所以“至少要做一次”的场景（菜单、重试）用 do-while\n");

    /* ---------- 12. continue 的坑：while 里会跳过更新 ---------- */
    printf("12. 坑：while 里 continue 会跳过 i++（for 里不会）\n");
    printf("     错误写法（死循环，不演示）：\n");
    printf("        while (i < 10) { if (i %% 2 == 0) continue; i++; }\n");
    printf("     正确写法：先更新，再判断是否跳过 —— ");
    int m = 0;
    while (m < 10) {
        m++;                              /* ★ 更新放在 continue 之前 */
        if (m % 2 == 0)
            continue;
        printf("%d ", m);
    }
    printf("\n     对比例子：for (i = 0; i < 10; i++) 里 continue 不会卡死，因为 i++ 在头部\n");

    /* ---------- 13. while (1) + break ---------- */
    printf("13. 无限循环 + break：循环条件恒真，靠内部 break 退出\n");
    int counter = 0;
    while (1) {
        counter++;
        if (counter == 3) {
            printf("    计数器走到 %d，break 退出\n", counter);
            break;
        }
    }
    printf("    while (1) 是合法写法，但一定要有能到达的 break\n");

    /* ---------- 14. 小结 ---------- */
    printf("14. 小结：\n");
    printf("    while (条件) { 体 }：先判后做，可能 0 次\n");
    printf("    do { 体 } while (条件);：先做后判，至少 1 次，末尾分号别漏\n");
    printf("    次数明确用 for，条件/输入驱动用 while\n");
    printf("    三问必答：初值是谁、谁让它变、什么条件下停\n");
    printf("    ★ while 里的 continue 会跳过更新 → 死循环；for 不会\n");
    printf("    while (1) + break 是合法写法，但要保证有出口\n");

    return 0;
}

