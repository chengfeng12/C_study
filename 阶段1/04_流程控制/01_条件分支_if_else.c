/*
 * 01_条件分支_if_else.c —— 阶段1 / 第 04 课 / 第 01 个文件：条件分支 if / else
 *
 * 编译：gcc 01_条件分支_if_else.c -o if_demo
 * 运行：./if_demo
 *
 * 编译时会看到 1 条警告 -Wdangling-else（悬空 else），
 * 是第 5 节"坑 3"故意留的，不是错误，程序能正常编译运行。
 *
 * ====================== 一、为什么需要分支 ======================
 * 到上一课为止，程序都是从上到下一条道走到黑。真实程序必须"看情况":
 *
 *      温度 > 30      → 开空调
 *      密码正确        → 进入系统
 *      余额 < 金额     → 提示不足
 *
 * 这种"满足条件才执行 / 二选一 / 多选一"的结构叫**分支（选择）结构**，
 * C 里就三样东西：if、if-else、switch（switch 下一个文件讲）。
 *
 * ====================== 二、if 的三种形态 ======================
 *
 * 形态 1：单分支 —— 满足就做，不满足跳过
 *
 *      if (条件)
 *          语句;
 *
 *      if (age >= 18)
 *          printf("成年\n");
 *
 * 形态 2：双分支 —— 二选一，必走其中一条
 *
 *      if (条件)
 *          语句1;
 *      else
 *          语句2;
 *
 * 形态 3：多分支 —— 从上往下依次判断，命中一个就跳出整条链
 *
 *      if (条件1)      语句1;
 *      else if (条件2)  语句2;
 *      else if (条件3)  语句3;
 *      else            兜底;
 *
 * ★ 关键：else 一定和**最近的那个还没配对的 if** 配对，
 *   不存在"else if 是特殊语法"这回事——它就是 else 后面接一个新的 if。
 *
 * ====================== 三、"条件"到底是什么 ======================
 * 括号里放的是**任意表达式**，C 的判定规则只有一条：
 *
 *      结果 == 0        →  假（不执行）
 *      结果 != 0        →  真（执行）
 *
 * 所以下面这些都是"真"：if (1)、if (-1)、if (0.1)、if ('a')、if (p)
 * 下面这些是"假"：    if (0)、if (0.0)、if ('\0')、if (NULL)
 *
 * 注意：C 没有专门的"布尔"要求。C99 之前连 bool 都没有，
 *       C99 起 <stdbool.h> 提供 true/false，本质还是 1 和 0。
 *
 * 条件一般由三种运算符拼出来（上一课都学过）：
 *      比较：  ==  !=  >  <  >=  <=
 *      逻辑：  &&（并且）  ||（或者）  !（取反）
 *      算术/位运算结果也可以直接用：if (n & 1) 判断奇偶
 *
 * ====================== 四、书写风格约定 ======================
 * 推荐（也是本书全篇的风格）：
 *
 *      if (x > 0) {
 *          ...;
 *      } else {
 *          ...;
 *      }
 *
 * 要点：
 *      1) 即使只有一条语句，也建议加花括号 { }，以后加语句不会出事
 *      2) 左括号跟 if 之间留空格，和函数调用 if(x) 区分开（if 不是函数）
 *      3) else 另起一行或跟在 } 后面，全篇统一就行
 *      4) 嵌套超过 3 层，改成提前 return 或抽函数
 *
 * ====================== 五、常见坑（重点看） ======================
 *
 * 坑 1：if 后面多了个分号 —— 条件成立时执行的是"空语句"
 *      if (x > 0);
 *          printf("正数\n");        // 这句永远执行！和 if 没关系
 *
 * 坑 2：少写花括号，多余的语句掉到 if 外面
 *      if (x > 0)
 *          printf("正数\n");
 *          x = 0;                   // 缩进骗人，这句永远执行
 *
 * 坑 3：悬空 else（dangling else）—— else 配给最近的那个 if
 *      if (a)
 *          if (b)
 *              printf("ab\n");
 *      else                          // ← 配给里层的 if(b)，不是 if(a)！
 *          printf("not b\n");
 *      想让它配外层，给里层加花括号：
 *      if (a) { if (b) ... } else ...
 *
 * 坑 4：把 == 写成 =
 *      if (x = 0)                    // 赋值表达式结果是 0 → 永远为假
 *      if (x = 1)                    // 永远为真，x 还被改成 1
 *      防呆写法：if (0 == x)          // 少写一个 = 会直接编译报错
 *      实际建议：打开 -Wall，编译器会用 -Wparentheses 提醒你
 *
 * 坑 5：用 == 比较浮点数
 *      0.1 + 0.2 == 0.3 的结果是**假**，因为二进制存不下 0.1
 *      正确做法：判断差值足够小
 *      if (fabs(a - b) < 1e-9)
 *      或者用整数（把"元"换成"分"来算）
 *
 * 坑 6：多分支顺序写反
 *      if (score >= 60)  "及格"
 *      else if (score >= 90) "优秀"      // 永远轮不到，95 也会被判"及格"
 *      区间判断一定按范围**从窄到宽**（或从宽到窄）排好顺序
 *
 * 坑 7：在 if 里做"有副作用"的比较
 *      if (n++ > 0)                  // 能跑，但没人看得懂 n 最后是多少
 *
 * 坑 8：忘了浮点/整数转换
 *      if (1 / 2 == 0)               // 整数除法，1/2 是 0，条件为真
 *      if (1.0 / 2 == 0.5)           // 要小数就写成浮点
 *
 * ====================== 六、实践建议 ======================
 *  - 条件写得"正向"一点：if (ok) 比 if (!not_ok) 好读
 *  - 复杂条件拆成有名字的变量：
 *        int can_vote = age >= 18 && has_id;
 *        if (can_vote) ...
 *  - 边界值一定要测：== 边界、比边界小 1、比边界大 1
 *  - 多个区间用 else if，等值判断用 switch（下一个文件）
 *  - 函数入口先做"参数不合法就 return"，能干掉一大半嵌套
 *  - 编译一定开 -Wall -Wextra，坑 1~4 编译器基本都能帮你看出来
 */

#include <stdio.h>

/* 多分支的典型用法：按分数返回等级（区间从高到低排） */
static char grade(int score)
{
    if (score >= 90)
        return 'A';
    else if (score >= 80)
        return 'B';
    else if (score >= 60)
        return 'C';
    else
        return 'D';
}

int main(void)
{
    /* ---------- 1. 单分支：满足才做 ---------- */
    int age = 20;
    printf("1. 单分支 if(条件)：满足才执行，不满足直接跳过\n");
    if (age >= 18)
        printf("   age=%d，已成年，可以投票\n", age);

    int age2 = 15;
    if (age2 >= 18)
        printf("   age2=%d，已成年\n", age2);      /* 不会执行 */
    printf("   age2=%d，不满足条件，if 体内的语句被跳过\n", age2);

    /* ---------- 2. 双分支：if - else 二选一 ---------- */
    printf("2. 双分支 if - else：必走其中一条\n");
    int n = 7;
    if (n % 2 == 0)
        printf("   n=%d 是偶数\n", n);
    else
        printf("   n=%d 是奇数\n", n);

    int x = -3;
    if (x < 0)
        printf("   x=%d 是负数，绝对值 = %d\n", x, -x);
    else
        printf("   x=%d 是非负数，绝对值 = %d\n", x, x);

    /* ---------- 3. 多分支：else if 链 ---------- */
    printf("3. 多分支 else if：从上往下判断，命中一个就跳出整条链\n");
    int scores[4] = {95, 85, 75, 50};
    for (int k = 0; k < 4; k++)
        printf("   %d 分 → 等级 %c\n", scores[k], grade(scores[k]));
    printf("   注意：else 后面接新 if，写法是 else if，不是 elseif\n");

    /* ---------- 4. 条件"非 0 即真" ---------- */
    printf("4. 条件只看“是不是 0”：非 0 为真，0 为假\n");
    if (1)     printf("   if (1)      → 真\n");
    if (-1)    printf("   if (-1)     → 真（负数也算真！）\n");
    double dz = 0.1;
    if (dz)    printf("   if (0.1)    → 真\n");
    if ('a')   printf("   if ('a')    → 真（字符 'a' 是 97）\n");
    if (0)     printf("   if (0)      → 这句不会打印\n");
    if (0.0)   printf("   if (0.0)    → 这句也不会打印\n");
    printf("   所以 if (x != 0) 和 if (x) 等价；判空写 if (p) 或 if (p != NULL)\n");

    /* ---------- 5. 坑 1：if 后面多了分号 ---------- */
    int m = 1;
    printf("5. 坑：if 后面多写一个分号，条件成立时执行的是空语句\n");
    if (m == 1)
        ;                                    /* ← 这个分号就是 if 的全部内容 */
    printf("   m=%d 条件成立，但 if 的语句体就是这个分号，所以什么也没做\n", m);
    if (m == 1) {
        printf("   正确写法：条件成立时执行花括号里的语句\n");
    }

    /* ---------- 6. 坑 2：少写花括号，多余语句掉到外面 ---------- */
    int q = 10;
    printf("6. 坑：少写花括号，缩进骗人\n");
    if (q > 100)
        printf("   q > 100，条件为假，这一句被跳过\n");
    printf("   这一句缩进看着像在 if 里，其实永远执行（q=%d）\n", q);
    printf("   结论：即使只有一条语句，也加上 { }\n");

    /* ---------- 7. 坑 3：悬空 else 配给最近的 if ---------- */
    int a = 5, b = 0;
    printf("7. 坑：悬空 else，else 只配最近的那个 if\n");
    if (a > 0)
        if (b > 0)
            printf("   a>0 且 b>0\n");
    else
        printf("   a=%d、b=%d → 走到 else：它配的是里层 if (b>0)\n", a, b);
    printf("   想让 else 配外层 if (a>0)，就给里层加花括号\n");
    if (a > 0) {
        if (b > 0)
            printf("   a>0 且 b>0\n");
    } else {
        printf("   现在 else 才配外层 if (a>0)\n");
    }

    /* ---------- 8. 坑 4：== 写成 = ---------- */
    int v = 3;
    printf("8. 坑：把 == 写成 =\n");
    if ((v = 0))                          /* 加一层括号只为消掉编译警告 */
        printf("   if (v = 0) 不会执行\n");
    printf("   if (v = 0)：赋值结果是 0，条件为假，v 也被改成了 %d\n", v);
    printf("   防呆写法：if (0 == v)，少写一个 = 会直接编译报错\n");

    /* ---------- 9. 坑 5：浮点数不能直接用 == ---------- */
    double d = 0.1 + 0.2;
    printf("9. 坑：浮点数别用 == 比较\n");
    printf("   0.1 + 0.2 = %.17f\n", d);
    printf("   0.1 + 0.2 == 0.3 的结果为 %s（二进制存不下 0.1）\n",
           (d == 0.3) ? "真" : "假");
    if (d > 0.3 - 1e-9 && d < 0.3 + 1e-9)
        printf("   正确做法：判断差值小于误差 |a-b| < 1e-9 → 认为是 0.3\n");

    /* ---------- 10. 坑 6：多分支顺序写反 ---------- */
    int s = 95;
    printf("10. 坑：区间判断顺序写反，95 分被误判\n");
    if (s >= 60)
        printf("    先判 >=60 → 打印“及格”，后面的 else if 永远轮不到\n");
    else if (s >= 90)
        printf("    优秀（这句对 %d 分永远不会执行）\n", s);
    printf("    正确顺序：先判 >=90，再 >=80，再 >=60（从窄到宽）\n");

    /* ---------- 11. 组合条件与提前返回 ---------- */
    printf("11. 组合条件：&& 并且、|| 或者、! 取反\n");
    int age3 = 20, has_id = 1;
    if (age3 >= 18 && has_id)
        printf("    age>=18 且 有身份证 → 可以入场\n");
    if (age3 < 18 || !has_id)
        printf("    这句不会打印\n");
    printf("    复杂条件先拆成有名字的变量，可读性更好\n");

    /* ---------- 12. 实际用法：输入校验 / 边界值 ---------- */
    printf("12. 实际用法：先挡掉非法值，再处理正常逻辑\n");
    int ts[5] = {-1, 0, 25, 100, 101};
    for (int k = 0; k < 5; k++) {
        int t = ts[k];
        if (t < 0 || t > 100) {
            printf("    t=%-3d → 非法温度，忽略\n", t);
        } else if (t >= 30) {
            printf("    t=%-3d → 开空调\n", t);
        } else {
            printf("    t=%-3d → 温度正常\n", t);
        }
    }

    /* ---------- 13. 小结 ---------- */
    printf("13. 小结：\n");
    printf("    if (条件) 语句;                  单分支：满足才做\n");
    printf("    if (条件) A; else B;             双分支：二选一\n");
    printf("    if / else if / else              多分支：命中即跳出\n");
    printf("    条件非 0 即真，0 才为假\n");
    printf("    始终加花括号；别在 if 后加分号；== 别写成 =；\n");
    printf("    浮点别用 ==；区间判断注意顺序；开 -Wall 让编译器帮你查\n");

    return 0;
}

