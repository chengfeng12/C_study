/*
 * 05_do_while循环.c —— 阶段1 / 第 04 课 / 第 05 个文件：do-while 循环
 *
 * 编译：gcc 05_do_while循环.c -o bin/05_do_while循环
 * 运行：./bin/05_do_while循环
 *
 * 本文件能干净编译（-Wall -Wextra 零警告）。
 * 第 7 节"体内变量不能用于条件"只用注释演示错误写法（那样写编译不过）。
 *
 * ====================== 一、do-while 是什么 ======================
 * while 是"先判后做"，条件不成立就一次都不做。
 * do-while 反过来：**先把循环体做一遍，再去判断要不要继续**。
 *
 *      do {
 *          循环体;
 *      } while (条件);        ← ★ 末尾这个分号是语法的一部分，漏了直接编译报错
 *
 * 流程：
 *      1) 执行循环体（无条件下先做一次）
 *      2) 判断条件
 *      3) 为真 → 回到 1)；为假 → 结束
 *
 *      ┌──────────────┐
 *      │   循环体      │ ←──┐
 *      └──────┬───────┘    │
 *      ┌──────↓───────┐    │
 *      │  判断条件     │──真┘
 *      └──────┬───────┘
 *            假
 *          结束
 *
 * 一句话记住：**do-while = 至少执行一次的循环。**
 *
 * ====================== 二、和 while 的唯一区别 ======================
 *
 *      int x = 100;
 *
 *      while (x < 10) { ... }        // 判断在前 → 0 次
 *      do { ... } while (x < 10);    // 判断在后 → 1 次
 *
 * 注意区别只在"第一次"：
 *      第一次之后两者完全一样，都是"条件为真就继续"。
 *      所以循环次数 ≥ 1 时，两种写法结果相同，选可读性好的那个。
 *
 * ====================== 三、什么时候非它不可：四个真实场景 ======================
 *
 *  (1) 菜单：必须先显示一次菜单，用户才可能选
 *          int choice;
 *          do {
 *              show_menu();
 *              choice = read_choice();
 *          } while (choice != 0);
 *      用 while 写就得在循环外再显示一次菜单，重复代码。
 *
 *  (2) 输入校验：先收数据，再判断合法，不合法就重来
 *          do {
 *              printf("请输入 1~100：");
 *              scanf("%d", &v);
 *          } while (v < 1 || v > 100);
 *      "至少要输入一次"，语义上就是 do-while。
 *
 *  (3) 重试：最多试 N 次
 *          int tries = 0;
 *          do {
 *              ok = try_connect();
 *              tries++;
 *          } while (!ok && tries < 3);
 *
 *  (4) 宏里包多条语句：do { ... } while (0) 惯用法（见第八节，非常重要）
 *
 * 反过来说：如果这件事"有可能一次都不做"，就别用 do-while，
 * 否则会莫名其妙多执行一次 —— 这是最常见的语义误用。
 *
 * ====================== 四、条件在循环体之后求值 ======================
 * 因为判断写在最后，所以条件里能用的变量，必须在 do 之前就已经存在：
 *
 *      do {
 *          int x = read();              // x 只活在花括号里
 *      } while (x > 0);                 // ✗ 编译报错：x 未声明
 *
 * 正确写法是把变量提到外面：
 *
 *      int x;
 *      do {
 *          x = read();
 *      } while (x > 0);                 // ✓
 *
 * 顺带一句：do-while 的循环体也是一个块作用域，体内声明的变量出了 } 就销毁。
 *
 * ====================== 五、break 与 continue ======================
 *
 *      break     立即结束整个 do-while
 *      continue  跳过本轮剩余语句，**直接去做条件判断**
 *
 * ★ 注意 continue 的去向：
 *      for        → 跳到"更新"（i++），所以安全
 *      while      → 跳到"条件"，更新在体内会被跳过 → 可能死循环
 *      do-while   → 跳到"条件"，和 while 一样，更新若在 continue 之后就危险
 *
 * 安全习惯：循环变量的更新永远写在 continue 之前（或改用 for）。
 *
 * ====================== 六、do-while 和 while 怎么互转 ======================
 * 任何 do-while 都能改写成 while，办法是"把第一轮提到循环外"：
 *
 *      do { 体 } while (C);
 *
 *      等价于：
 *
 *      体;                    // 先做一次
 *      while (C) { 体 }
 *
 * 反过来，while 想保证"至少一次"，就先在外面补一遍第一轮的代码。
 * 实际写的时候不用纠结等价性，**看语义选更自然的那个**。
 *
 * ====================== 七、常见坑 ======================
 *  1. 末尾漏分号                } while (x < 10)    → 编译报错
 *  2. 以为能省变量初始化        条件里的变量必须在 do 之前声明并初始化
 *  3. 条件写到前面              语法规定 while 在后面，写成 while (C) do { } 不合法
 *  4. 给"可能 0 次"的逻辑用 do-while  → 会多执行一次
 *  5. 条件里用体内的局部变量    作用域已结束，编译报错
 *  6. 体内忘更新                条件恒真 → 死循环
 *  7. 条件恒真又没 break        死循环
 *  8. 用 do-while 做数组遍历    while 里还得手动维护下标，可读性差，用 for
 *  9. 嵌套时 while 配对看错     do { do { } while (A); } while (B); 缩进要清楚
 * 10. 分号后多写语句           while (C); 后面那句只在循环结束后执行
 *
 * ====================== 八、do { ... } while (0) 惯用法 ======================
 * 这是 C 里非常重要的宏技巧，和"循环"其实没关系，纯粹借用 do-while 的语法：
 *
 *      #define LOG_AND_RUN(cmd) do {      \
 *          printf("[开始]\n");             \
 *          cmd;                            \
 *          printf("[结束]\n");             \
 *      } while (0)
 *
 * 为什么必须包成 do-while(0)：
 *
 *      if (ok) LOG_AND_RUN(f()); else g();     ✓ 展开后语法正确
 *
 *      // 若宏只写成 { ... }：
 *      if (ok) { ... }; else g();             ✗ 多出的分号让 else 悬空 → 编译报错
 *
 * 所以：**多语句宏一律用 do { ... } while (0) 包起来**，
 * 调用时末尾加分号，行为和普通函数调用一致，能在 if/else 里安全使用。
 * （while (0) 保证只执行一次，不做第二次判断。）
 *
 * ====================== 九、选择表 ======================
 *
 *      情形                                  用谁
 *      ------------------------------------  --------------
 *      可能一次都不执行                        while / for
 *      至少执行一次（菜单、校验、重试）        do-while
 *      次数明确                                for
 *      多语句宏                                do { } while (0)
 *      无限循环 + break                        while (1) / for (;;)
 *
 * ====================== 十、实践建议 ======================
 *  - 写 do-while 先确认"第一轮无论如何都该做"，否则就用 while
 *  - 循环变量的声明和初始化放在 do 之前
 *  - 更新语句放在 continue 之前
 *  - 菜单/重试这类交互，配 switch 用起来最顺（见 02_多分支_switch_case.c）
 *  - 多语句宏一律 do { } while (0)
 *  - 死循环难排查时，在循环体开头打印条件变量
 */

#include <stdio.h>

/* 第八章要讲的宏：多语句必须用 do { } while (0) 包起来 */
#define LOG_AND_RUN(cmd) do {           \
    printf("   [宏] 准备执行\n");        \
    cmd;                                \
    printf("   [宏] 执行完毕\n");        \
} while (0)

/* 模拟"从设备读一个数"，前几次返回非法值 */
static int fake_read(int round)
{
    static const int seq[4] = {0, 150, -3, 42};
    return seq[round % 4];
}

int main(void)
{
    /* ---------- 1. 条件一开始就假：do-while 仍会执行一次 ---------- */
    printf("1. 同一个条件，while 与 do-while 的差别\n");
    int x = 100, w = 0, dw = 0;
    while (x < 10)
        w++;
    do {
        dw++;
    } while (x < 10);
    printf("   while  (x < 10) 执行 %d 次\n", w);
    printf("   do-while(x < 10) 执行 %d 次（先做后判，至少一次）\n", dw);

    /* ---------- 2. 执行顺序：先体后条件 ---------- */
    printf("2. 执行顺序：先执行循环体，再判断\n");
    int i = 1;
    do {
        printf("   第 %d 轮：i=%d\n", i, i);
        i++;
    } while (i <= 3);
    printf("   退出时 i=%d（第 3 轮做完后 i 变成 4，条件为假）\n", i);

    /* ---------- 3. 菜单驱动：最典型的 do-while ---------- */
    printf("3. 菜单驱动：先显示菜单，再读选择\n");
    int seq_menu[3] = {2, 1, 0};      /* 模拟用户的三次选择，0 表示退出 */
    int mi = 0, choice;
    do {
        printf("   菜单：1-查看 2-设置 0-退出 > ");
        choice = seq_menu[mi++];
        printf("%d\n", choice);
        switch (choice) {
        case 1:
            printf("      → 执行查看\n");
            break;
        case 2:
            printf("      → 执行设置\n");
            break;
        case 0:
            printf("      → 退出\n");
            break;
        default:
            printf("      → 非法选项，请重新选择\n");
            break;
        }
    } while (choice != 0);
    printf("   选到 0 才退出，菜单至少显示过一次\n");

    /* ---------- 4. 输入校验：不合法就重来 ---------- */
    printf("4. 输入校验：先收数据，再判断是否合法\n");
    int v = 0, round = 0;
    do {
        v = fake_read(round);
        printf("   读到 %4d → %s\n", v,
               (v >= 1 && v <= 100) ? "合法" : "非法，重试");
        round++;
    } while (v < 1 || v > 100);
    printf("   最终采用 %d（前几次非法值都被挡回去了）\n", v);

    /* ---------- 5. 重试最多 N 次 ---------- */
    printf("5. 重试：最多试 3 次，成功就提前退出\n");
    int secret = 8888;
    int tries_in[4] = {1111, 2222, 8888, 0000};
    int t = 0, ok = 0;
    do {
        int code = tries_in[t];
        t++;
        printf("   第 %d 次尝试：%04d → %s\n", t, code,
               code == secret ? "正确" : "错误");
        if (code == secret) {
            ok = 1;
            break;                    /* 成功就跳出，不再重试 */
        }
    } while (t < 3);
    printf("   %s，共尝试 %d 次\n", ok ? "登录成功" : "失败次数过多", t);

    /* ---------- 6. continue 在 do-while 里的去向 ---------- */
    printf("6. continue 会跳到“条件判断”，所以更新要写在它前面\n");
    printf("   打印 1~9 中的奇数：");
    int c = 0;
    do {
        c++;                          /* ★ 更新在 continue 之前才安全 */
        if (c % 2 == 0)
            continue;
        printf("%d ", c);
    } while (c < 9);
    printf("\n   若把 c++ 写到 continue 后面，c 永远不增 → 死循环\n");

    /* ---------- 7. 体内声明的变量不能用于条件 ---------- */
    printf("7. 条件里能用的变量，必须在 do 之前声明\n");
    /* 错误写法（编译不过）：
     *     do { int y = fake_read(...); } while (y > 0);
     * 因为 y 活在花括号里，条件在花括号外面求值。
     */
    int y;
    do {
        y = fake_read(round++);
    } while (y <= 0);
    printf("   y 提到外面声明后可用：最后一次读到 y=%d\n", y);

    /* ---------- 8. do-while 与 while 互相改写 ---------- */
    printf("8. do-while 可以改写成“先做一次 + while”\n   do-while：");
    int q = 1;
    do {
        printf("%d ", q);
        q++;
    } while (q <= 3);
    printf("\n   等价的 while：");
    int q2 = 1;
    printf("%d ", q2);                /* 把第一轮提到循环外 */
    q2++;
    while (q2 <= 3) {
        printf("%d ", q2);
        q2++;
    }
    printf("\n");

    /* ---------- 9. 多语句宏：do { } while (0) ---------- */
    printf("9. 多语句宏用 do { } while (0) 包起来，才能在 if/else 里安全使用\n");
    int flag = 1;
    if (flag)
        LOG_AND_RUN(printf("   任务执行中\n"));
    else
        printf("   跳过\n");
    printf("   宏展开后是 do { ... } while (0)，整体算一条语句\n");

    /* ---------- 10. 嵌套 do-while ---------- */
    printf("10. 嵌套 do-while：外层行、内层列\n");
    int r = 1;
    do {
        int col = 1;
        printf("   ");
        do {
            printf("%d ", r * col);
            col++;
        } while (col <= 3);
        printf("\n");
        r++;
    } while (r <= 2);
    printf("   内层每次都要重新初始化 col=1，否则第二轮就不会跑\n");

    /* ---------- 11. 条件恒真时靠 break 退出 ---------- */
    printf("11. 条件恒真（do {} while (1)）必须靠 break 退出\n");
    int guard = 0;
    do {
        guard++;
        printf("   第 %d 次检查\n", guard);
        if (guard == 3) {
            printf("   → 命中退出条件，break\n");
            break;
        }
    } while (1);
    printf("   while (1) 加 break 是合法写法，但 break 必须真的能到达\n");

    /* ---------- 12. 小结 ---------- */
    printf("12. 小结：\n");
    printf("    do { 体 } while (条件);   ★ 末尾分号不能漏\n");
    printf("    先做后判，至少执行一次；第一次之后与 while 相同\n");
    printf("    适合菜单、输入校验、重试这类“至少做一次”的交互\n");
    printf("    条件里用的变量要在 do 之前声明并初始化\n");
    printf("    continue 跳到条件判断，更新语句要写在它前面\n");
    printf("    多语句宏一律 do { ... } while (0)\n");

    return 0;
}

