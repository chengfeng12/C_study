/*
 * 07_goto.c —— 阶段1 / 第 04 课 / 第 07 个文件：goto 与标签（多层跳出、统一清理）
 *
 * 编译：gcc 07_goto.c -o bin/07_goto
 * 运行：./bin/07_goto
 *
 * 本文件能干净编译（-Wall -Wextra 零警告）。
 * 第 6 节演示"跳进块内会跳过初始化"，编译器**不会**给任何警告 —— 这正是要警惕的地方；
 * 示例里只说明情况，不去读那个未初始化的变量（读了就是未定义行为）。
 * 第 7 节用 goto 实现循环，是**反例**，只为说明"能跑不等于该写"。
 *
 * ====================== 一、语法 ======================
 *
 * 跳转：
 *      goto 标号;
 *
 * 标号（标签）的定义，就是"标号 + 冒号"，贴在任意一条语句前面：
 *
 *      标号:
 *          语句;
 *
 * 例子：
 *      int n = 0;
 *      if (n == 0)
 *          goto skip;          // 跳到下面
 *      printf("这行被跳过\n");
 *  skip:
 *      printf("从这里继续\n");
 *
 * 关于标号的几条硬规则（很多教材不写，但必须知道）：
 *
 *  1) 标号是**普通标识符**，但它和变量名属于两个独立命名空间，
 *     所以 `int done;` 和 `done:` 可以同时存在于一个函数里（虽然别这么干）。
 *
 *  2) 标号的可见范围是**整个函数**，与花括号无关。
 *     在 if 块里定义的标号，块外面也能 goto 过去，反之亦然。
 *
 *  3) 同一个函数里，标号**不能重名**；不同函数里可以重名（各管各的）。
 *
 *  4) 不能跨函数跳转：goto 只能跳到**本函数内**的标号。
 *
 *  5) 标号后面必须跟一条**语句**。C23 之前声明不算语句，所以
 *     `done: int x = 1;` 是不合法的，要写成 `done: ;` 或后面接一条语句。
 *     （和 switch 的 case 里定义变量要加 { } 是同一条规则）
 *
 *  6) `case` / `default` 标签不是普通标号，**不能**作为 goto 的目标。
 *
 * ====================== 二、执行语义 ======================
 * goto 是**无条件跳转**：
 *      - 不看任何条件，直接跳
 *      - 跳过去之后不会回来（不像函数调用没有返回地址）
 *      - 既能向前跳（跳过一段代码），也能向后跳（等于把代码再跑一遍）
 *
 * "向后跳"就是循环的原理，所以 goto 在语言能力上可以替代 for/while ——
 * 但**不该这么用**（见第五节反例）。
 *
 * ====================== 三、能跳和不能跳 ======================
 *
 *      ✓ 从块内跳到块外（跳出 if/for/while/switch 的任意层）
 *      ✓ 跳到同一函数的后面（向前跳，最常见的用法）
 *      ✓ 跳到同一函数的后面再回来（向后跳，语法合法但别用）
 *      ✗ 跳到别的函数里
 *      ✗ 跳到 case / default 标签上（它们不是普通标号）
 *      ✗ 跳进变长数组（VLA）的作用域
 *
 *  ★ 灰色地带：跳进一个块内部
 *
 *      int cond = 1;
 *      if (cond) goto inside;
 *      {
 *          int y = 99;        // ← 这一行被跳过了
 *      inside:
 *          printf("%d", y);   // y 从没被初始化，这里是未定义行为
 *      }
 *
 *    语法上**能编译**（C 允许），但值不确定，是完全不可预期的 bug。
 *    C++ 直接禁止这种写法，C 只是"不拦你"。所以：
 *
 *      规则：goto 只用来**往外跳**，绝不要往里跳。
 *
 *  ★ 禁止跳进 VLA 作用域（C99 起）：
 *
 *      int n = 10;
 *      goto skip;
 *      int vla[n];                // 变长数组
 *      skip:                      // ✗ 约束违规：跳进了 vla 的作用域
 *
 *    因为 VLA 的长度要在运行期算，跳过了就没人分配它的空间。
 *
 * ====================== 四、被广泛接受的两个用法 ======================
 *
 *  (1) 多层跳出（3 层以上才值得）
 *
 *          for (i...) for (j...) for (k...)
 *              if (hit(i, j, k)) goto found;
 *          return 0;              // 没找到
 *      found:
 *          return 1;
 *
 *      2 层通常用 flag 或抽函数更清楚；3 层以上 flag 会层层传递，goto 反而最干净。
 *
 *  (2) 统一清理（cleanup 模式）—— goto 最有价值的用法
 *
 *          int f(void)
 *          {
 *              int rc = 0;
 *              A *a = NULL;
 *              B *b = NULL;
 *
 *              a = open_a();
 *              if (!a) { rc = -1; goto out; }
 *
 *              b = open_b();
 *              if (!b) { rc = -2; goto out; }     // 只清理已申请的 a
 *
 *              rc = do_work(a, b);
 *          out:
 *              if (b) close_b(b);                 // 逆序释放
 *              if (a) close_a(a);
 *              return rc;
 *          }
 *
 *      好处：申请 5 层资源、失败有 5 种可能时，释放代码只写一遍，
 *            而且**不会漏**（每个失败点都走同一段收尾）。
 *
 *      命名惯例（Linux 内核风格）：
 *          out:        总出口
 *          err_free:   释放资源后返回错误
 *          err:        直接返回错误
 *      按"越靠后越收尾"的顺序排列，落在哪个标签就做哪段清理。
 *
 *      替代方案：每个失败分支各写一次 return（也就是"早返回"）。
 *      步骤少、清理短时，早返回更直观；步骤多、清理长时，goto 更省。
 *      两种都能写对，关键是**全文件统一风格**。
 *
 * ====================== 五、反例：这些用法会挨骂 ======================
 *  1. 用 goto 实现循环
 *          i = 0;
 *      loop:
 *          if (i >= 3) goto done;
 *          printf("%d", i); i++;
 *          goto loop;
 *      done:
 *      能跑，但 while 一行就能表达，goto 版只是给人添麻烦。
 *
 *  2. 单层跳出用 goto
 *          循环里直接 break 就行，goto 是杀鸡用牛刀。
 *
 *  3. 往里跳（跳过初始化）          见第三节，未定义行为。
 *
 *  4. 双向乱跳，形成"面条代码"       跳转关系图一画，连作者自己都理不清。
 *
 *  5. 用 goto 代替 if/else            条件逻辑就该用 if，别用跳转模拟。
 *
 * ====================== 六、编译器和工具的态度 ======================
 *  - 定义了没用到的标号：`-Wunused-label`（-Wall 会报）
 *  - 跳过变量初始化：**默认不报**（gcc 有 -Wjump-misses-init，但不在 -Wall 里）
 *  - 跳进 VLA 作用域：编译期直接报错（约束违规）
 *  - 静态分析（clang-tidy、cppcheck）能查出部分"往里跳"的问题
 *
 * 所以：goto 相关的错误主要靠**约定和 review** 兜底，不能指望编译器提醒。
 *
 * ====================== 七、C 与 C++ 的差异（顺带一提） ======================
 *      C    跳过带初始化的变量：合法，值不确定
 *      C++  跳过带初始化的变量：**编译报错**（即使没有非平凡的构造）
 *
 * 本仓库是 C 代码，所以上面那类代码"能编过"，但这不代表它是对的。
 *
 * ====================== 八、goto / break / return 怎么选 ======================
 *
 *      需求                                     用谁
 *      ---------------------------------------  ------------------
 *      跳出当前一层循环或 switch                 break
 *      结束整个函数（正常或出错）                return
 *      跳出 2 层循环                             flag 或抽函数（简单场景）
 *      跳出 3 层以上嵌套                         goto（标号放循环外）
 *      多层资源申请失败后统一清理                goto cleanup（推荐）
 *      用跳转模拟循环 / 分支                     ✗ 都不该用
 *
 * ====================== 九、实践建议 ======================
 *  - goto 只有两个正当用途：多层跳出、统一清理；其余场景想清楚再说
 *  - 标号只写在函数末尾（清理段）或循环之后，**永远只往前跳**
 *  - 标号命名写清楚：out / err / found / done，别用 l1、l2、aaa
 *  - 清理段里按"逆序"释放：后申请的先释放
 *  - 一个函数里 goto 超过 3~5 处，说明该拆函数了
 *  - 能用 return 解决就别用 goto；能用一个 flag 解决也别用 goto
 *  - 新加 goto 时顺手在标号旁写一句"谁会跳到这里"
 */

#include <stdio.h>

/* 模拟申请资源，fail_at 指定第几步失败 */
static int acquire(const char *name, int step, int fail_at)
{
    if (step == fail_at) {
        printf("   申请 %s 失败（第 %d 步）\n", name, step);
        return 0;
    }
    printf("   申请 %s 成功\n", name);
    return 1;
}

/* 写法一：失败都汇到末尾的清理段 */
static int work_goto(int fail_step)
{
    int rc = 0;
    printf("   [goto 版] 开始，第 %d 步会失败\n", fail_step);

    if (fail_step == 1) { rc = -1; goto out; }
    if (fail_step == 2) { rc = -2; goto out; }
    if (fail_step == 3) { rc = -3; goto out; }
    printf("   [goto 版] 三步全部成功\n");

out:
    printf("   [goto 版] 收尾处理，返回 %d\n", rc);
    return rc;
}

/* 写法二：每个失败分支自己收尾（早返回） */
static int work_return(int fail_step)
{
    printf("   [return 版] 开始，第 %d 步会失败\n", fail_step);

    if (fail_step == 1) {
        printf("   [return 版] 收尾处理，返回 -1\n");
        return -1;
    }
    if (fail_step == 2) {
        printf("   [return 版] 收尾处理，返回 -2\n");
        return -2;
    }
    if (fail_step == 3) {
        printf("   [return 版] 收尾处理，返回 -3\n");
        return -3;
    }
    printf("   [return 版] 三步全部成功\n");
    printf("   [return 版] 收尾处理，返回 0\n");
    return 0;
}

int main(void)
{
    /* ---------- 1. 最简单的 goto：向前跳 ---------- */
    printf("1. 最简单的 goto：无条件向前跳\n");
    goto skip;
    printf("   这一行永远执行不到\n");
skip:
    printf("   已经跳到 skip 标号处继续执行\n");
    printf("   goto 后面那句并没被删除，只是被跳过了\n");

    /* ---------- 2. 标号是函数级的，不受花括号限制 ---------- */
    printf("2. 标号的作用域是整个函数，能跨花括号跳\n");
    if (1) {
        printf("   在 if 块里\n");
        goto outside_block;              /* 从块内跳到块外 */
    }
    printf("   这句被跳过\n");
outside_block:
    printf("   已经从 if 块里跳到块外，标号写在块外也没问题\n");

    /* ---------- 3. 三层循环一次跳出 ---------- */
    printf("3. 三层循环用 goto 一次跳出\n");
    for (int i = 1; i <= 3; i++)
        for (int j = 1; j <= 3; j++)
            for (int k = 1; k <= 3; k++)
                if (i == 2 && j == 2 && k == 2) {
                    printf("   命中 (%d, %d, %d)，goto found\n", i, j, k);
                    goto found;
                }
found:
    printf("   三层循环全部结束，后面的组合一个都没跑\n");

    /* ---------- 4. 统一清理：多级申请 + 逆序释放 ---------- */
    printf("4. cleanup 模式：申请 A/B/C，第二步失败\n");
    int rc = 0;
    int got_a = 0, got_b = 0, got_c = 0;

    got_a = acquire("A", 1, 2);
    if (!got_a) { rc = -1; goto cleanup; }

    got_b = acquire("B", 2, 2);
    if (!got_b) { rc = -2; goto cleanup; }

    got_c = acquire("C", 3, 2);
    if (!got_c) { rc = -3; goto cleanup; }

    printf("   三步全部成功\n");

cleanup:
    if (got_c) printf("   释放 C（逆序：后申请的先释放）\n");
    if (got_b) printf("   释放 B\n");
    if (got_a) printf("   释放 A\n");
    printf("   统一返回错误码 %d，没申请到的资源不会被误释放\n", rc);

    /* ---------- 5. 同一任务的两种写法 ---------- */
    printf("5. goto 版与早返回版：都能写对，看清理代码的长短\n");
    printf("   失败在第 2 步：\n");
    int r1 = work_goto(2);
    printf("   goto 版结束，返回 %d\n", r1);
    int r2 = work_return(2);
    printf("   return 版结束，返回 %d\n", r2);
    printf("   清理只有一两句时，早返回更直观；清理有五六句时，goto 不重复\n");

    /* ---------- 6. 坑：跳进块内会跳过初始化（编译器不报警） ---------- */
    printf("6. 坑：往里跳会跳过初始化，编译器一声不吭\n");
    int cond = 1;
    if (cond)
        goto inside;                     /* 直接跳进下面的块 */
    {
        int y = 99;                      /* ← 这一行被跳过，y 从没初始化 */
    inside:
        (void)sizeof y;                  /* 只为消掉"未使用"警告，sizeof 不会真读 y */
        printf("   已经跳进块里，但 int y = 99; 这一行没有执行\n");
        printf("   此时若去读 y 就是未定义行为，而编译器不会给任何警告\n");
    }
    printf("   规则：goto 只往外跳，不要往里跳\n");

    /* ---------- 7. 反例：用 goto 实现循环 ---------- */
    printf("7. 反例：用 goto 也能循环（能跑，但别这么写）\n");
    int k = 0;
loop_again:
    if (k < 3) {
        printf("   k=%d\n", k);
        k++;
        goto loop_again;                 /* 向后跳 = 循环 */
    }
    printf("   这段等价于 while (k < 3)，但可读性差得多\n");

    /* ---------- 8. 小结 ---------- */
    printf("8. 小结：\n");
    printf("    goto 标号; 跳到本函数内的 标号: 处，可前可后，无返回\n");
    printf("    标号是函数级的、不能重名、不能跨函数、C23 前后面必须跟语句\n");
    printf("    能跳出任意层块，但往里跳会跳过初始化（未定义行为）\n");
    printf("    禁止跳进 VLA 作用域；case 标签不能当 goto 目标\n");
    printf("    正经用途只有两个：3 层以上跳出、失败统一清理（逆序释放）\n");
    printf("    默认不报警的地方最多，所以全靠约定：只往前跳、只往外跳\n");

    return 0;
}

